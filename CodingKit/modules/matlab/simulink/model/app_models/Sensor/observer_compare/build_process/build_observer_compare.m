function build_observer_compare()
%BUILD_OBSERVER_COMPARE Add a read-only observer branch to the Sensor assembly.
assert(strcmp(version('-release'),'2026b'));
gate=library.settingsLookup();assert(gate.gatePass);
module=fileparts(fileparts(mfilename('fullpath')));
for folder={'src','waveform_analysis','ref'}
    if ~isfolder(fullfile(module,folder{1})),mkdir(fullfile(module,folder{1}));end
end
addpath(fullfile(module,'parameter'),fileparts(mfilename('fullpath')));
p=observer_compare_parameters(); %#ok<NASGU>
model='SensorObserverCompare';destination=fullfile(module,'src',[model,'.slx']);
assert(~isfile(destination) && ~bdIsLoaded(model),'Rebuild in an isolated module copy.');
open_system('MotorExperiment');assert(strcmp(get_param('MotorExperiment','Dirty'),'off'));
disp(model_read('MotorExperiment','root','0'));
save_system('MotorExperiment',destination);open_system(model);
initialize_observer_compare(model);
callback=['addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));', ...
    'initialize_observer_compare(bdroot);'];
result=edit(model,'root',{struct('op','configure','target',['config:',model], ...
    'params',struct('PostLoadFcn',callback)), ...
    struct('op','create_subsystem','name','ObserverMonitor','ref','monitor', ...
    'interface',struct('inputs',{{}},'outputs',{{}}))},false,'incremental');
monitorId=createdId(result,'monitor');
inputs={'phase_voltage','ia_feedback','ib_feedback','ic_feedback','theta_reference', ...
    'omega_reference','theta_physical','omega_physical'};operations={};
for index=1:numel(inputs),operations{end+1}=b('Inport',inputs{index},struct('Port',num2str(index)));end
load_system('SlidingModeObserver');disp(model_read('SlidingModeObserver','root','0'));
smoPath=Simulink.ID.getFullName('SlidingModeObserver:1');
operations=[operations,{b('Demux','phase_channels',struct('Outputs','3')), ...
    struct('op','add_block','type','Clarke','ReferenceBlock','ClarkePark/Clarke','name','VoltageClarke','ref','voltageClarke'), ...
    struct('op','add_block','type','Clarke','ReferenceBlock','ClarkePark/Clarke','name','CurrentClarke','ref','currentClarke'), ...
    struct('op','add_block','type','SMO','ReferenceBlock',smoPath,'name','SMO','ref','smo'), ...
    b('Mux','voltage_ab',struct('Inputs','2')), ...
    b('ZeroOrderHold','VoltageSample',struct('SampleTime','timingCfg.Ts')), ...
    b('Delay','VoltageAge',struct('DelayLength','timingCfg.FeedbackTicks*experimentCfg.UseTiming', ...
    'InitialCondition','0','SampleTime','timingCfg.Ts')), ...
    b('Demux','aligned_voltage',struct('Outputs','2')), ...
    b('Terminator','VoltageZero',struct()),b('Terminator','CurrentZero',struct()), ...
    b('Constant','Direction',struct('Value','compareCfg.Direction')), ...
    b('Constant','ObserverEnable',struct('Value','compareCfg.ObserverEnable')), ...
    b('Constant','ObserverReset',struct('Value','compareCfg.ObserverReset')), ...
    b('Sum','RawAngleError',struct('Inputs','+-')), ...
    b('Trigonometry','ReferenceSin',struct('Operator','sin')),b('Trigonometry','ReferenceCos',struct('Operator','cos')), ...
    b('Trigonometry','ReferenceWrapped',struct('Operator','atan2')), ...
    b('Trigonometry','ErrorSin',struct('Operator','sin')),b('Trigonometry','ErrorCos',struct('Operator','cos')), ...
    b('Trigonometry','AngleError',struct('Operator','atan2')), ...
    b('Sum','SpeedError',struct('Inputs','+-')), ...
    b('Mux','measured_current',struct('Inputs','2')),b('Mux','estimated_current',struct('Inputs','2')), ...
    b('Sum','CurrentResidual',struct('Inputs','+-')),b('Demux','residual_channels',struct('Outputs','2')), ...
    b('DotProduct','SquaredResidual',struct()),b('Sqrt','ResidualNorm',struct()), ...
    b('Mux','observer_channels',struct('Inputs','25')), ...
    b('ToWorkspace','ObserverTrace',struct('VariableName','observer_trace','SaveFormat','Structure With Time', ...
    'MaxDataPoints','inf','SampleTime','currentCfg.Ts')), ...
    c('#phase_voltage.y1','#phase_channels.u1'),c('#voltage_ab.y1','#VoltageSample.u1'), ...
    c('#VoltageSample.y1','#VoltageAge.u1'),c('#VoltageAge.y1','#aligned_voltage.u1'), ...
    c('#aligned_voltage.y1','#smo.u1'),c('#aligned_voltage.y2','#smo.u2'), ...
    c('#currentClarke.y1','#smo.u3'),c('#currentClarke.y2','#smo.u4'), ...
    c('#Direction.y1','#smo.u5'),c('#ObserverEnable.y1','#smo.u6'),c('#ObserverReset.y1','#smo.u7'), ...
    c('#voltageClarke.y1','#voltage_ab.u1'),c('#voltageClarke.y2','#voltage_ab.u2'), ...
    c('#voltageClarke.y3','#VoltageZero.u1'),c('#currentClarke.y3','#CurrentZero.u1'), ...
    c('#smo.y1','#RawAngleError.u1'),c('#theta_reference.y1','#RawAngleError.u2'), ...
    c('#theta_reference.y1','#ReferenceSin.u1'),c('#theta_reference.y1','#ReferenceCos.u1'), ...
    c('#ReferenceSin.y1','#ReferenceWrapped.u1'),c('#ReferenceCos.y1','#ReferenceWrapped.u2'), ...
    c('#RawAngleError.y1','#ErrorSin.u1'),c('#RawAngleError.y1','#ErrorCos.u1'), ...
    c('#ErrorSin.y1','#AngleError.u1'),c('#ErrorCos.y1','#AngleError.u2'), ...
    c('#smo.y2','#SpeedError.u1'),c('#omega_reference.y1','#SpeedError.u2'), ...
    c('#currentClarke.y1','#measured_current.u1'),c('#currentClarke.y2','#measured_current.u2'), ...
    c('#smo.y6','#estimated_current.u1'),c('#smo.y7','#estimated_current.u2'), ...
    c('#estimated_current.y1','#CurrentResidual.u1'),c('#measured_current.y1','#CurrentResidual.u2'), ...
    c('#CurrentResidual.y1','#residual_channels.u1'), ...
    c('#CurrentResidual.y1','#SquaredResidual.u1'),c('#CurrentResidual.y1','#SquaredResidual.u2'), ...
    c('#SquaredResidual.y1','#ResidualNorm.u1'),c('#observer_channels.y1','#ObserverTrace.u1')}];
for index=1:3
    operations=[operations,{c(sprintf('#phase_channels.y%d',index),sprintf('#voltageClarke.u%d',index)), ...
        c(['#',inputs{index+1},'.y1'],sprintf('#currentClarke.u%d',index))}];
end
recordSources={'#ReferenceWrapped.y1','#omega_reference.y1','#theta_physical.y1','#omega_physical.y1'};
for index=1:12,recordSources{end+1}=sprintf('#smo.y%d',index);end
recordSources=[recordSources,{'#currentClarke.y1','#currentClarke.y2','#aligned_voltage.y1','#aligned_voltage.y2', ...
    '#ObserverEnable.y1','#ObserverReset.y1','#Direction.y1','#AngleError.y1','#SpeedError.y1', ...
    '#residual_channels.y1','#residual_channels.y2','#ResidualNorm.y1'}];
% 28 scalar channels: Mux ports are separate even when their units differ.
operations{end+1}=struct('op','configure','target','#observer_channels','params',struct('Inputs',num2str(numel(recordSources))));
for index=1:numel(recordSources),operations{end+1}=c(recordSources{index},sprintf('#observer_channels.u%d',index));end
groups={'ObserverAngleScope',{'#ReferenceWrapped.y1','#smo.y1','#AngleError.y1'}; ...
    'ObserverSpeedScope',{'#omega_reference.y1','#smo.y2','#SpeedError.y1'}; ...
    'ObserverCurrentScope',{'#currentClarke.y1','#currentClarke.y2','#smo.y6','#smo.y7','#residual_channels.y1','#residual_channels.y2'}; ...
    'ObserverEmfScope',{'#smo.y4','#smo.y5','#smo.y11'}; ...
    'ObserverStatusScope',{'#smo.y3','#ObserverEnable.y1','#ObserverReset.y1','#Direction.y1'}; ...
    'ObserverVoltageScope',{'#aligned_voltage.y1','#aligned_voltage.y2'}};
for group=1:size(groups,1)
    name=groups{group,1};sources=groups{group,2};mux=[name,'_mux'];
    operations=[operations,{b('Mux',mux,struct('Inputs',num2str(numel(sources)))), ...
        b('Scope',name,struct('NumInputPorts','1')),c(['#',mux,'.y1'],['#',name,'.u1'])}];
    for index=1:numel(sources),operations{end+1}=c(sources{index},sprintf('#%s.u%d',mux,index));end
end
edit(model,monitorId,operations,true,'full');
rootSources={'blk_29.y8','blk_64.y7','blk_64.y8','blk_64.y9','blk_64.y3','blk_64.y6','blk_171.y1','blk_170.y1'};
operations={};for index=1:8,operations{end+1}=c(rootSources{index},sprintf('%s.u%d',monitorId,index));end
edit(model,'root',operations,true,'incremental');
save_system(model,destination);
monitorPath=Simulink.ID.getFullName([model,':',extractAfter(monitorId,'blk_')]);
print(['-s',monitorPath],'-dpng',fullfile(module,'build_process','observer_diagram.png'));
end
function operation=b(type,name,parameters)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',parameters);
end
function operation=c(source,destination)
operation=struct('op','connect','target',[source,' -> ',destination]);
end
function id=createdId(result,reference)
match=regexp(char(result),[reference,':\s*(blk_\d+)'],'tokens');assert(isscalar(match));id=match{1}{1};
end
function result=edit(model,scope,operations,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(operations),layout);disp(result);
disp(model_read(model,scope,'0'));
if ~contains(string(result),'status: ok')
    disp(model_check(model,scope,'["all"]'));error('Inspect the partial or failed edit.');
end
if complete
    check=model_check(model,scope,'["all"]');disp(check);assert(~contains(string(check),'severity: error'));
end
end
