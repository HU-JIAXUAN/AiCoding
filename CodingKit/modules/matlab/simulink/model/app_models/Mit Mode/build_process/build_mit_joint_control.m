function build_mit_joint_control(outputFile)
%BUILD_MIT_JOINT_CONTROL Assemble the MIT branch on the shared FOC fixture.
module = fileparts(fileparts(mfilename('fullpath')));
project = fileparts(fileparts(fileparts(module)));
name = 'MitJointControl';
if nargin == 0
    outputFile = fullfile(module,'src',[name '.slx']);
end
assert(~bdIsLoaded(name) && ~isfile(outputFile), ...
    'Close the model and choose a new output file before rebuilding.');
[folder,basename,extension] = fileparts(outputFile);
assert(strcmp(basename,name) && strcmp(extension,'.slx'));
addpath(fullfile(project,'docs','scripts'));
assert(library.settingsLookup().gatePass,'Resolve the custom library settings first.');
initialize_motor_paths();
template = which('MotorExperiment.slx');
assert(~isempty(template),'MotorExperiment.slx is required.');
source = model_read(template,'root','0');
assert(startsWith(strtrim(string(source)),'status: ok'),'%s',char(source));
new_system(name,FromFile=template);
cleanup = onCleanup(@() close_system(name,0));
open_system(name);
initialize_mit_joint_control(name);

callback = ['addpath(fullfile(fileparts(fileparts(get_param(bdroot,''FileName''))),' ...
    '''build_process''));initialize_mit_joint_control(bdroot);'];
id = @(block) blockId(name,block);
ops = {config(['config:' name],struct('PostLoadFcn',callback)), ...
    config(id('PositionCommand'),struct('FinalValue','mitCfg.GearRatio*mitCfg.PositionReference')), ...
    config(id('SpeedCommand'),struct('FinalValue','mitCfg.GearRatio*mitCfg.VelocityReference')), ...
    config(id('LoadTorque'),struct('FinalValue','mitCfg.LoadTorque/mitCfg.GearRatio')), ...
    block('Constant','UseMITMode',struct('Value','mitCfg.UseMitMode','OutDataTypeStr','boolean')), ...
    block('Constant','JointKp',struct('Value','mitCfg.Kp')), ...
    block('Constant','JointKd',struct('Value','mitCfg.Kd')), ...
    block('Constant','BusVoltage',struct('Value','inverterCfg.Vdc')), ...
    block('Constant','ZeroDCurrent',struct('Value','0')), ...
    block('Step','JointTorqueFeedforward',struct('Time','experimentCfg.CommandTime', ...
        'InitialValue','0','FinalValue','mitCfg.FeedforwardTorque','SampleTime','currentCfg.Ts')), ...
    block('Gain','JointPositionReference',struct('Gain','1/mitCfg.GearRatio')), ...
    block('Gain','JointVelocityReference',struct('Gain','1/mitCfg.GearRatio')), ...
    block('Gain','JointPosition',struct('Gain','1/mitCfg.GearRatio')), ...
    block('Gain','JointVelocity',struct('Gain','1/mitCfg.GearRatio')), ...
    block('Gain','JointTorqueEstimate',struct('Gain','mitCfg.GearRatio')), ...
    block('Gain','JointLoadTorque',struct('Gain','mitCfg.GearRatio')), ...
    block('Logic','NotMITMode',struct('Operator','NOT')), ...
    block('Logic','NotResetMIT',struct('Operator','NOT')), ...
    block('Logic','MITActive',struct('Operator','AND','Inputs','3')), ...
    block('Logic','MotionActive',struct('Operator','AND','Inputs','2')), ...
    block('Switch','SelectQCurrent',switchParams()), ...
    block('Switch','SelectDCurrent',switchParams()), ...
    block('Mux','MITTraceChannels',struct('Inputs','13')), ...
    block('ToWorkspace','SaveMITTrace',struct('VariableName','mitTrace', ...
        'SaveFormat','Structure With Time','SampleTime','currentCfg.Ts','MaxDataPoints','inf')), ...
    struct('op','create_subsystem','name','MITMode','ref','MITMode', ...
        'interface',struct('inputs',{{}},'outputs',{{}}))};
edit(name,'root',ops,false,'incremental');
edit(name,id('MITMode'),mitOperations(),true,'full');

% Intercept only the reference inputs and their existing logging branches.
% The current PI, transforms, modulation, timing and PMSM links are inherited.
motion = id('MotionStage');
current = id('CurrentStage');
feedback = id('FeedbackStage');
trace = id('TraceChannels');
currents = id('CurrentsChannels');
enable = port(id('Enable'),'y',1);
reset = port(id('Reset'),'y',1);
mit = id('MITMode');
selectQ = id('SelectQCurrent');
selectD = id('SelectDCurrent');
useMIT = port(id('UseMITMode'),'y',1);

ops = {connect(port(id('PositionCommand'),'y',1),port(id('JointPositionReference'),'u',1)), ...
    connect(port(id('SpeedCommand'),'y',1),port(id('JointVelocityReference'),'u',1)), ...
    connect(port(feedback,'y',5),port(id('JointPosition'),'u',1)), ...
    connect(port(feedback,'y',4),port(id('JointVelocity'),'u',1)), ...
    connect(port(id('Electrical'),'y',3),port(id('JointTorqueEstimate'),'u',1)), ...
    connect(port(id('LoadTorque'),'y',1),port(id('JointLoadTorque'),'u',1)), ...
    connect(useMIT,port(id('NotMITMode'),'u',1)), ...
    connect(reset,port(id('NotResetMIT'),'u',1)), ...
    connect(useMIT,port(id('MITActive'),'u',1)), ...
    connect(enable,port(id('MITActive'),'u',2)), ...
    connect(port(id('NotResetMIT'),'y',1),port(id('MITActive'),'u',3)), ...
    connect(port(id('NotMITMode'),'y',1),port(id('MotionActive'),'u',1)), ...
    connect(enable,port(id('MotionActive'),'u',2)), ...
    disconnect(enable,port(motion,'u',7)), ...
    connect(port(id('MotionActive'),'y',1),port(motion,'u',7)), ...
    connect(port(mit,'y',1),port(selectQ,'u',1)), ...
    connect(useMIT,port(selectQ,'u',2)), ...
    connect(port(motion,'y',1),port(selectQ,'u',3)), ...
    connect(port(id('ZeroDCurrent'),'y',1),port(selectD,'u',1)), ...
    connect(useMIT,port(selectD,'u',2)), ...
    connect(port(motion,'y',2),port(selectD,'u',3))};

inputs = {'JointPositionReference','JointVelocityReference','JointKp','JointKd', ...
    'JointTorqueFeedforward','JointPosition','JointVelocity','MITActive','BusVoltage'};
for k = 1:numel(inputs)
    ops{end+1} = connect(port(id(inputs{k}),'y',1),port(mit,'u',k));
end
destinations = {port(current,'u',1),port(currents,'u',1),port(trace,'u',1); ...
    port(current,'u',2),port(currents,'u',2),port(trace,'u',2)};
selectors = {selectD,selectQ};
for axis = 1:2
    original = port(motion,'y',3-axis);
    replacement = port(selectors{axis},'y',1);
    for k = 1:size(destinations,2)
        dst = destinations{axis,k};
        ops(end+1:end+2) = {disconnect(original,dst),connect(replacement,dst)};
    end
end

logger = id('MITTraceChannels');
traceSources = {port(id('JointPositionReference'),'y',1),port(id('JointVelocityReference'),'y',1), ...
    port(id('JointPosition'),'y',1),port(id('JointVelocity'),'y',1), ...
    port(id('JointTorqueFeedforward'),'y',1),port(mit,'y',3),port(mit,'y',2), ...
    port(mit,'y',1),port(selectQ,'y',1),port(feedback,'y',2), ...
    port(id('JointTorqueEstimate'),'y',1),port(id('JointLoadTorque'),'y',1),port(selectD,'y',1)};
for k = 1:numel(traceSources)
    ops{end+1} = connect(traceSources{k},port(logger,'u',k));
end
ops{end+1} = connect(port(logger,'y',1),port(id('SaveMITTrace'),'u',1));
edit(name,'root',ops,true,'incremental');

if ~isfolder(folder), mkdir(folder); end
save_system(name,outputFile);
end

function ops = mitOperations()
% Use the newly updated filter state in the torque command at each FOC tick.
in = {'q_ref','dq_ref','kp','kd','tau_ff','q','dq','active','bus_voltage'};
out = {'iq_ref','tau_request','tau_ff_filtered'};
ops = cell(1,numel(in)+numel(out));
for k = 1:numel(in)
    ops{k} = block('Inport',in{k},struct('Port',num2str(k)));
end
for k = 1:numel(out)
    ops{numel(in)+k} = block('Outport',out{k},struct('Port',num2str(k)));
end
ops = [ops,{block('Sum','PositionError',struct('Inputs','+-')), ...
    block('Sum','VelocityError',struct('Inputs','+-')), ...
    block('Product','SpringTorque',struct('Inputs','**')), ...
    block('Product','DampingTorque',struct('Inputs','**')), ...
    block('Gain','NewFeedforward',struct('Gain','1-mitCfg.FeedforwardMemory')), ...
    block('Gain','PreviousFeedforward',struct('Gain','mitCfg.FeedforwardMemory')), ...
    block('UnitDelay','FeedforwardState',struct('SampleTime','currentCfg.Ts','InitialCondition','0')), ...
    block('Sum','FilterSum',struct('Inputs','++')), ...
    block('Switch','ActiveFeedforward',switchParams()), ...
    block('Constant','ZeroTorque',struct('Value','0')), ...
    block('Sum','TotalTorque',struct('Inputs','+++')), ...
    block('Gain','TorqueToCurrent',struct('Gain','1/(mitCfg.Kt*mitCfg.GearRatio)')), ...
    block('Saturate','CurrentLimit',struct('UpperLimit','mitCfg.CurrentLimit','LowerLimit','-mitCfg.CurrentLimit')), ...
    block('Constant','MaxBusVoltage',struct('Value','mitCfg.BusVoltageMax')), ...
    block('RelationalOperator','BusInRange',struct('Operator','<=')), ...
    block('Logic','DriveActive',struct('Operator','AND','Inputs','2')), ...
    block('Switch','OutputCurrent',switchParams())}];
links = {
    'q_ref',1,'PositionError',1; 'q',1,'PositionError',2
    'dq_ref',1,'VelocityError',1; 'dq',1,'VelocityError',2
    'PositionError',1,'SpringTorque',1; 'kp',1,'SpringTorque',2
    'VelocityError',1,'DampingTorque',1; 'kd',1,'DampingTorque',2
    'tau_ff',1,'NewFeedforward',1; 'FeedforwardState',1,'PreviousFeedforward',1
    'NewFeedforward',1,'FilterSum',1; 'PreviousFeedforward',1,'FilterSum',2
    'FilterSum',1,'ActiveFeedforward',1; 'active',1,'ActiveFeedforward',2
    'ZeroTorque',1,'ActiveFeedforward',3; 'ActiveFeedforward',1,'FeedforwardState',1
    'ActiveFeedforward',1,'tau_ff_filtered',1; 'ActiveFeedforward',1,'TotalTorque',3
    'SpringTorque',1,'TotalTorque',1; 'DampingTorque',1,'TotalTorque',2
    'TotalTorque',1,'tau_request',1; 'TotalTorque',1,'TorqueToCurrent',1
    'TorqueToCurrent',1,'CurrentLimit',1; 'CurrentLimit',1,'OutputCurrent',1
    'bus_voltage',1,'BusInRange',1; 'MaxBusVoltage',1,'BusInRange',2
    'active',1,'DriveActive',1; 'BusInRange',1,'DriveActive',2
    'DriveActive',1,'OutputCurrent',2; 'ZeroTorque',1,'OutputCurrent',3
    'OutputCurrent',1,'iq_ref',1};
for k = 1:size(links,1)
    ops{end+1} = connect(port(['#' links{k,1}],'y',links{k,2}), ...
        port(['#' links{k,3}],'u',links{k,4}));
end
end

function edit(model,scope,ops,complete,layout)
open_loop_model_edit(model,scope,ops,complete,layout);
end

function id = blockId(model,name)
blocks = find_system(model,'SearchDepth',1,'Type','Block','Name',name);
assert(isscalar(blocks),'Expected a single top-level block named %s.',name);
id = ['blk_' extractAfter(Simulink.ID.getSID(blocks{1}),':')];
end

function op = block(type,name,params)
op = struct('op','add_block','type',type,'name',name,'ref',name,'params',params);
end

function op = config(target,params)
op = struct('op','configure','target',target,'params',params);
end

function op = connect(src,dst)
op = struct('op','connect','target',[src ' -> ' dst]);
end

function op = disconnect(src,dst)
op = struct('op','disconnect','target',[src ' -> ' dst]);
end

function p = port(id,kind,index)
p = sprintf('%s.%s%d',id,kind,index);
end

function params = switchParams()
params = struct('Criteria','u2 ~= 0');
end
