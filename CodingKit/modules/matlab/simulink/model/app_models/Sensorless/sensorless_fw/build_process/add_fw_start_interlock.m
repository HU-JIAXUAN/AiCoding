function add_fw_start_interlock(model)
%ADD_FW_START_INTERLOCK Observe terminal EMF before cold alignment/restart.
% Permission is a registered state. No true rotor angle/speed enters this gate.
assert(strcmp(model,'SensorlessFieldWeakeningFOC')&&bdIsLoaded(model));
disp(model_read(model,'root','0'));
assert(isempty(find_system(model,'SearchDepth',1,'Name','StartInterlock')));
observer=child(model,'Observer');controller=child(model,'Controller');
scope=id(observer);disp(model_read(model,scope,'0'));
estimator=child(observer,'Estimator');
o={b('Outport','emf_magnitude',struct('Port','5')),c([id(estimator) '.y11'],'#emf_magnitude.u1')};
edit(model,scope,o,true,'incremental');

inputs=child(model,'inputs');ports=get_param(inputs,'PortHandles');assert(numel(ports.Outport)==7);
enable=child(controller,'enable');excluded=sprintf('%s.u%s',id(controller),get_param(enable,'Port'));
destinations=cell(7,1);
for k=1:7
    line=get_param(ports.Outport(k),'Line');destinations{k}={};if line==-1,continue;end
    targetPorts=get_param(line,'DstPortHandle');
    for j=1:numel(targetPorts)
        endpoint=sprintf('%s.u%d',id(get_param(targetPorts(j),'Parent')),get_param(targetPorts(j),'PortNumber'));
        if ~strcmp(endpoint,excluded),destinations{k}{end+1}=endpoint;end
    end
end
inputLine=get_param(ports.Inport(1),'Line');sourcePort=get_param(inputLine,'SrcPortHandle');
source=sprintf('%s.y%d',id(get_param(sourcePort,'Parent')),get_param(sourcePort,'PortNumber'));
o={struct('op','delete','target',id(inputs)),b('Demux','inputs',struct('Outputs','7')), ...
    struct('op','create_subsystem','name','StartInterlock','ref','StartInterlock', ...
    'interface',struct('inputs',{{}},'outputs',{{}})),c(source,'#inputs.u1')};
for k=1:7
    for j=1:numel(destinations{k}),o{end+1}=c(sprintf('#inputs.y%d',k),destinations{k}{j});end
end
edit(model,'root',o,false,'incremental');
guard=child(model,'StartInterlock');scope=id(guard);
names={'request_enable','reset','observer_enable','emf_magnitude','direction'};o={};
for k=1:numel(names),o{end+1}=b('Inport',names{k},struct('Port',num2str(k)));end
o=[o,{b('Outport','permit',struct('Port','1')), ...
    b('UnitDelay','WarmCount',struct('SampleTime','currentCfg.Ts','InitialCondition','0')), ...
    b('UnitDelay','PermitState',struct('SampleTime','currentCfg.Ts','InitialCondition','false')), ...
    b('UnitDelay','PreviousDirection',struct('SampleTime','currentCfg.Ts','InitialCondition','focCfg.Direction')), ...
    b('RelationalOperator','DirectionChanged',struct('Operator','~=')), ...
    b('Logic','NotReset',struct('Operator','NOT')),b('Logic','DirectionStable',struct('Operator','NOT')), ...
    b('Logic','RequestActive',struct('Operator','AND','Inputs','3')), ...
    b('Logic','ObserveActive',struct('Operator','AND','Inputs','2')), ...
    b('Constant','One',struct('Value','1')),b('Constant','Zero',struct('Value','0')), ...
    b('Sum','IncrementCount',struct('Inputs','++')), ...
    b('Saturate','BoundCount',struct('LowerLimit','0','UpperLimit','startGuardCfg.ObserveTicks')), ...
    b('Switch','NextCount',struct('Criteria','u2 ~= 0')), ...
    b('Constant','RequiredTicks',struct('Value','startGuardCfg.ObserveTicks')), ...
    b('RelationalOperator','WarmReady',struct('Operator','>=')), ...
    b('Constant','StartEmfLimit',struct('Value','startGuardCfg.MaxStartEmf')), ...
    b('RelationalOperator','LowEmf',struct('Operator','<=')), ...
    b('Logic','Qualified',struct('Operator','AND','Inputs','3')), ...
    b('Logic','PermissionHold',struct('Operator','OR','Inputs','2')), ...
    b('Logic','NextPermission',struct('Operator','AND','Inputs','2')), ...
    b('Logic','CurrentPermission',struct('Operator','AND','Inputs','2')), ...
    b('DataTypeConversion','PermitDouble',struct('OutDataTypeStr','double')), ...
    b('DataTypeConversion','QualifiedDouble',struct('OutDataTypeStr','double')), ...
    b('DataTypeConversion','DirectionChangedDouble',struct('OutDataTypeStr','double')), ...
    b('Constant','GuardEnabled',struct('Value','startGuardCfg.Enable')), ...
    b('Switch','PermitSelected',struct('Criteria','u2 ~= 0')), ...
    c('#direction.y1','#PreviousDirection.u1'),c('#direction.y1','#DirectionChanged.u1'), ...
    c('#PreviousDirection.y1','#DirectionChanged.u2'),c('#DirectionChanged.y1','#DirectionStable.u1'), ...
    c('#reset.y1','#NotReset.u1'),c('#request_enable.y1','#RequestActive.u1'), ...
    c('#NotReset.y1','#RequestActive.u2'),c('#DirectionStable.y1','#RequestActive.u3'), ...
    c('#RequestActive.y1','#ObserveActive.u1'),c('#observer_enable.y1','#ObserveActive.u2'), ...
    c('#WarmCount.y1','#IncrementCount.u1'),c('#One.y1','#IncrementCount.u2'), ...
    c('#IncrementCount.y1','#BoundCount.u1'),c('#BoundCount.y1','#NextCount.u1'), ...
    c('#ObserveActive.y1','#NextCount.u2'),c('#Zero.y1','#NextCount.u3'),c('#NextCount.y1','#WarmCount.u1'), ...
    c('#WarmCount.y1','#WarmReady.u1'),c('#RequiredTicks.y1','#WarmReady.u2'), ...
    c('#emf_magnitude.y1','#LowEmf.u1'),c('#StartEmfLimit.y1','#LowEmf.u2'), ...
    c('#WarmReady.y1','#Qualified.u1'),c('#LowEmf.y1','#Qualified.u2'),c('#ObserveActive.y1','#Qualified.u3'), ...
    c('#Qualified.y1','#PermissionHold.u1'),c('#PermitState.y1','#PermissionHold.u2'), ...
    c('#PermissionHold.y1','#NextPermission.u1'),c('#RequestActive.y1','#NextPermission.u2'), ...
    c('#NextPermission.y1','#PermitState.u1'),c('#PermitState.y1','#CurrentPermission.u1'), ...
    c('#RequestActive.y1','#CurrentPermission.u2'),c('#CurrentPermission.y1','#PermitDouble.u1'), ...
    c('#Qualified.y1','#QualifiedDouble.u1'),c('#DirectionChanged.y1','#DirectionChangedDouble.u1'), ...
    c('#PermitDouble.y1','#PermitSelected.u1'),c('#GuardEnabled.y1','#PermitSelected.u2'), ...
    c('#request_enable.y1','#PermitSelected.u3'),c('#PermitSelected.y1','#permit.u1')}];
definitions=sensorless_fw_channels('guard');
o=[o,{b('Mux','GuardChannels',struct('Inputs','9')),b('ToWorkspace','SaveGuard',struct( ...
    'VariableName','guard_trace','SaveFormat','Structure With Time','SampleTime','currentCfg.Ts','MaxDataPoints','inf')), ...
    c('#GuardChannels.y1','#SaveGuard.u1'),b('Mux','PermitChannels',struct('Inputs','4')), ...
    b('Scope','PermitScope',struct('NumInputPorts','1')),c('#PermitChannels.y1','#PermitScope.u1'), ...
    b('Scope','ObservedEmfScope',struct('NumInputPorts','1')),c('#emf_magnitude.y1','#ObservedEmfScope.u1'), ...
    b('Scope','ObservationCountScope',struct('NumInputPorts','1')),c('#WarmCount.y1','#ObservationCountScope.u1')}];
for k=1:size(definitions,1),o{end+1}=c(definitions{k,4},sprintf('#GuardChannels.u%d',k));end
signals={'#request_enable.y1','#PermitSelected.y1','#QualifiedDouble.y1','#DirectionChangedDouble.y1'};
for k=1:4,o{end+1}=c(signals{k},sprintf('#PermitChannels.u%d',k));end
edit(model,scope,o,true,'full');
inputs=child(model,'inputs');obsEnable=child(model,'ObserverEnabledDouble');
o={c([id(inputs) '.y3'],[id(guard) '.u1']),c([id(inputs) '.y4'],[id(guard) '.u2']), ...
    c([id(obsEnable) '.y1'],[id(guard) '.u3']),c([id(observer) '.y5'],[id(guard) '.u4']), ...
    c([id(inputs) '.y5'],[id(guard) '.u5']),c([id(guard) '.y1'],excluded)};
edit(model,'root',o,true,'incremental');disp('FW_START_INTERLOCK_ADDED');
end
function path=child(scope,name)
found=find_system(scope,'SearchDepth',1,'Name',name);assert(isscalar(found),name);path=found{1};
end
function value=id(path)
value=['blk_' extractAfter(Simulink.ID.getSID(path),':')];
end
function operation=b(type,name,params)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',params);
end
function operation=c(source,target)
operation=struct('op','connect','target',[source ' -> ' target]);
end
function result=edit(model,scope,operations,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(operations),layout);disp(result);
disp(model_read(model,scope,'0'));
if ~startsWith(strtrim(string(result)),'status: ok')
    disp(model_check(model,scope,'["all"]'));error('Inspect partial edit before continuing.');
end
if complete
    check=model_check(model,scope,'["all"]');disp(check);
    assert(startsWith(strtrim(string(check)),'status: healthy'));
end
end
