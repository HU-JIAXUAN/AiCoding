function report=analyze_sensorless_fw_case(record,specification,limits)
%ANALYZE_SENSORLESS_FW_CASE Evaluate actual fast physical and sampled traces.
p=record.parameters;cp=record.plant.columns;co=record.observer.columns;
cc=record.controller.columns;ca=record.allocation.columns;
physical=record.plant.trace;observer=record.observer.trace;
controller=record.controller.trace;allocation=record.allocation.trace;
time=record.observer.time;index=round(time/p.bridgeCfg.Ts)+1;
assert(max(abs(record.plant.time(index)-time))<1e-11);
steady=time>=p.experimentCfg.Duration-limits.SteadyWindow;
steadyPhysical=record.plant.time>=p.experimentCfg.Duration-limits.SteadyWindow;
thetaError=atan2(sin(observer(:,co.theta_hat)-physical(index,cp.theta_e)), ...
    cos(observer(:,co.theta_hat)-physical(index,cp.theta_e)));
target=p.focCfg.SpeedReference;
if isfield(specification,'target_speed'),target=specification.target_speed;end
speedError=physical(index,cp.speed_mechanical)-target;
active=physical(:,cp.bridge_mode)==1;duty=physical(active,cp.duty);
feasible=allocation(:,ca.feasible)>0.5;
power=physical(:,cp.bus_voltage).*physical(:,cp.dc_current);
mechanicalPower=physical(:,cp.torque).*physical(:,cp.speed_mechanical);
metrics=struct('angle_rms_rad',sqrt(mean(thetaError(steady).^2)), ...
    'speed_error_rms_rad_per_s',sqrt(mean(speedError(steady).^2)), ...
    'steady_speed_rad_per_s',mean(physical(index(steady),cp.speed_mechanical)), ...
    'valid_fraction',mean(observer(steady,co.valid)>0.5), ...
    'auto_fraction',mean(controller(steady,cc.handover_mode)==4), ...
    'physical_dq_peak_A',max(hypot(physical(:,cp.id_true),physical(:,cp.iq_true))), ...
    'allocated_dq_peak_A',max(hypot(allocation(:,ca.id_reference),allocation(:,ca.iq_reference))), ...
    'steady_id_reference_A',mean(allocation(steady,ca.id_reference)), ...
    'steady_id_actual_A',mean(physical(index(steady),cp.id_true)), ...
    'weakening_fraction',mean(allocation(steady,ca.fw_active)>0.5), ...
    'feasible_fraction',mean(feasible(steady)), ...
    'steady_dc_power_W',mean(power(steadyPhysical)), ...
    'steady_mechanical_power_W',mean(mechanicalPower(steadyPhysical)), ...
    'kcl_max_A',max(abs(sum(physical(:,cp.phase_current),2))), ...
    'duty_min',min(duty,[],'all'),'duty_max',max(duty,[],'all'), ...
    'handover_fault_count',nnz(controller(:,cc.handover_fault)), ...
    'speed_integral_peak_Nm',max(abs(controller(:,cc.integral_torque))), ...
    'host_seconds',record.host_seconds);
checks=struct('angle',metrics.angle_rms_rad<=limits.AngleRmsMax, ...
    'valid',metrics.valid_fraction>=limits.ValidFractionMin, ...
    'auto',metrics.auto_fraction>=limits.AutoFractionMin, ...
    'physical_current',metrics.physical_dq_peak_A<=p.refCfg.CurrentMax+limits.CurrentOvershoot, ...
    'reference_current',metrics.allocated_dq_peak_A<=p.refCfg.CurrentMax+limits.ReferenceTolerance, ...
    'kcl',metrics.kcl_max_A<=limits.KclTolerance, ...
    'duty',~isempty(duty)&&metrics.duty_min>=p.inverterCfg.MinDuty-limits.DutyTolerance&&metrics.duty_max<=1-p.inverterCfg.MinDuty+limits.DutyTolerance, ...
    'no_fault',metrics.handover_fault_count==0, ...
    'feasible_voltage',all(allocation(feasible,ca.predicted_voltage)<=allocation(feasible,ca.voltage_available)+limits.VoltageTolerance));
if specification.expect_tracking
    checks.speed=metrics.speed_error_rms_rad_per_s<=limits.SpeedErrorRmsMax;
    checks.final_command=abs(controller(end,cc.speed_reference)-target)<1e-6;
else
    checks.expected_speed_limitation=metrics.speed_error_rms_rad_per_s>limits.SpeedErrorRmsMax;
end
if specification.require_weakening
    checks.negative_id_reference=metrics.steady_id_reference_A<=-limits.WeakeningIdMinimum;
    checks.negative_id_actual=metrics.steady_id_actual_A<=-limits.WeakeningIdMinimum;
    checks.weakening=metrics.weakening_fraction>=limits.WeakeningFractionMin;
end
if specification.require_regeneration
    checks.regeneration=metrics.steady_dc_power_W<-10&&metrics.steady_mechanical_power_W<-10;
end
values=struct2cell(checks);normalPassed=all(cellfun(@(x)isscalar(x)&&x,values));
if specification.expected_counterexample
    classification='expected-counterexample';
    passed=metrics.weakening_fraction==0&&metrics.speed_error_rms_rad_per_s>limits.SpeedErrorRmsMax;
else
    classification='physical-closed-loop';passed=normalPassed;
end
report=struct('name',specification.name,'passed',passed,'classification',classification, ...
    'normal_acceptance_passed',normalPassed,'metrics',metrics,'checks',checks, ...
    'expect_tracking',specification.expect_tracking,'require_weakening',specification.require_weakening, ...
    'require_regeneration',specification.require_regeneration,'duration_s',p.experimentCfg.Duration);
end
