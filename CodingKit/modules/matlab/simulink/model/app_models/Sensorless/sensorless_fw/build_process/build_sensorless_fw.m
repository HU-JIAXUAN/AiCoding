function build_sensorless_fw(templateFile)
%BUILD_SENSORLESS_FW Assemble linked EEMF, allocator and dynamic-bus IPMSM.
assert(strcmp(version('-release'),'2026b'));
gate=library.settingsLookup();assert(gate.gatePass);
module=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(module,'parameter'),fileparts(mfilename('fullpath')));
model='SensorlessFieldWeakeningFOC';destination=fullfile(module,'src',[model '.slx']);
assert(~isfile(destination)&&~bdIsLoaded(model),'Refusing to overwrite an App.');
p=sensorless_fw_parameters(); %#ok<NASGU>
if nargin<1
    project=fileparts(fileparts(fileparts(which('initialize_motor_paths'))));
    templateFile=fullfile(project,'model','app_models','Sensorless','sensorless_foc','src','EemfSensorlessFOC.slx');
end
for libraryName={'PMSMBridgeBusPlant','ClarkePark','CurrentControl','CurrentReference','Inverter','ControlTiming'}
    load_system(libraryName{1});disp(model_read(libraryName{1},'root','0'));
end
if ~isfolder(fileparts(destination)),mkdir(fileparts(destination));end
load_system(templateFile);[~,template]=fileparts(templateFile);
assert(strcmp(get_param(template,'Dirty'),'off')&&strcmp(get_param(template,'Open'),'off'));
save_system(template,destination);initialize_sensorless_fw(model);
disp(model_read(model,'root','0'));
ids=scopeIds(model,model);
removed={'Plant','VoltageStage','TruthCurrents','MeasuredCurrents','FeasibleCommand','DeadtimeError','TraceChannels','SaveTrace'};
ops={};for k=1:numel(removed),ops{end+1}=struct('op','delete','target',ids.(removed{k}));end
for name={'Plant','VoltageStage'}
    ops{end+1}=struct('op','create_subsystem','name',name{1},'ref',name{1},'interface',struct('inputs',{{}},'outputs',{{}}));
end
callback=['addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));', ...
    'initialize_sensorless_fw(bdroot);'];
ops{end+1}=struct('op','configure','target',['config:' model],'params',struct( ...
    'Solver','FixedStepDiscrete','SolverType','Fixed-step','FixedStep','experimentCfg.Step', ...
    'StopTime','experimentCfg.Duration','ReturnWorkspaceOutputs','on', ...
    'AlgebraicLoopMsg','error','PostLoadFcn',callback));
ops{end+1}=struct('op','configure','target',ids.inputs,'params',struct('Outputs','7'));
edit(model,'root',ops,false,'incremental');
ids=scopeIds(model,model);
% The unit-normalized library instances have their own mask workspace. The
% rest of the App, including the allocator and physical rail, remains in SI.
edit(model,'root',{struct('op','configure','target',ids.VoltageStage,'params',struct( ...
    'Mask','on','MaskPromptString','Normalized inverter configuration', ...
    'MaskStyleString','edit','MaskVariables','inverterCfg=@1;', ...
    'MaskValueString','normalizedInverterCfg'))},false,'incremental');

% Physical motor: no angle/voltage source from a prescribed truth waveform.
o=interface({'duty','mode','load_torque','bus_voltage'},{'phase_current','theta_e','phase_voltage'});
o=[o,{lib('PMSMBridgeBusPlant','BridgeBusMotor','Motor',struct('MaskValueString','bridgeCfg')), ...
    b('Demux','CurrentAB',struct('Outputs','2')),lib('ClarkePark','Park','RotorPark',struct()), ...
    c('#duty.y1','#Motor.u1'),c('#mode.y1','#Motor.u2'),c('#load_torque.y1','#Motor.u3'), ...
    c('#bus_voltage.y1','#Motor.u4'),c('#Motor.y2','#phase_current.u1'), ...
    c('#Motor.y6','#theta_e.u1'),c('#Motor.y3','#phase_voltage.u1'), ...
    c('#Motor.y1','#CurrentAB.u1'),c('#CurrentAB.y1','#RotorPark.u1'), ...
    c('#CurrentAB.y2','#RotorPark.u2'),c('#Motor.y6','#RotorPark.u3')}];
o=[o,logging('plant','bridgeCfg.Ts'),scopes({ ...
    'TrueCurrentScope',{'#RotorPark.y1','#RotorPark.y2'}; ...
    'MechanicalSpeedScope',{'#Motor.y5'};'TorqueScope',{'#Motor.y7','#load_torque.y1'}; ...
    'BusVoltageScope',{'#bus_voltage.y1'};'BusCurrentScope',{'#Motor.y8'}; ...
    'BridgeModeScope',{'#mode.y1','#Motor.y9'}})];
edit(model,ids.Plant,o,true,'full');

% Actual applied terminal voltage is measured from the physical model. The
% PI limiter residual evaluates the current command before the PWM delay.
o=interface({'voltage_request','theta_feedback','bus_voltage','actual_phase_voltage','drive_enable'}, ...
    {'duty_command','duty_applied','limit_scale','voltage_residual','feasible_command','phase_voltage','request_magnitude'});
o=[o,{b('Product','NormalizeVoltage',struct('Inputs','*/')), ...
    lib('CurrentControl','VoltageLimit','VoltageLimit',struct()),b('Demux','LimitedDQ',struct('Outputs','2')), ...
    lib('ClarkePark','InversePark','InversePark',struct()),lib('Inverter','SVPWM','SVPWM',struct()), ...
    b('Mux','RawDuties',struct('Inputs','3')),b('Terminator','CommonMode',struct()), ...
    b('Constant','NeutralDuty',struct('Value','[0.5;0.5;0.5]')),b('Switch','EnabledDuty',struct('Criteria','u2 ~= 0')), ...
    lib('ControlTiming','Actuation','PWMUpdate',struct()),b('Switch','TimingSelect',struct('Criteria','u2 ~= 0')), ...
    b('Constant','UseTiming',struct('Value','experimentCfg.UseTiming')), ...
    b('Demux','CommandChannels',struct('Outputs','3')),lib('Inverter','Average','CommandAverage',struct()), ...
    b('Mux','CommandPhase',struct('Inputs','3')),b('Product','RestoreVoltage',struct('Inputs','**')), ...
    b('Demux','CommandVoltage',struct('Outputs','3')),lib('ClarkePark','Clarke','CommandClarke',struct()), ...
    b('Terminator','ZeroSequence',struct()),lib('ClarkePark','Park','CommandPark',struct()), ...
    b('Mux','FeasibleDQ',struct('Inputs','2')),b('Sum','ConsistentResidual',struct('Inputs','+-')), ...
    b('DotProduct','RequestSquared',struct()),b('Sqrt','RequestMagnitude',struct()), ...
    c('#voltage_request.y1','#NormalizeVoltage.u1'),c('#bus_voltage.y1','#NormalizeVoltage.u2'), ...
    c('#NormalizeVoltage.y1','#VoltageLimit.u1'),c('#VoltageLimit.y1','#LimitedDQ.u1'), ...
    c('#LimitedDQ.y1','#InversePark.u1'),c('#LimitedDQ.y2','#InversePark.u2'), ...
    c('#theta_feedback.y1','#InversePark.u3'),c('#InversePark.y1','#SVPWM.u1'),c('#InversePark.y2','#SVPWM.u2'), ...
    c('#SVPWM.y4','#CommonMode.u1'),c('#RawDuties.y1','#EnabledDuty.u1'), ...
    c('#drive_enable.y1','#EnabledDuty.u2'),c('#NeutralDuty.y1','#EnabledDuty.u3'), ...
    c('#EnabledDuty.y1','#duty_command.u1'),c('#EnabledDuty.y1','#PWMUpdate.u1'), ...
    c('#PWMUpdate.y1','#TimingSelect.u1'),c('#UseTiming.y1','#TimingSelect.u2'),c('#PWMUpdate.y2','#TimingSelect.u3'), ...
    c('#TimingSelect.y1','#duty_applied.u1'),c('#EnabledDuty.y1','#CommandChannels.u1'), ...
    c('#CommandPhase.y1','#RestoreVoltage.u1'),c('#bus_voltage.y1','#RestoreVoltage.u2'), ...
    c('#RestoreVoltage.y1','#CommandVoltage.u1'),c('#CommandClarke.y1','#CommandPark.u1'), ...
    c('#CommandClarke.y2','#CommandPark.u2'),c('#CommandClarke.y3','#ZeroSequence.u1'), ...
    c('#theta_feedback.y1','#CommandPark.u3'),c('#CommandPark.y1','#FeasibleDQ.u1'), ...
    c('#CommandPark.y2','#FeasibleDQ.u2'),c('#FeasibleDQ.y1','#feasible_command.u1'), ...
    c('#FeasibleDQ.y1','#ConsistentResidual.u1'),c('#voltage_request.y1','#ConsistentResidual.u2'), ...
    c('#ConsistentResidual.y1','#voltage_residual.u1'),c('#VoltageLimit.y2','#limit_scale.u1'), ...
    c('#actual_phase_voltage.y1','#phase_voltage.u1'),c('#voltage_request.y1','#RequestSquared.u1'), ...
    c('#voltage_request.y1','#RequestSquared.u2'),c('#RequestSquared.y1','#RequestMagnitude.u1'), ...
    c('#RequestMagnitude.y1','#request_magnitude.u1')}];
for k=1:3
    o=[o,{c(sprintf('#SVPWM.y%d',k),sprintf('#RawDuties.u%d',k)), ...
        c(sprintf('#CommandChannels.y%d',k),sprintf('#CommandAverage.u%d',k)), ...
        c(sprintf('#CommandAverage.y%d',k),sprintf('#CommandPhase.u%d',k)), ...
        c(sprintf('#CommandVoltage.y%d',k),sprintf('#CommandClarke.u%d',k))}];
end
o=[o,scopes({'DutyScope',{'#EnabledDuty.y1','#TimingSelect.y1'}; ...
    'VoltageResidualScope',{'#ConsistentResidual.y1'};'ActualPhaseVoltageScope',{'#actual_phase_voltage.y1'}})];
edit(model,ids.VoltageStage,o,true,'full');

% Replace scalar iq allocation with the reusable vector-constrained allocator.
controller=Simulink.ID.getFullName([model ':' extractAfter(ids.Controller,'blk_')]);
disp(model_read(model,ids.Controller,'0'));ci=scopeIds(model,controller);
deleteNames={'TorqueToCurrent','ClosedCurrentLimit','AllocatedTorque','EstimatedTorque','Zero'};
deleteIds=cellfun(@(n)ci.(n),deleteNames,'UniformOutput',false);
iqDest=destinations(model,ci.ClosedCurrentLimit,deleteIds);
torqueDest=destinations(model,ci.AllocatedTorque,deleteIds);
estimateDest=destinations(model,ci.EstimatedTorque,deleteIds);
o={};for k=1:numel(deleteNames),o{end+1}=struct('op','delete','target',ci.(deleteNames{k}));end
o=[o,interfaceExtra({'bus_voltage','voltage_demand'},11), ...
    {b('Outport','drive_enable',struct('Port','3')),lib('CurrentReference','Allocator','CurrentAllocator',struct()), ...
    b('UnitDelay','VoltageDemandPrevious',struct('SampleTime','currentCfg.Ts','InitialCondition','0')), ...
    b('DataTypeConversion','WeakeningFlagDouble',struct('OutDataTypeStr','double')), ...
    b('DataTypeConversion','CurrentLimitFlagDouble',struct('OutDataTypeStr','double')), ...
    b('DataTypeConversion','VoltageLimitFlagDouble',struct('OutDataTypeStr','double')), ...
    b('DataTypeConversion','FeasibleFlagDouble',struct('OutDataTypeStr','double')), ...
    b('Gain','EstimatedSaliency',struct('Gain','pmsmCfg.Ld-pmsmCfg.Lq')), ...
    b('Constant','EstimatedFlux',struct('Value','pmsmCfg.Flux')),b('Sum','EstimatedActiveFlux',struct('Inputs','++')), ...
    b('Product','EstimatedTorqueProduct',struct('Inputs','**')), ...
    b('Gain','EstimatedTorque',struct('Gain','1.5*pmsmCfg.PolePairs')), ...
    c('#SpeedPI.y1','#CurrentAllocator.u1'),c('#Handover.y2','#CurrentAllocator.u2'), ...
    c('#bus_voltage.y1','#CurrentAllocator.u3'),c('#voltage_demand.y1','#VoltageDemandPrevious.u1'), ...
    c('#VoltageDemandPrevious.y1','#CurrentAllocator.u4'),c('#Handover.y8','#CurrentAllocator.u5'), ...
    c('#reset.y1','#CurrentAllocator.u6'),c('#CurrentAllocator.y1','#ClosedCurrent.u1'), ...
    c('#CurrentAllocator.y16','#WeakeningFlagDouble.u1'), ...
    c('#CurrentAllocator.y13','#CurrentLimitFlagDouble.u1'), ...
    c('#CurrentAllocator.y14','#VoltageLimitFlagDouble.u1'), ...
    c('#CurrentAllocator.y15','#FeasibleFlagDouble.u1'), ...
    c('#EstimatedRotorPark.y1','#EstimatedSaliency.u1'),c('#EstimatedSaliency.y1','#EstimatedActiveFlux.u1'), ...
    c('#EstimatedFlux.y1','#EstimatedActiveFlux.u2'),c('#EstimatedActiveFlux.y1','#EstimatedTorqueProduct.u1'), ...
    c('#EstimatedRotorPark.y2','#EstimatedTorqueProduct.u2'),c('#EstimatedTorqueProduct.y1','#EstimatedTorque.u1'), ...
    c('#Handover.y8','#drive_enable.u1')}];
for k=1:numel(iqDest),o{end+1}=c('#CurrentAllocator.y2',iqDest{k});end
for k=1:numel(torqueDest),o{end+1}=c('#CurrentAllocator.y3',torqueDest{k});end
for k=1:numel(estimateDest),o{end+1}=c('#EstimatedTorque.y1',estimateDest{k});end
o=[o,logging('allocation','currentCfg.Ts'),scopes({ ...
    'CurrentAllocationScope',{'#CurrentAllocator.y4','#CurrentAllocator.y5','#CurrentAllocator.y1','#CurrentAllocator.y2','#CurrentAllocator.y6'}; ...
    'AllocationVoltageScope',{'#CurrentAllocator.y7','#CurrentAllocator.y8','#CurrentAllocator.y9','#CurrentAllocator.y11','#CurrentAllocator.y18','#CurrentAllocator.y19'}; ...
    'AllocationFlagsScope',{'#CurrentLimitFlagDouble.y1','#VoltageLimitFlagDouble.y1','#FeasibleFlagDouble.y1','#WeakeningFlagDouble.y1'}})];
ci=rmfield(ci,deleteNames);o=resolve(o,ci);
edit(model,ids.Controller,o,true,'incremental');

% Root wiring uses actual measured phase voltage; truth theta stays in Plant.
o={c([ids.Controller '.y1'],[ids.VoltageStage '.u1']),c([ids.Controller '.y2'],[ids.VoltageStage '.u2']), ...
    c([ids.inputs '.y7'],[ids.VoltageStage '.u3']),c([ids.Plant '.y3'],[ids.VoltageStage '.u4']), ...
    c([ids.Controller '.y3'],[ids.VoltageStage '.u5']),c([ids.VoltageStage '.y2'],[ids.Plant '.u1']), ...
    c([ids.Controller '.y3'],[ids.Plant '.u2']),c([ids.inputs '.y2'],[ids.Plant '.u3']), ...
    c([ids.inputs '.y7'],[ids.Plant '.u4']),c([ids.Plant '.y1'],[ids.Measurement '.u1']), ...
    c([ids.Plant '.y3'],[ids.Observer '.u1']),c([ids.VoltageStage '.y4'],[ids.Controller '.u10']), ...
    c([ids.inputs '.y7'],[ids.Controller '.u11']),c([ids.VoltageStage '.y7'],[ids.Controller '.u12']), ...
    b('Terminator','UnneededTruthAngle',struct()),c([ids.Plant '.y2'],'#UnneededTruthAngle.u1'), ...
    b('Terminator','FeasibleVoltage',struct()),c([ids.VoltageStage '.y5'],'#FeasibleVoltage.u1')};
o=[o,resolve(logging('actuation','currentCfg.Ts'),ids)];
edit(model,'root',o,true,'incremental');
add_fw_start_interlock(model);
tidy_sensorless_fw_model(model);
save_system(model,destination);
assert(strcmp(get_param(model,'Dirty'),'off')&&strcmp(get_param(model,'Open'),'off'));
print(['-s' model],'-dpng',fullfile(module,'build_process','fw_app_diagram.png'));
for name={'Plant','VoltageStage','Controller'}
    actual=Simulink.ID.getFullName([model ':' extractAfter(ids.(name{1}),'blk_')]);
    print(['-s' actual],'-dpng',fullfile(module,'build_process',['fw_' lower(name{1}) '_diagram.png']));
end
close_system(model,0);disp('SENSORLESS_FW_MODEL_BUILT');
end

function ids=scopeIds(model,scope)
blocks=find_system(scope,'SearchDepth',1,'Type','Block');ids=struct();
for k=1:numel(blocks)
    if strcmp(blocks{k},scope),continue;end
    name=get_param(blocks{k},'Name');assert(isvarname(name));
    ids.(name)=['blk_' extractAfter(Simulink.ID.getSID(blocks{k}),':')];
end
end
function targets=destinations(model,source,excluded)
path=Simulink.ID.getFullName([model ':' extractAfter(source,'blk_')]);ports=get_param(path,'PortHandles');
line=get_param(ports.Outport(1),'Line');targets={};if line==-1,return;end
ends=get_param(line,'DstPortHandle');
for k=1:numel(ends)
    parent=get_param(ends(k),'Parent');id=['blk_' extractAfter(Simulink.ID.getSID(parent),':')];
    if ismember(id,excluded),continue;end
    targets{end+1}=sprintf('%s.u%d',id,get_param(ends(k),'PortNumber')); %#ok<AGROW>
end
end
function operations=interface(inputs,outputs)
operations=interfaceExtra(inputs,1);
for k=1:numel(outputs),operations{end+1}=b('Outport',outputs{k},struct('Port',num2str(k)));end
end
function operations=interfaceExtra(inputs,first)
operations={};for k=1:numel(inputs),operations{end+1}=b('Inport',inputs{k},struct('Port',num2str(first+k-1)));end
end
function operation=b(type,name,params)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',params);
end
function operation=lib(model,export,name,params)
source=find_system(model,'SearchDepth',1,'Name',export);assert(isscalar(source),export);
operation=struct('op','add_block','type',export,'ReferenceBlock',source{1},'name',name,'ref',name,'params',params);
end
function operation=c(source,destination)
operation=struct('op','connect','target',[source ' -> ' destination]);
end
function operations=logging(scope,period)
definitions=sensorless_fw_channels(scope);
if strcmp(scope,'allocation'),mux='AllocationChannels';sink='SaveAllocation';
else,mux='TraceChannels';sink='SaveTrace';end
operations={b('Mux',mux,struct('Inputs',num2str(size(definitions,1)))), ...
    b('ToWorkspace',sink,struct('VariableName',[scope '_trace'],'SaveFormat','Structure With Time', ...
    'SampleTime',period,'MaxDataPoints','inf')),c(['#' mux '.y1'],['#' sink '.u1'])};
for k=1:size(definitions,1),operations{end+1}=c(definitions{k,4},sprintf('#%s.u%d',mux,k));end
end
function operations=scopes(groups)
operations={};
for k=1:size(groups,1)
    name=groups{k,1};signals=groups{k,2};mux=[name 'Channels'];
    operations=[operations,{b('Mux',mux,struct('Inputs',num2str(numel(signals)))), ...
        b('Scope',name,struct('NumInputPorts','1')),c(['#' mux '.y1'],['#' name '.u1'])}];
    for j=1:numel(signals),operations{end+1}=c(signals{j},sprintf('#%s.u%d',mux,j));end
end
end
function operations=resolve(operations,ids)
names=fieldnames(ids);
for k=1:numel(operations)
    if ~isfield(operations{k},'target'),continue;end
    for j=1:numel(names)
        operations{k}.target=strrep(operations{k}.target,['#' names{j} '.'],[ids.(names{j}) '.']);
    end
end
end
function result=edit(model,scope,operations,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(operations),layout);disp(result);
disp(model_read(model,scope,'0'));
if ~contains(string(result),'status: ok')
    disp(model_check(model,scope,'["all"]'));error('Inspect the partial edit before continuing.');
end
if complete
    check=model_check(model,scope,'["all"]');disp(check);assert(~contains(string(check),'severity: error'));
end
end
