    if ismember(k,[3,4,5,6,23,24,25])
        name=sprintf('LogSample%d',k);
        ops=[ops,{b('RateTransition',name,struct('OutPortSampleTimeOpt','Specify','OutPortSampleTime','hfiCfg.Ts', ...
            'Integrity','off','Deterministic','off')),c(source,['#',name,'.u1'])}];
        source=['#',name,'.y1'];
    end
    ops{end+1}=c(source,sprintf('#ControllerTrace.u%d',k));
end
edit(model,scope,ops,true,'full');
end

