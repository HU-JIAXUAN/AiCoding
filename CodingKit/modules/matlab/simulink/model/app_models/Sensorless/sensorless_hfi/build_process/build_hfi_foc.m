    c('#Measurement.y1','#SupervisorUpdate.u3'),c('#Position.y2','#Controller.u2'),c('#Position.y3','#Controller.u3'), ...
    c('#Position.y4','#ControlActive.u2'),c('#Position.y4','#SupervisorUpdate.u2'),c('#Position.y5','#Polarity.u1'), ...
    c('#Position.y6','#Axis.u1'),c('#Polarity.y8','#IsPositivePulse.u1'),c('#Controller.y2','#ControllerSignals.u1'), ...
