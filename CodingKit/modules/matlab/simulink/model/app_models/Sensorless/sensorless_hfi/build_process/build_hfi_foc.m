    b('Logic','MasterActive',struct('Operator','AND','Inputs','3')),b('DataTypeConversion','MasterDouble',struct('OutDataTypeStr','double')), ...
    b('Logic','ControlActive',struct('Operator','AND','Inputs','2')),b('DataTypeConversion','ControlDouble',struct('OutDataTypeStr','double')), ...
    b('Sum','TotalVoltage',struct('Inputs','++')),b('Constant','PositiveStage',struct('Value','3')), ...
    b('RelationalOperator','IsPositivePulse',struct('Operator','==')),b('Sum','AngleDifference',struct('Inputs','+-')), ...
    b('Trigonometry','ErrorSin',struct('Operator','sin')),b('Trigonometry','ErrorCos',struct('Operator','cos')), ...
    b('Trigonometry','AngleError',struct('Operator','atan2')),b('Gain','MechanicalTruth',struct('Gain','1/pmsmCfg.PolePairs'))};
r=edit(model,'root',ops,false,'incremental');p=merge(p,created_from_ops(r,ops));
embed(model,p.SupervisorUpdate,fullfile(module,'src','hfi_foc_supervise.m'));disp(model_read(model,'root','0'));
