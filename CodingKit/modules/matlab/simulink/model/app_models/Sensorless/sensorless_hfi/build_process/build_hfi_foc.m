function ops=interface(inputs,outputs)
ops={};for k=1:numel(inputs),ops{end+1}=b('Inport',inputs{k},struct('Port',num2str(k)));end
for k=1:numel(outputs),ops{end+1}=b('Outport',outputs{k},struct('Port',num2str(k)));end
end
function operation=reference(model,name,instance)
found=find_system(model,'SearchDepth',1,'Name',name);assert(isscalar(found));sid=Simulink.ID.getSID(found{1});source=Simulink.ID.getFullName(sid);
operation=struct('op','add_block','type',get_param(source,'Name'),'ReferenceBlock',source,'name',instance,'ref',instance);
end
function operation=b(type,name,parameters)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',parameters);
end
function operation=c(source,destination)
operation=struct('op','connect','target',[source,' -> ',destination]);
end
function ops=edges_to_ops(edges)
ops=cell(1,size(edges,1));for k=1:size(edges,1),ops{k}=c(['#',edges{k,1},'.y1'],sprintf('#%s.u%d',edges{k,2},edges{k,3}));end
end
function result=edit(model,scope,ops,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(ops),layout);disp(result);disp(model_read(model,scope,'0'));
if ~contains(string(result),'status: ok'),disp(model_check(model,scope,'["all"]'));error('HFIFOC:Edit','%s',char(result));end
if complete,health=model_check(model,scope,'["all"]');disp(health);assert(~contains(string(health),'severity: error'));end
end
function p=created(result,names)
p=struct();for k=1:numel(names),match=regexp(char(result),['(?m)^[ \t]*',regexptranslate('escape',names{k}),':[ \t]*(blk_\d+)'],'tokens');assert(isscalar(match));p.(names{k})=match{1}{1};end
end
function p=created_from_ops(result,ops)
names={};for k=1:numel(ops),if isfield(ops{k},'ref'),names{end+1}=ops{k}.ref;end;end
p=created(result,names);
end
function a=merge(a,b)
names=fieldnames(b);for k=1:numel(names),a.(names{k})=b.(names{k});end
end
function ops=resolve(ops,p)
names=fieldnames(p);for k=1:numel(ops),if isfield(ops{k},'target'),for n=1:numel(names),ops{k}.target=strrep(ops{k}.target,['#',names{n},'.'],[p.(names{n}),'.']);end;end;end
end
function embed(model,id,file)
configuration=get_param(Simulink.ID.getFullName([model,':',extractAfter(id,'blk_')]),'MATLABFunctionConfiguration');configuration.FunctionScript=fileread(file);
end
function ops=scopes(groups)
ops={};for g=1:size(groups,1),name=groups{g,1};sources=groups{g,2};mux=[name,'Channels'];
    ops=[ops,{b('Mux',mux,struct('Inputs',num2str(numel(sources)))),b('Scope',name,struct('NumInputPorts','1')),c(['#',mux,'.y1'],['#',name,'.u1'])}];
    for k=1:numel(sources),ops{end+1}=c(sources{k},sprintf('#%s.u%d',mux,k));end
end
