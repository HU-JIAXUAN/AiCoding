    'VoltageScope',{'#VoltageSignals.y1','#VoltageSignals.y2','#VoltageSignals.y3','#VoltageSignals.y4','#VoltageSignals.y8'}; ...
    'IntegralScope',{'#ControllerSignals.y14','#ControllerSignals.y15','#ControllerSignals.y16','#ControllerSignals.y17'}; ...
    'FrameScope',{'#ControllerSignals.y20','#ControllerSignals.y21','#ControllerSignals.y22'}})];
