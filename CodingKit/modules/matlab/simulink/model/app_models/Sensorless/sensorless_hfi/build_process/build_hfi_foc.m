    b('UnitDelay','Snapshot',struct('InitialCondition','zeros(16,1)','SampleTime','hfiCfg.Ts')),b('Demux','Probe',struct('Outputs','16')), ...
    b('Demux','Voltage',struct('Outputs','2')),b('Demux','Current',struct('Outputs','2')), ...
    reference('HighFrequencyObserver','HFIAxis','Axis'),reference('HighFrequencyObserver','PolarityPulse','Polarity'), ...
    b('UnitDelay','DoneMemory',struct('InitialCondition','0','SampleTime','hfiCfg.Ts')),b('Logic','NotDone',struct('Operator','NOT')), ...
