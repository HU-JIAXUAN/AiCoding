ops=[ops,{b('Mux','StateChannels',struct('Inputs','10')),b('ToWorkspace','LogState',struct('VariableName','state_trace', ...
    'SaveFormat','Structure With Time','SampleTime','hfiCfg.Ts','MaxDataPoints','inf')),c('#StateChannels.y1','#LogState.u1')}];
