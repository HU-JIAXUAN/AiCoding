function build_probe_stage(model,scope)
disp(model_read(model,scope,'0'));path=Simulink.ID.getFullName([model,':',extractAfter(scope,'blk_')]);
names={'voltage_ab','current_ab','enable','reset','snapshot'};ports=struct();
for k=1:numel(names),found=find_system(path,'SearchDepth',1,'Name',names{k});sid=Simulink.ID.getSID(found{1});ports.(names{k})=['blk_',extractAfter(sid,':')];end
ops={b('EnablePort','RunProbe',struct('StatesWhenEnabling','reset')),b('Demux','Voltage',struct('Outputs','2')),b('Demux','Current',struct('Outputs','2')), ...
    struct('op','add_block','type','SaliencyProbe','ReferenceBlock','HighFrequencyObserver/SaliencyProbe','name','Probe','ref','Probe', ...
        'params',struct('MaskValueString','probeCfg','Position','[300 100 640 560]')),b('Mux','Snapshot',struct('Inputs','16')), ...
    struct('op','configure','target',ports.snapshot,'params',struct('OutputWhenDisabled','held','InitialOutput','zeros(16,1)')), ...
    c([ports.voltage_ab,'.y1'],'#Voltage.u1'),c([ports.current_ab,'.y1'],'#Current.u1'), ...
    c([ports.enable,'.y1'],'#Probe.u5'),c([ports.reset,'.y1'],'#Probe.u6'),c('#Snapshot.y1',[ports.snapshot,'.u1'])};
for k=1:2,ops=[ops,{c(sprintf('#Voltage.y%d',k),sprintf('#Probe.u%d',k)),c(sprintf('#Current.y%d',k),sprintf('#Probe.u%d',k+2))}];end
for k=1:16,ops{end+1}=c(sprintf('#Probe.y%d',k),sprintf('#Snapshot.u%d',k));end
edit(model,scope,ops,false,'incremental');
end
function operation=b(type,name,params)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',params);
end
function operation=c(source,destination)
operation=struct('op','connect','target',[source,' -> ',destination]);
end
function result=edit(model,scope,operations,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(operations),layout);disp(result);disp(model_read(model,scope,'0'));
if ~contains(string(result),'status: ok'),disp(model_check(model,scope,'["all"]'));error('HFIStartup:Edit','%s',char(result));end
if complete,health=model_check(model,scope,'["all"]');disp(health);assert(~contains(string(health),'severity: error'));end
end
function value=id(result,name)
matches=regexp(char(result),['(?m)^[ \t]*',regexptranslate('escape',name),':[ \t]*(blk_\d+)'],'tokens');assert(isscalar(matches));value=matches{1}{1};
end
function values=ids(result,names)
values=struct();for k=1:numel(names),values.(names{k})=id(result,names{k});end
end
function ops=resolve(ops,ports)
names=fieldnames(ports);
for k=1:numel(ops)
    if isfield(ops{k},'target')
        for n=1:numel(names),ops{k}.target=strrep(ops{k}.target,['#',names{n},'.'],[ports.(names{n}),'.']);end
    end
end
end
