function build_flying_foc()
%BUILD_FLYING_FOC Physical bridge/PMSM, Flux library and precharged current PI.
assert(strcmp(version('-release'),'2026b'));gate=library.settingsLookup();assert(gate.gatePass);
module=fileparts(fileparts(mfilename('fullpath')));
model='FlyingFluxFOC';destination=fullfile(module,'src',[model,'.slx']);
assert(~bdIsLoaded(model) && ~isfile(destination),'Refusing to overwrite a model.');
for name={'PMSMBridgePlant','FluxObserver','CurrentControl','ClarkePark','Inverter'}
    load_system(name{1});disp(model_read(name{1},'root','0'));
end
new_system(model);initialize_flying_foc(model);
callback=['addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));', ...
    'initialize_flying_foc(bdroot);'];
o={struct('op','configure','target',['config:',model],'params',struct('Solver','FixedStepDiscrete', ...
    'SolverType','Fixed-step','FixedStep','bridgeCfg.Ts','StopTime','experimentCfg.Duration', ...
    'ReturnWorkspaceOutputs','on','PostLoadFcn',callback)), ...
    struct('op','create_subsystem','name','Controller','ref','Controller', ...
    'interface',struct('inputs',{{}},'outputs',{{}}))};
result=edit(model,'root',o,false,'full');controller=createdId(result,'Controller');

inputs={'current_ab','theta','omega','valid','residual','voltage_ab','speed_reference','enable','reset'};
o={};for k=1:numel(inputs)
    dimension=1;if k==1 || k==6,dimension=2;end
    o{end+1}=b('Inport',inputs{k},struct('Port',num2str(k),'SampleTime','currentCfg.Ts', ...
        'PortDimensions',num2str(dimension),'OutDataTypeStr','double'));
end
o=[o,{b('Outport','duty_abc',struct('Port','1','PortDimensions','3')),b('Outport','bridge_mode',struct('Port','2','PortDimensions','1')), ...
    lib('ClarkePark',10,'CurrentPark',''),lib('ClarkePark',10,'VoltagePark',''), ...
    lib('ClarkePark',18,'InversePark',''),lib('CurrentControl',38,'CurrentPI','currentCfg'), ...
    lib('CurrentControl',10,'VoltageLimit',''),lib('Inverter',1,'SVPWM',''), ...
    b('MATLAB Function','Sequence',struct()),b('MATLAB Function','PIResidual',struct()), ...
    b('Demux','CurrentChannels',struct('Outputs','2')),b('Demux','VoltageChannels',struct('Outputs','2')), ...
    b('Mux','CurrentDQ',struct('Inputs','2')),b('Mux','VoltageDQ',struct('Inputs','2')), ...
    b('DotProduct','VoltageSquared',struct()),b('Sqrt','VoltageMagnitude',struct()), ...
    b('Mux','SequenceInput',struct('Inputs','8')),b('UnitDelay','SequenceState', ...
    struct('InitialCondition','zeros(8,1)','SampleTime','currentCfg.Ts')), ...
    b('Constant','SequenceSettings',struct('Value','flyingCfg.Vector')), ...
    b('Demux','SequenceOutput',struct('Outputs','12')),b('Mux','ReferenceDQ',struct('Inputs','2')), ...
    b('Sum','CurrentError',struct('Inputs','+-')),b('Constant','Zero',struct('Value','0')), ...
    b('Constant','ZeroVector',struct('Value','[0;0]')), ...
    b('Constant','ResidualSettings',struct('Value','[currentCfg.Ts;currentCfg.Kid;currentCfg.Kiq]')), ...
    b('Demux','LimitedChannels',struct('Outputs','2')),b('Mux','Duty',struct('Inputs','3')), ...
    b('Terminator','CommonMode',struct()),b('Terminator','LimitScale',struct())}];
for k=7:12,o{end+1}=b('Terminator',sprintf('SequenceDiagnostic%d',k),struct());end
result=edit(model,controller,o,false,'full');sequence=createdId(result,'Sequence');residual=createdId(result,'PIResidual');
embed(model,sequence,fullfile(module,'src','flying_capture_step.m'));
embed(model,residual,fullfile(module,'src','flying_pi_residual.m'));
disp(model_read(model,controller,'0'));
% The existing blocks are resolved from their actual names at this scope.
known=idsAt(model,controller);o={};
links={'current_ab',1,'CurrentChannels',1;'voltage_ab',1,'VoltageChannels',1; ...
    'CurrentChannels',1,'CurrentPark',1;'CurrentChannels',2,'CurrentPark',2;'theta',1,'CurrentPark',3; ...
    'VoltageChannels',1,'VoltagePark',1;'VoltageChannels',2,'VoltagePark',2;'theta',1,'VoltagePark',3; ...
    'CurrentPark',1,'CurrentDQ',1;'CurrentPark',2,'CurrentDQ',2; ...
    'VoltagePark',1,'VoltageDQ',1;'VoltagePark',2,'VoltageDQ',2; ...
    'voltage_ab',1,'VoltageSquared',1;'voltage_ab',1,'VoltageSquared',2;'VoltageSquared',1,'VoltageMagnitude',1; ...
    'CurrentDQ',1,'SequenceInput',1;'omega',1,'SequenceInput',2;'valid',1,'SequenceInput',3; ...
    'residual',1,'SequenceInput',4;'VoltageMagnitude',1,'SequenceInput',5; ...
    'speed_reference',1,'SequenceInput',6;'enable',1,'SequenceInput',7;'reset',1,'SequenceInput',8; ...
    'SequenceState',1,'Sequence',1;'SequenceInput',1,'Sequence',2;'SequenceSettings',1,'Sequence',3; ...
    'Sequence',1,'SequenceState',1;'Sequence',2,'SequenceOutput',1; ...
    'SequenceOutput',1,'ReferenceDQ',1;'SequenceOutput',2,'ReferenceDQ',2; ...
    'SequenceOutput',3,'bridge_mode',1;'ReferenceDQ',1,'CurrentError',1;'CurrentDQ',1,'CurrentError',2; ...
    'CurrentError',1,'CurrentPI',1;'PIResidual',1,'CurrentPI',2;'ZeroVector',1,'CurrentPI',3; ...
    'Zero',1,'CurrentPI',4;'Zero',1,'CurrentPI',5;'SequenceOutput',4,'CurrentPI',6;'SequenceOutput',5,'CurrentPI',7; ...
    'CurrentPI',1,'VoltageLimit',1;'CurrentPI',1,'PIResidual',1;'VoltageLimit',1,'PIResidual',2; ...
    'VoltageDQ',1,'PIResidual',3;'CurrentError',1,'PIResidual',4;'SequenceOutput',6,'PIResidual',5; ...
    'ResidualSettings',1,'PIResidual',6;'VoltageLimit',1,'LimitedChannels',1; ...
    'LimitedChannels',1,'InversePark',1;'LimitedChannels',2,'InversePark',2;'theta',1,'InversePark',3; ...
    'InversePark',1,'SVPWM',1;'InversePark',2,'SVPWM',2; ...
    'SVPWM',1,'Duty',1;'SVPWM',2,'Duty',2;'SVPWM',3,'Duty',3; ...
    'SVPWM',4,'CommonMode',1;'VoltageLimit',2,'LimitScale',1;'Duty',1,'duty_abc',1};
for k=1:size(links,1),o{end+1}=c(port(known,links{k,1},'y',links{k,2}),port(known,links{k,3},'u',links{k,4}));end
for k=7:12,o{end+1}=c(sprintf('%s.y%d',known.SequenceOutput,k),sprintf('%s.u1',known.(sprintf('SequenceDiagnostic%d',k))));end
o=[o,logging('controller'),scopes({'CurrentScope',{'#ReferenceDQ.y1','#CurrentDQ.y1'}; ...
    'VoltageScope',{'#CurrentPI.y1','#VoltageLimit.y1','#VoltageDQ.y1'}; ...
    'SequenceScope',{'#Sequence.y2'}})];
o=resolve(o,known);edit(model,controller,o,true,'incremental');

o={lib('PMSMBridgePlant',1,'Plant','bridgeCfg'),lib('FluxObserver',1,'Estimator','fluxCfg|pllCfg'), ...
    b('FromWorkspace','Stimulus',struct('VariableName','flyingStim','Interpolate','off', ...
    'SampleTime','currentCfg.Ts','OutputAfterFinalValue','Holding final value')), ...
    b('Demux','Inputs',struct('Outputs','5')),b('ZeroOrderHold','CurrentSample',struct('SampleTime','currentCfg.Ts')), ...
    b('UnitDelay','VoltageCompleted',struct('InitialCondition','zeros(2,1)','SampleTime','bridgeCfg.Ts')), ...
    b('ZeroOrderHold','VoltageSample',struct('SampleTime','currentCfg.Ts')), ...
    b('Demux','CurrentChannels',struct('Outputs','2')),b('Demux','VoltageChannels',struct('Outputs','2')), ...
    b('Logic','ObserverEnabled',struct('Operator','AND','Inputs','2')), ...
    b('DataTypeConversion','ObserverEnableDouble',struct('OutDataTypeStr','double')), ...
    b('MATLAB Function','AgeAlign',struct()),b('Constant','MeasurementAge',struct('Value','bridgeCfg.Ts/2')), ...
    b('Gain','EstimateMechanical',struct('Gain','1/bridgeCfg.PolePairs'))};
result=edit(model,'root',o,false,'incremental');age=createdId(result,'AgeAlign');
embed(model,age,fullfile(module,'src','flying_angle_align.m'));disp(model_read(model,'root','0'));
known=idsAt(model,'root');o={};
links={'Stimulus',1,'Inputs',1;'Controller',1,'Plant',1;'Controller',2,'Plant',2;'Inputs',2,'Plant',3; ...
    'Plant',1,'CurrentSample',1;'Plant',4,'VoltageCompleted',1;'VoltageCompleted',1,'VoltageSample',1; ...
    'CurrentSample',1,'CurrentChannels',1;'VoltageSample',1,'VoltageChannels',1; ...
    'VoltageChannels',1,'Estimator',1;'VoltageChannels',2,'Estimator',2; ...
    'CurrentChannels',1,'Estimator',3;'CurrentChannels',2,'Estimator',4; ...
    'Inputs',3,'ObserverEnabled',1;'Inputs',5,'ObserverEnabled',2; ...
    'ObserverEnabled',1,'ObserverEnableDouble',1;'ObserverEnableDouble',1,'Estimator',5;'Inputs',4,'Estimator',6; ...
    'Estimator',1,'AgeAlign',1;'Estimator',2,'AgeAlign',2;'VoltageSample',1,'AgeAlign',3;'MeasurementAge',1,'AgeAlign',4; ...
    'CurrentSample',1,'Controller',1;'AgeAlign',1,'Controller',2;'Estimator',2,'Controller',3; ...
    'Estimator',3,'Controller',4;'Estimator',12,'Controller',5;'AgeAlign',2,'Controller',6; ...
    'Inputs',1,'Controller',7;'Inputs',3,'Controller',8;'Inputs',4,'Controller',9; ...
    'Estimator',2,'EstimateMechanical',1};
for k=1:size(links,1),o{end+1}=c(port(known,links{k,1},'y',links{k,2}),port(known,links{k,3},'u',links{k,4}));end
o=[o,logging('plant'),logging('observer'),scopes({'AngleScope',{'#Plant.y6','#Estimator.y1','#AgeAlign.y1'}; ...
    'SpeedScope',{'#Plant.y5','#EstimateMechanical.y1','#Inputs.y1'}; ...
    'OffCurrentScope',{'#Plant.y2','#Plant.y8'}; ...
    'ModeScope',{'#Controller.y2','#Estimator.y3','#Inputs.y3','#Inputs.y4'}})];
o=resolve(o,known);edit(model,'root',o,true,'incremental');
save_system(model,destination);close_system(model,0);
end
function operation=lib(model,sid,name,mask)
source=Simulink.ID.getFullName(sprintf('%s:%d',model,sid));
operation=struct('op','add_block','type',get_param(source,'Name'),'ReferenceBlock',source,'name',name,'ref',name);
if ~isempty(mask),operation.params=struct('MaskValueString',mask);end
end
function operation=b(type,name,parameters)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',parameters);
end
function operation=c(source,destination)
operation=struct('op','connect','target',[source,' -> ',destination]);
end
function id=createdId(result,reference)
match=regexp(char(result),['(?m)^\s*',reference,':\s*(blk_\d+)\s*$'],'tokens');assert(isscalar(match));id=match{1}{1};
end
function result=edit(model,scope,operations,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(operations),layout);disp(result);
disp(model_read(model,scope,'0'));
if ~contains(string(result),'status: ok')
    disp(model_check(model,scope,'["all"]'));error('Inspect the partial model before proceeding.');
end
if complete
    check=model_check(model,scope,'["all"]');disp(check);assert(~contains(string(check),'severity: error'));
end
end
function ids=idsAt(model,scope)
if strcmp(scope,'root'),owner=model;else,owner=Simulink.ID.getFullName([model,':',extractAfter(scope,'blk_')]);end
blocks=find_system(owner,'SearchDepth',1,'Type','Block');ids=struct();
for k=1:numel(blocks)
    if strcmp(blocks{k},owner),continue,end
    ids.(get_param(blocks{k},'Name'))=['blk_',extractAfter(Simulink.ID.getSID(blocks{k}),':')];
end
end
function value=port(ids,name,kind,index)
value=sprintf('%s.%s%d',ids.(name),kind,index);
end
function operations=resolve(operations,ids)
names=fieldnames(ids);
for k=1:numel(operations)
    if isfield(operations{k},'target')
        for j=1:numel(names),operations{k}.target=strrep(operations{k}.target,['#',names{j},'.'],[ids.(names{j}),'.']);end
    end
end
end
function embed(model,id,source)
block=Simulink.ID.getFullName([model,':',extractAfter(id,'blk_')]);
configuration=get_param(block,'MATLABFunctionConfiguration');configuration.FunctionScript=fileread(source);
end
function operations=logging(scope)
definitions=flying_foc_channels(scope);mux=[scope,'Trace'];
operations={b('Mux',mux,struct('Inputs',num2str(size(definitions,1)))), ...
    b('ToWorkspace',[scope,'Save'],struct('VariableName',[scope,'_trace'],'SaveFormat','Structure With Time', ...
    'SampleTime','currentCfg.Ts','MaxDataPoints','inf')),c(['#',mux,'.y1'],['#',scope,'Save.u1'])};
for k=1:size(definitions,1),operations{end+1}=c(definitions{k,4},sprintf('#%s.u%d',mux,k));end
end
function operations=scopes(groups)
operations={};
for k=1:size(groups,1)
    name=groups{k,1};sources=groups{k,2};mux=[name,'Channels'];
    operations=[operations,{b('Mux',mux,struct('Inputs',num2str(numel(sources)))), ...
        b('Scope',name,struct('NumInputPorts','1')),c(['#',mux,'.y1'],['#',name,'.u1'])}];
    for j=1:numel(sources),operations{end+1}=c(sources{j},sprintf('#%s.u%d',mux,j));end
end
end
