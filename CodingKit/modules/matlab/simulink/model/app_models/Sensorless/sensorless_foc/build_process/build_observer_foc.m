function build_observer_foc(kind,templateFile)
%BUILD_OBSERVER_FOC Preserve the physical FOC and rebuild only its observer.
%   BUILD_OBSERVER_FOC('eemf'|'flux') creates a sibling of SensorlessFOC.
%   The optional template path supports rebuilding in an isolated folder.
assert(strcmp(version('-release'),'2026b'));
gate=library.settingsLookup();assert(gate.gatePass);
kind=char(validatestring(kind,{'eemf','flux'}));
module=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(module,'parameter'),fileparts(mfilename('fullpath')));
if nargin<2,templateFile=fullfile(module,'src','SensorlessFOC.slx');end
if strcmp(kind,'eemf'),model='EemfSensorlessFOC';libraryName='EmfObserver';export='EEMF';
else,model='FluxSensorlessFOC';libraryName='FluxObserver';export='Flux';end
destination=fullfile(module,'src',[model,'.slx']);
assert(~bdIsLoaded(model) && ~isfile(destination),'Refusing to overwrite an App.');
assert(isfile(templateFile));if ~isfolder(fileparts(destination)),mkdir(fileparts(destination));end
load_system(templateFile);template=erase(string(templateFile),'.slx');
[~,template]=fileparts(template);assert(strcmp(get_param(template,'Dirty'),'off'));
assert(strcmp(get_param(template,'Open'),'off'),'Close the source model editor before rebuilding.');
save_system(template,destination); % Save As: template bytes remain unchanged.
initialize_observer_foc(model,kind);
callback=sprintf(['addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),', ...
    '''..'',''build_process''));initialize_observer_foc(bdroot,''%s'');'],kind);
edit(model,'root',{struct('op','configure','target',['config:',model], ...
    'params',struct('PostLoadFcn',callback))},false,'incremental');
rootNames={'Observer','Measurement','VoltageStage','ObserverEnabledDouble','inputs','Controller'};
rootIds=struct();
for k=1:numel(rootNames),rootIds.(rootNames{k})=blockId(model,rootNames{k});end
result=edit(model,'root',{struct('op','delete','target',rootIds.Observer), ...
    struct('op','create_subsystem','name','Observer','ref','Observer', ...
    'interface',struct('inputs',{{}},'outputs',{{}}))},false,'incremental');
rootIds.Observer=createdId(result,'Observer');
load_system(libraryName);disp(model_read(libraryName,'root','0'));
source=find_system(libraryName,'SearchDepth',1,'Name',export);assert(isscalar(source));
disp(model_read(model,rootIds.Observer,'0'));
ins={'phase_voltage','current_ab','enable','reset','direction'};
outs={'theta_hat','omega_hat','valid','residual_norm'};o={};
for k=1:numel(ins),o{end+1}=b('Inport',ins{k},struct('Port',num2str(k)));end
for k=1:numel(outs),o{end+1}=b('Outport',outs{k},struct('Port',num2str(k)));end
if strcmp(kind,'eemf'),mask='emfCfg|pllCfg';else,mask='fluxCfg|pllCfg';end
o=[o,{b('Demux','PhaseChannels',struct('Outputs','3')), ...
    struct('op','add_block','type','Clarke','ReferenceBlock','ClarkePark/Clarke','name','VoltageClarke','ref','VoltageClarke'), ...
    b('Mux','VoltageAB',struct('Inputs','2')), ...
    b('ZeroOrderHold','VoltageSample',struct('SampleTime','timingCfg.Ts')), ...
    b('Delay','VoltageAge',struct('SampleTime','timingCfg.Ts', ...
    'DelayLength','timingCfg.FeedbackTicks*experimentCfg.UseTiming','InitialCondition','0')), ...
    b('Demux','VoltageChannels',struct('Outputs','2')),b('Demux','CurrentChannels',struct('Outputs','2')), ...
    struct('op','add_block','type',export,'ReferenceBlock',source{1}, ...
    'name','Estimator','ref','Estimator','params',struct('MaskValueString',mask)), ...
    b('Terminator','ZeroSequence',struct()),c('#phase_voltage.y1','#PhaseChannels.u1'), ...
    c('#current_ab.y1','#CurrentChannels.u1'),c('#VoltageClarke.y1','#VoltageAB.u1'), ...
    c('#VoltageClarke.y2','#VoltageAB.u2'),c('#VoltageClarke.y3','#ZeroSequence.u1'), ...
    c('#VoltageAB.y1','#VoltageSample.u1'),c('#VoltageSample.y1','#VoltageAge.u1'), ...
    c('#VoltageAge.y1','#VoltageChannels.u1'),c('#VoltageChannels.y1','#Estimator.u1'), ...
    c('#VoltageChannels.y2','#Estimator.u2'),c('#CurrentChannels.y1','#Estimator.u3'), ...
    c('#CurrentChannels.y2','#Estimator.u4'),c('#Estimator.y1','#theta_hat.u1'), ...
    c('#Estimator.y2','#omega_hat.u1'),c('#Estimator.y3','#valid.u1')}];
for k=1:3,o{end+1}=c(sprintf('#PhaseChannels.y%d',k),sprintf('#VoltageClarke.u%d',k));end
if strcmp(kind,'eemf')
    o=[o,{b('Mux','ResidualAB',struct('Inputs','2')),b('DotProduct','SquaredResidual',struct()), ...
        b('Sqrt','ResidualNorm',struct()),c('#direction.y1','#Estimator.u5'), ...
        c('#enable.y1','#Estimator.u6'),c('#reset.y1','#Estimator.u7'), ...
        c('#Estimator.y8','#ResidualAB.u1'),c('#Estimator.y9','#ResidualAB.u2'), ...
        c('#ResidualAB.y1','#SquaredResidual.u1'),c('#ResidualAB.y1','#SquaredResidual.u2'), ...
        c('#SquaredResidual.y1','#ResidualNorm.u1'),c('#ResidualNorm.y1','#residual_norm.u1')}];
    diagnostic={'EmfScope',{'#Estimator.y4','#Estimator.y5','#Estimator.y11'}; ...
        'ResidualScope',{'#Estimator.y8','#Estimator.y9','#ResidualNorm.y1'}};
else
    o=[o,{b('Terminator','UnusedDirection',struct()),c('#direction.y1','#UnusedDirection.u1'), ...
        c('#enable.y1','#Estimator.u5'),c('#reset.y1','#Estimator.u6'),c('#Estimator.y12','#residual_norm.u1')}];
    diagnostic={'FluxScope',{'#Estimator.y4','#Estimator.y5','#Estimator.y8'}; ...
        'QualityScope',{'#Estimator.y12','#Estimator.y13','#Estimator.y14'}};
end
definitions=observer_foc_channels('observer',kind);
o=[o,{b('Mux','TraceChannels',struct('Inputs',num2str(size(definitions,1)))), ...
    b('ToWorkspace','SaveTrace',struct('VariableName','observer_trace', ...
    'SaveFormat','Structure With Time','SampleTime','currentCfg.Ts','MaxDataPoints','inf')), ...
    c('#TraceChannels.y1','#SaveTrace.u1')}];
for k=1:size(definitions,1),o{end+1}=c(definitions{k,4},sprintf('#TraceChannels.u%d',k));end
groups=[{'EstimateAngleScope',{'#Estimator.y1'};'EstimateSpeedScope',{'#Estimator.y2'}};diagnostic; ...
    {'ValidityScope',{'#Estimator.y3','#enable.y1','#reset.y1'}}];
for k=1:size(groups,1)
    name=groups{k,1};sources=groups{k,2};mux=[name,'Channels'];
    o=[o,{b('Mux',mux,struct('Inputs',num2str(numel(sources)))), ...
        b('Scope',name,struct('NumInputPorts','1')),c(['#',mux,'.y1'],['#',name,'.u1'])}];
    for j=1:numel(sources),o{end+1}=c(sources{j},sprintf('#%s.u%d',mux,j));end
end
edit(model,rootIds.Observer,o,true,'full');
o={c([rootIds.VoltageStage,'.y8'],[rootIds.Observer,'.u1']), ...
    c([rootIds.Measurement,'.y1'],[rootIds.Observer,'.u2']), ...
    c([rootIds.ObserverEnabledDouble,'.y1'],[rootIds.Observer,'.u3']), ...
    c([rootIds.inputs,'.y4'],[rootIds.Observer,'.u4']),c([rootIds.inputs,'.y5'],[rootIds.Observer,'.u5'])};
for k=1:4,o{end+1}=c(sprintf('%s.y%d',rootIds.Observer,k),sprintf('%s.u%d',rootIds.Controller,k+1));end
edit(model,'root',o,true,'incremental');save_system(model,destination);close_system(model,0);
end
function value=blockId(model,name)
matches=find_system(model,'SearchDepth',1,'Name',name);assert(isscalar(matches));
value=['blk_',extractAfter(Simulink.ID.getSID(matches{1}),':')];
end
function operation=b(type,name,parameters)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',parameters);
end
function operation=c(source,destination)
operation=struct('op','connect','target',[source,' -> ',destination]);
end
function id=createdId(result,reference)
match=regexp(char(result),[reference,':\s*(blk_\d+)'],'tokens');assert(isscalar(match));id=match{1}{1};
end
function result=edit(model,scope,operations,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(operations),layout);disp(result);
disp(model_read(model,scope,'0'));
if ~contains(string(result),'status: ok')
    disp(model_check(model,scope,'["all"]'));error('Inspect the partial edit before continuing.');
end
if complete
    check=model_check(model,scope,'["all"]');disp(check);assert(~contains(string(check),'severity: error'));
end
end
