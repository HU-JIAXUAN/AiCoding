function operations=interface(inputs,outputs)
operations={};
for index=1:numel(inputs),operations{end+1}=b('Inport',inputs{index},struct('Port',num2str(index)));end
for index=1:numel(outputs),operations{end+1}=b('Outport',outputs{index},struct('Port',num2str(index)));end
end
function operations=logging(scope)
definitions=sensorless_foc_channels(scope);
operations={b('Mux','TraceChannels',struct('Inputs',num2str(size(definitions,1)))), ...
    b('ToWorkspace','SaveTrace',struct('VariableName',[scope,'_trace'],'SaveFormat','Structure With Time', ...
    'SampleTime','currentCfg.Ts','MaxDataPoints','inf')),c('#TraceChannels.y1','#SaveTrace.u1')};
for index=1:size(definitions,1)
    source=definitions{index,4};
    if strcmp(scope,'controller') && ismember(definitions{index,1},{'speed_reference','speed_error','torque_estimated','auto_sampled'})
        rateName=['LogRate_',definitions{index,1}];
        operations=[operations,{b('RateTransition',rateName,struct('OutPortSampleTimeOpt','Specify', ...
            'OutPortSampleTime','currentCfg.Ts','Integrity','off','Deterministic','off')),c(source,['#',rateName,'.u1'])}];
        source=['#',rateName,'.y1'];
    end
    operations{end+1}=c(source,sprintf('#TraceChannels.u%d',index));
end
end
function operations=scopes(groups)
operations={};
for group=1:size(groups,1)
    name=groups{group,1};sources=groups{group,2};mux=[name,'_mux'];
    operations=[operations,{b('Mux',mux,struct('Inputs',num2str(numel(sources)))),b('Scope',name,struct('NumInputPorts','1')), ...
        c(['#',mux,'.y1'],['#',name,'.u1'])}];
    for index=1:numel(sources),operations{end+1}=c(sources{index},sprintf('#%s.u%d',mux,index));end
end
end
function operation=lib(model,sid,name)
source=Simulink.ID.getFullName(sprintf('%s:%d',model,sid));
operation=struct('op','add_block','type',get_param(source,'Name'),'ReferenceBlock',source,'name',name,'ref',name);
end
function operation=b(type,name,parameters)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',parameters);
end
function operation=c(source,destination)
operation=struct('op','connect','target',[source,' -> ',destination]);
end
function id=createdId(result,reference)
