function definitions=flying_foc_channels(scope)
%FLYING_FOC_CHANNELS Actual logged source order, widths and SI units.
switch scope
    case 'plant'
        names={'current_ab','phase_current','phase_voltage','voltage_ab','speed_m', ...
            'theta_e','torque','dc_current','diode_states','magnetic_energy', ...
            'kinetic_energy','bridge_loss','equation_residual','next_phase_current', ...
            'neutral_voltage','pole_voltage'};
        widths=[2,3,3,2,1,1,1,1,3,1,1,1,1,3,1,3];
        units={'A','A','V','V','rad/s','rad','N*m','A','1','J','J','W','V','A','V','V'};
        definitions=cell(0,4);
        for k=1:numel(names),definitions(end+1,:)={names{k},widths(k),units{k},sprintf('#Plant.y%d',k)};end
        definitions=[definitions;{'bridge_mode',1,'1','#Controller.y2'; ...
            'stimulus',5,'rad/s,N*m,1,1,1','#Stimulus.y1'}];
    case 'observer'
        names={'theta_raw','omega_e','valid','rotor_flux_alpha','rotor_flux_beta', ...
            'stator_flux_alpha','stator_flux_beta','flux_magnitude','torque_hat', ...
            'phase_measured','phase_error','equivalent_residual','filtered_speed','compensation_ready'};
        units={'rad','rad/s','1','Wb','Wb','Wb','Wb','Wb','N*m','rad','rad','A_equivalent','rad/s','1'};
        definitions={'sampled_current_ab',2,'A','#CurrentSample.y1'; ...
            'sampled_voltage_ab',2,'V','#VoltageSample.y1'};
        for k=1:numel(names),definitions(end+1,:)={names{k},1,units{k},sprintf('#Estimator.y%d',k)};end
        definitions(end+1,:)={'theta_used',1,'rad','#AgeAlign.y1'};
    case 'controller'
        definitions={'sequence',12,'mixed_SI','#Sequence.y2';'measured_dq',2,'A','#CurrentDQ.y1'; ...
            'error_dq',2,'A','#CurrentError.y1';'pi_voltage',2,'V','#CurrentPI.y1'; ...
            'limited_voltage',2,'V','#VoltageLimit.y1';'integral_base',2,'V','#CurrentPI.y2'; ...
            'integral_state',2,'V','#CurrentPI.y3';'pi_residual',2,'V','#PIResidual.y1'; ...
            'duty_abc',3,'1','#Duty.y1'};
    otherwise,error('Unknown flying trace scope.');
end
end
