function build_angle_tracking()
%BUILD_ANGLE_TRACKING Rebuild the visible-block PLL library and its test model.
% Requires R2026b, Simulink and the Simulink Agentic Toolkit on the MATLAB path.
assert(strcmp(version('-release'),'2026b'),'Build with MATLAB R2026b.');
gate=library.settingsLookup(); assert(gate.gatePass);
module=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(module,'parameter'),fullfile(module,'src'),fileparts(mfilename('fullpath')));
assert(~bdIsLoaded('AngleTracking') && ~bdIsLoaded('AngleTrackingTest'), ...
    'Close these two models before rebuilding.');
assert(~isfile(fullfile(module,'src','AngleTracking.slx')), ...
    'Source model already exists. Rebuild in a separate copy.');
new_system('AngleTracking','Library');
open_system('AngleTracking');
editScope('AngleTracking','root',{struct('op','create_subsystem','name','PLL', ...
    'ref','pll','interface',struct('inputs',{{}},'outputs',{{}})), ...
    struct('op','configure','target','#pll','params',struct('Mask','on', ...
    'MaskVariables','pllCfg=@1;','MaskStyleString','edit', ...
    'MaskPromptString','PLL configuration','MaskValueString','pllCfg'))});
sid=Simulink.ID.getSID('AngleTracking/PLL');
scope=['blk_',extractAfter(sid,':')];
o={};
inputs={'phase','magnitude','enable','reset'};
for k=1:numel(inputs), o{end+1}=b('Inport',inputs{k},struct('Port',num2str(k),'SampleTime','pllCfg.Ts')); end
outputs={'theta_e_hat','omega_e_hat','phase_error','valid','integral','lock_count'};
for k=1:numel(outputs), o{end+1}=b('Outport',outputs{k},struct('Port',num2str(k))); end
o=[o,{b('Constant','zero',struct('Value','0')),b('Constant','one',struct('Value','1')), ...
    b('Constant','theta0',struct('Value','pllCfg.Theta0')), ...
    b('Constant','omega0',struct('Value','pllCfg.Omega0')), ...
    b('Logic','not_reset',struct('Operator','NOT')),b('Logic','active',struct('Operator','AND','Inputs','2')), ...
    b('RelationalOperator','amplitude_ok',struct('Operator','>=')), ...
    b('Constant','min_magnitude',struct('Value','pllCfg.MinMagnitude')), ...
    b('Logic','update_ok',struct('Operator','AND','Inputs','2')), ...
    b('UnitDelay','theta_state',struct('InitialCondition','pllCfg.Theta0','SampleTime','pllCfg.Ts')), ...
    b('UnitDelay','integral_state',struct('InitialCondition','pllCfg.Omega0','SampleTime','pllCfg.Ts')), ...
    b('UnitDelay','count_state',struct('InitialCondition','0','SampleTime','pllCfg.Ts')), ...
    b('Sum','phase_delta',struct('Inputs','+-'))}];
o=[o,wrapBlocks('error_wrap')];
o=[o,{b('Gain','proportional',struct('Gain','pllCfg.Kp')), ...
    b('Sum','speed_raw',struct('Inputs','++')), ...
    b('Saturate','speed_limit',struct('UpperLimit','pllCfg.OmegaMax','LowerLimit','-pllCfg.OmegaMax')), ...
    b('Sum','limit_residual',struct('Inputs','+-')), ...
    b('Gain','back_calculation',struct('Gain','pllCfg.Kaw')), ...
    b('Gain','integral_gain',struct('Gain','pllCfg.Ki')), ...
    b('Sum','integral_rate',struct('Inputs','++')), ...
    b('Gain','integral_step',struct('Gain','pllCfg.Ts')), ...
    b('Sum','integral_candidate',struct('Inputs','++')), ...
    b('Saturate','integral_limit',struct('UpperLimit','pllCfg.OmegaMax','LowerLimit','-pllCfg.OmegaMax')), ...
    b('Gain','angle_step',struct('Gain','pllCfg.Ts')),b('Sum','angle_candidate',struct('Inputs','++')), ...
    sw('angle_hold'),sw('integral_hold'),sw('angle_reset'),sw('integral_reset'), ...
    sw('angle_output'),sw('speed_output'),sw('error_output'),sw('integral_output'), ...
    b('Abs','abs_error',struct()),b('Constant','lock_error',struct('Value','pllCfg.LockError')), ...
    b('RelationalOperator','phase_ok',struct('Operator','<=')), ...
    b('Logic','qualified',struct('Operator','AND','Inputs','2')), ...
    b('Sum','count_increment',struct('Inputs','++')), ...
    b('Saturate','count_limit',struct('UpperLimit','pllCfg.LockSamples','LowerLimit','0')), ...
    sw('count_reset'),b('Constant','lock_samples',struct('Value','pllCfg.LockSamples')), ...
    b('RelationalOperator','count_ok',struct('Operator','>=')), ...
    b('Logic','valid_logic',struct('Operator','AND','Inputs','2')), ...
    b('DataTypeConversion','valid_double',struct('OutDataTypeStr','double'))}];
o=[o,wrapBlocks('angle_wrap')];
edges={ 'reset','not_reset',1; 'enable','active',1; 'not_reset','active',2; ...
    'magnitude','amplitude_ok',1; 'min_magnitude','amplitude_ok',2; ...
    'active','update_ok',1; 'amplitude_ok','update_ok',2; ...
    'phase','phase_delta',1; 'theta_state','phase_delta',2; ...
    'phase_delta','error_wrap_sin',1; 'phase_delta','error_wrap_cos',1; ...
    'error_wrap','proportional',1; 'proportional','speed_raw',1; 'integral_state','speed_raw',2; ...
    'speed_raw','speed_limit',1; 'speed_limit','limit_residual',1; 'speed_raw','limit_residual',2; ...
    'limit_residual','back_calculation',1; 'error_wrap','integral_gain',1; ...
    'integral_gain','integral_rate',1; 'back_calculation','integral_rate',2; ...
    'integral_rate','integral_step',1; 'integral_step','integral_candidate',1; 'integral_state','integral_candidate',2; ...
    'integral_candidate','integral_limit',1; 'speed_limit','angle_step',1; ...
    'angle_step','angle_candidate',1; 'theta_state','angle_candidate',2; ...
    'angle_candidate','angle_wrap_sin',1; 'angle_candidate','angle_wrap_cos',1; ...
    'angle_wrap','angle_hold',1; 'update_ok','angle_hold',2; 'theta_state','angle_hold',3; ...
    'integral_limit','integral_hold',1; 'update_ok','integral_hold',2; 'integral_state','integral_hold',3; ...
    'angle_hold','angle_reset',1; 'active','angle_reset',2; 'theta0','angle_reset',3; ...
    'integral_hold','integral_reset',1; 'active','integral_reset',2; 'omega0','integral_reset',3; ...
    'angle_reset','theta_state',1; 'integral_reset','integral_state',1; ...
    'theta_state','angle_output',1; 'active','angle_output',2; 'theta0','angle_output',3; ...
    'speed_limit','speed_output',1; 'update_ok','speed_output',2; 'zero','speed_output',3; ...
    'error_wrap','error_output',1; 'update_ok','error_output',2; 'zero','error_output',3; ...
    'integral_state','integral_output',1; 'active','integral_output',2; 'omega0','integral_output',3; ...
    'error_wrap','abs_error',1; 'abs_error','phase_ok',1; 'lock_error','phase_ok',2; ...
    'phase_ok','qualified',1; 'update_ok','qualified',2; ...
    'count_state','count_increment',1; 'one','count_increment',2; 'count_increment','count_limit',1; ...
    'count_limit','count_reset',1; 'qualified','count_reset',2; 'zero','count_reset',3; ...
    'count_reset','count_state',1; 'count_state','count_ok',1; 'lock_samples','count_ok',2; ...
    'count_ok','valid_logic',1; 'qualified','valid_logic',2; 'valid_logic','valid_double',1; ...
    'angle_output','theta_e_hat',1; 'speed_output','omega_e_hat',1; 'error_output','phase_error',1; ...
    'valid_double','valid',1; 'integral_output','integral',1; 'count_reset','lock_count',1};
o=wire(o,edges); editScope('AngleTracking',scope,o);
save_system('AngleTracking',fullfile(module,'src','AngleTracking.slx'));
new_system('AngleTrackingTest'); open_system('AngleTrackingTest');
initialize_angle_tracking_test('AngleTrackingTest');
cb=['addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));', ...
    'initialize_angle_tracking_test(bdroot);'];
o={struct('op','configure','target','config:AngleTrackingTest','params', ...
    struct('Solver','FixedStepDiscrete','SolverType','Fixed-step','FixedStep','pllCfg.Ts', ...
    'StopTime','pllTestCfg.Duration','ReturnWorkspaceOutputs','on','PostLoadFcn',cb)), ...
    b('FromWorkspace','stimulus',struct('VariableName','testStim','Interpolate','off','SampleTime','pllCfg.Ts','OutputAfterFinalValue','Holding final value')), ...
    b('Demux','inputs',struct('Outputs','6')), ...
    struct('op','add_block','type','PLL','ReferenceBlock','AngleTracking/PLL','name','PLL','ref','pll'), ...
    b('Mux','trace_mux',struct('Inputs','12')), ...
    b('ToWorkspace','trace',struct('VariableName','trace','SaveFormat','Structure With Time','MaxDataPoints','inf')), ...
    b('Mux','angle_channels',struct('Inputs','3')),b('Scope','AngleScope',struct('NumInputPorts','1')), ...
    b('Mux','speed_channels',struct('Inputs','3')),b('Scope','SpeedScope',struct('NumInputPorts','1')), ...
    b('Mux','status_channels',struct('Inputs','5')),b('Scope','StatusScope',struct('NumInputPorts','1'))};
o{end+1}=c('#stimulus.y1','#inputs.u1');
for k=1:4, o{end+1}=c(sprintf('#inputs.y%d',k),sprintf('#pll.u%d',k)); end
for k=1:6
    o{end+1}=c(sprintf('#inputs.y%d',k),sprintf('#trace_mux.u%d',k));
    o{end+1}=c(sprintf('#pll.y%d',k),sprintf('#trace_mux.u%d',k+6));
end
o=[o,{c('#trace_mux.y1','#trace.u1'),c('#inputs.y1','#angle_channels.u1','phase_input'), ...
    c('#pll.y1','#angle_channels.u2','theta_e_hat'),c('#pll.y3','#angle_channels.u3','phase_error'), ...
    c('#inputs.y6','#speed_channels.u1','omega_true'),c('#pll.y2','#speed_channels.u2','omega_e_hat'),c('#pll.y5','#speed_channels.u3','integral'), ...
    c('#inputs.y2','#status_channels.u1','magnitude'),c('#inputs.y3','#status_channels.u2','enable'), ...
    c('#inputs.y4','#status_channels.u3','reset'),c('#pll.y4','#status_channels.u4','valid'),c('#pll.y6','#status_channels.u5','lock_count'), ...
    c('#angle_channels.y1','#AngleScope.u1'),c('#speed_channels.y1','#SpeedScope.u1'),c('#status_channels.y1','#StatusScope.u1')}];
editScope('AngleTrackingTest','root',o);
save_system('AngleTrackingTest',fullfile(module,'src','AngleTrackingTest.slx'));
print('-sAngleTracking/PLL','-dpng',fullfile(module,'build_process','pll_diagram.png'));
print('-sAngleTrackingTest','-dpng',fullfile(module,'build_process','test_diagram.png'));
end

function s=b(type,name,params)
s=struct('op','add_block','type',type,'name',name,'ref',name,'params',params);
end
function s=sw(name)
s=b('Switch',name,struct('Criteria','u2 > Threshold','Threshold','0.5'));
end
function s=c(source,destination,name)
s=struct('op','connect','target',[source,' -> ',destination]);
if nargin>2,s.params=struct('Name',name);end
end
function o=wire(o,edges)
for k=1:size(edges,1), o{end+1}=c(['#',edges{k,1},'.y1'],sprintf('#%s.u%d',edges{k,2},edges{k,3})); end
end
function o=wrapBlocks(name)
o={b('Trigonometry',[name,'_sin'],struct('Operator','sin')), ...
   b('Trigonometry',[name,'_cos'],struct('Operator','cos')), ...
   b('Trigonometry',name,struct('Operator','atan2')), ...
   c(['#',name,'_sin.y1'],['#',name,'.u1']),c(['#',name,'_cos.y1'],['#',name,'.u2'])};
end
function editScope(model,scope,operations)
disp(model_read(model,scope,'0'));
r=model_edit(model,scope,jsonencode(operations),'full'); disp(r);
disp(model_read(model,scope,'0')); check=model_check(model,scope,'["all"]'); disp(check);
assert(contains(string(r),'status: ok') && ~contains(string(check),'severity: error'), ...
    'Inspect the editor or structural-check result before continuing.');
end
