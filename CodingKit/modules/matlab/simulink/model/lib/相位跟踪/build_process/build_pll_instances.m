function build_pll_instances()
%BUILD_PLL_INSTANCES Build the two-instance configuration isolation model.
assert(strcmp(version('-release'),'2026b'));
gate=library.settingsLookup();assert(gate.gatePass);
module=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(module,'parameter'),fullfile(module,'src'),fullfile(module,'build_process'));
model='AngleTrackingInstancesTest';
assert(~bdIsLoaded(model) && ~isfile(fullfile(module,'src',[model,'.slx'])));
load_system(fullfile(module,'src','AngleTracking.slx'));
new_system(model);open_system(model);initialize_pll_instances(model);
callback=['addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));', ...
    'initialize_pll_instances(bdroot);'];
operations={struct('op','configure','target',['config:',model],'params', ...
    struct('Solver','FixedStepDiscrete','SolverType','Fixed-step','FixedStep','pllA.Ts', ...
    'StopTime','0.03','ReturnWorkspaceOutputs','on','PostLoadFcn',callback)), ...
    block('Constant','phase',struct('Value','0.1')), ...
    block('Constant','one',struct('Value','1')),block('Constant','zero',struct('Value','0')), ...
    struct('op','add_block','type','PLL','ReferenceBlock','AngleTracking/PLL', ...
    'name','PLL_A','ref','pll_a','params',struct('MaskValueString','pllA')), ...
    struct('op','add_block','type','PLL','ReferenceBlock','AngleTracking/PLL', ...
    'name','PLL_B','ref','pll_b','params',struct('MaskValueString','pllB')), ...
    block('Mux','trace_mux',struct('Inputs','4')), ...
    block('Mux','angles',struct('Inputs','2')),block('Mux','speeds',struct('Inputs','2')), ...
    block('Scope','AngleScope',struct('NumInputPorts','1')), ...
    block('Scope','SpeedScope',struct('NumInputPorts','1')), ...
    block('ToWorkspace','trace',struct('VariableName','trace', ...
    'SaveFormat','Structure With Time','MaxDataPoints','inf'))};
for index=1:2
    name=char('a'+index-1);reference=['#pll_',name];
    operations=[operations,{connect('#phase.y1',[reference,'.u1']), ...
        connect('#one.y1',[reference,'.u2']),connect('#one.y1',[reference,'.u3']), ...
        connect('#zero.y1',[reference,'.u4']), ...
        connect([reference,'.y1'],sprintf('#trace_mux.u%d',2*index-1)), ...
        connect([reference,'.y2'],sprintf('#trace_mux.u%d',2*index)), ...
        connect([reference,'.y1'],sprintf('#angles.u%d',index)), ...
        connect([reference,'.y2'],sprintf('#speeds.u%d',index))}];
    for port=3:6
        terminal=sprintf('unused_%s_%d',name,port);
        operations=[operations,{block('Terminator',terminal,struct()), ...
            connect(sprintf('%s.y%d',reference,port),['#',terminal,'.u1'])}];
    end
end
operations=[operations,{connect('#trace_mux.y1','#trace.u1'), ...
    connect('#angles.y1','#AngleScope.u1'),connect('#speeds.y1','#SpeedScope.u1')}];
disp(model_read(model,'root','0'));
result=model_edit(model,'root',jsonencode(operations),'full');disp(result);
disp(model_read(model,'root','0'));check=model_check(model,'root','["all"]');disp(check);
assert(contains(string(result),'status: ok') && ~contains(string(check),'severity: error'));
save_system(model,fullfile(module,'src',[model,'.slx']));
print(['-s',model],'-dpng',fullfile(module,'build_process','instances_diagram.png'));
end
function operation=block(type,name,parameters)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',parameters);
end
function operation=connect(source,destination)
operation=struct('op','connect','target',[source,' -> ',destination]);
end
