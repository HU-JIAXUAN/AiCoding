function build_speed_profile()
%BUILD_SPEED_PROFILE Add explicit-state speed profile without changing old loops.
assert(strcmp(version('-release'),'2026b'));gate=library.settingsLookup();assert(gate.gatePass);
module=fileparts(fileparts(mfilename('fullpath')));addpath(fullfile(module,'parameter'),fullfile(module,'src'));
model='MotionControl';load_system(model);disp(model_read(model,'root','0'));
assert(strcmpi(get_param(model,'FileName'),fullfile(module,'src',[model,'.slx'])),'The loaded library must belong to this module directory.');
assert(isempty(find_system(model,'SearchDepth',1,'Name','SpeedProfile')));
edit(model,'root',{struct('op','configure','target',['config:',model],'params',struct('Lock','off'))},false,'incremental');
r=edit(model,'root',{struct('op','create_subsystem','name','SpeedProfile','ref','profile','interface',struct('inputs',{{}},'outputs',{{}}))},false,'incremental');
scope=id(r,'profile');
mask=struct('Mask','on','MaskVariables','profileCfg=@1;','MaskStyleString','edit','MaskPromptString','Discrete speed profile configuration', ...
    'MaskValueString','speed_profile_parameters()');
edit(model,'root',{struct('op','configure','target',scope,'params',mask)},false,'incremental');
ops={b('Inport','reference',struct('Port','1','SampleTime','profileCfg.Ts')),b('Inport','enable',struct('Port','2','SampleTime','profileCfg.Ts')), ...
    b('Inport','reset',struct('Port','3','SampleTime','profileCfg.Ts')),b('Outport','limited',struct('Port','1')),b('Outport','held_state',struct('Port','2')), ...
    b('Saturate','SpeedBounds',struct('UpperLimit','profileCfg.Maximum','LowerLimit','profileCfg.Minimum')), ...
    b('UnitDelay','PreviousReference',struct('InitialCondition','0','SampleTime','profileCfg.Ts')),b('Sum','RequestedStep',struct('Inputs','+-')), ...
    b('Saturate','StepBounds',struct('UpperLimit','profileCfg.RisingStep','LowerLimit','-profileCfg.FallingStep')), ...
    b('Sum','NextReference',struct('Inputs','++')),b('Logic','NotReset',struct('Operator','NOT')),b('Logic','Active',struct('Operator','AND','Inputs','2')), ...
    b('Constant','Zero',struct('Value','0')),b('Switch','OutputAndNextState',struct('Criteria','u2 ~= 0')), ...
    b('Switch','StateDiagnostic',struct('Criteria','u2 ~= 0'))};
edges={'reference','SpeedBounds',1;'SpeedBounds','RequestedStep',1;'PreviousReference','RequestedStep',2; ...
    'RequestedStep','StepBounds',1;'PreviousReference','NextReference',1;'StepBounds','NextReference',2; ...
    'reset','NotReset',1;'enable','Active',1;'NotReset','Active',2;'NextReference','OutputAndNextState',1; ...
    'Active','OutputAndNextState',2;'Zero','OutputAndNextState',3;'OutputAndNextState','PreviousReference',1; ...
    'OutputAndNextState','limited',1;'PreviousReference','StateDiagnostic',1;'Active','StateDiagnostic',2;'Zero','StateDiagnostic',3; ...
    'StateDiagnostic','held_state',1};
for k=1:size(edges,1),ops{end+1}=c(['#',edges{k,1},'.y1'],sprintf('#%s.u%d',edges{k,2},edges{k,3}));end
edit(model,scope,ops,false,'full');
edit(model,'root',{struct('op','configure','target',scope,'params',struct('Mask','off'))},false,'incremental');
disp(model_read(model,scope,'0'));health=model_check(model,scope,'["all"]');disp(health);assert(contains(string(health),'status: healthy'));
mask.MaskValueString='profileCfg';
edit(model,'root',{struct('op','configure','target',scope,'params',mask)},false,'incremental');
profilePath=Simulink.ID.getFullName([model,':',extractAfter(scope,'blk_')]);save_system(model);close_system(model,0);
model='SpeedProfileTest';assert(~bdIsLoaded(model) && ~isfile(fullfile(module,'src',[model,'.slx'])));
new_system(model);open_system(model);initialize_speed_profile_test(model);
callback='addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));initialize_speed_profile_test(bdroot);';
ops={struct('op','configure','target',['config:',model],'params',struct('Solver','FixedStepDiscrete','SolverType','Fixed-step','FixedStep','profileCfg.Ts', ...
    'StopTime','profileTestCfg.Duration','ReturnWorkspaceOutputs','on','PostLoadFcn',callback)), ...
    b('FromWorkspace','Stimulus',struct('VariableName','testStim','Interpolate','off','SampleTime','profileCfg.Ts','OutputAfterFinalValue','Holding final value')), ...
    b('Demux','Inputs',struct('Outputs','3')),struct('op','add_block','type','SpeedProfile','ReferenceBlock',profilePath,'name','Profile','ref','Profile'), ...
    b('Mux','Trace',struct('Inputs','5')),b('ToWorkspace','SaveTrace',struct('VariableName','trace','SaveFormat','Structure With Time','SampleTime','profileCfg.Ts','MaxDataPoints','inf')), ...
    b('Mux','ReferenceChannels',struct('Inputs','3')),b('Scope','ReferenceScope',struct('NumInputPorts','1')), ...
    b('Mux','ControlChannels',struct('Inputs','2')),b('Scope','ControlScope',struct('NumInputPorts','1')), ...
    c('#Stimulus.y1','#Inputs.u1'),c('#Trace.y1','#SaveTrace.u1'),c('#ReferenceChannels.y1','#ReferenceScope.u1'),c('#ControlChannels.y1','#ControlScope.u1'), ...
    c('#Inputs.y1','#ReferenceChannels.u1'),c('#Profile.y1','#ReferenceChannels.u2'),c('#Profile.y2','#ReferenceChannels.u3'), ...
    c('#Inputs.y2','#ControlChannels.u1'),c('#Inputs.y3','#ControlChannels.u2'),c('#Profile.y1','#Trace.u4'),c('#Profile.y2','#Trace.u5')};
for k=1:3,ops=[ops,{c(sprintf('#Inputs.y%d',k),sprintf('#Profile.u%d',k)),c(sprintf('#Inputs.y%d',k),sprintf('#Trace.u%d',k))}];end
edit(model,'root',ops,true,'full');save_system(model,fullfile(module,'src',[model,'.slx']));close_system(model,0);
end
function result=edit(model,scope,ops,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(ops),layout);disp(result);disp(model_read(model,scope,'0'));
if ~contains(string(result),'status: ok'),disp(model_check(model,scope,'["all"]'));error('SpeedProfile:Edit','%s',char(result));end
if complete,health=model_check(model,scope,'["all"]');disp(health);assert(~contains(string(health),'severity: error'));end
end
function op=b(type,name,params)
op=struct('op','add_block','type',type,'name',name,'ref',name,'params',params);
end
function op=c(a,b)
op=struct('op','connect','target',[a,' -> ',b]);
end
function result=id(text,name)
match=regexp(char(text),['(?m)^[ \t]*',regexptranslate('escape',name),':[ \t]*(blk_\d+)'],'tokens');assert(isscalar(match));result=match{1}{1};
end
