function build_ekf_observer()
%BUILD_EKF_OBSERVER Build shared current correction, EKF and an independent bench.
assert(strcmp(version('-release'),'2026b'));gate=library.settingsLookup();assert(gate.gatePass);
initialize_ekf_paths();module=fileparts(fileparts(mfilename('fullpath')));
model='EkfObserver';test='EkfObserverTest';
assert(~bdIsLoaded(model) && ~bdIsLoaded(test));
assert(~isfile(fullfile(module,'src',[model,'.slx'])) && ~isfile(fullfile(module,'src',[test,'.slx'])));
new_system(model,'Library');
libraryCallback='addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));initialize_ekf_paths();';
edit(model,'root',{struct('op','configure','target',['config:',model],'params',struct('PostLoadFcn',libraryCallback))},false,'incremental');
measurement=create_core(model,'KalmanMeasurement');mask(model,measurement);
ins={'prior_memory','i_alpha','i_beta','direction','enable','reset'};outs={'posterior_memory','diagnostics'};
ops={};
for k=1:numel(ins)
    parameters=struct('Port',num2str(k),'SampleTime','cfg.Model.Ts');
    if k==1,parameters.PortDimensions='28';end
    ops{end+1}=b('Inport',ins{k},parameters);
end
for k=1:numel(outs),ops{end+1}=b('Outport',outs{k},struct('Port',num2str(k)));end
ops{end+1}=b('MATLAB Function','Correct',struct());
result=edit(model,measurement,ops,false,'full');ports=ids(result,[ins,outs,{'Correct'}]);
embed(model,ports.Correct,fullfile(module,'src/kalman_current_update.m'));
ops={b('Mux','Current',struct('Inputs','2')),b('Constant','Settings',struct('Value','cfg.Settings')), ...
    c('#i_alpha.y1','#Current.u1'),c('#i_beta.y1','#Current.u2'), ...
    c('#prior_memory.y1','#Correct.u1'),c('#Current.y1','#Correct.u2'),c('#direction.y1','#Correct.u3'), ...
    c('#enable.y1','#Correct.u4'),c('#reset.y1','#Correct.u5'),c('#Settings.y1','#Correct.u6'), ...
    c('#Correct.y1','#posterior_memory.u1'),c('#Correct.y2','#diagnostics.u1')};
edit(model,measurement,resolve(ops,ports),true,'incremental');
save_system(model,fullfile(module,'src',[model,'.slx']));
if strcmp(get_param(model,'Lock'),'on'),edit(model,'root',{struct('op','configure','target',['config:',model],'params',struct('Lock','off'))},false,'incremental');end
core=create_core(model,'EKF');mask(model,core);
ins={'u_alpha','u_beta','i_alpha','i_beta','direction','enable','reset'};
outs={'theta_e_hat','omega_e_hat','valid','i_hat_alpha','i_hat_beta','innovation_alpha','innovation_beta', ...
    'normalized_innovation','theta_std','omega_std','angle_rate','rate_mismatch','qualification_count','fault', ...
    'variance_i_alpha','variance_i_beta','variance_omega','variance_theta','gain_theta_alpha','gain_theta_beta', ...
    'gain_omega_alpha','gain_omega_beta','emf_magnitude','numeric_repairs','covariance'};
ops={};
for k=1:numel(ins),ops{end+1}=b('Inport',ins{k},struct('Port',num2str(k),'SampleTime','cfg.Model.Ts'));end
for k=1:numel(outs),ops{end+1}=b('Outport',outs{k},struct('Port',num2str(k)));end
ops{end+1}=b('MATLAB Function','Predict',struct());
result=edit(model,core,ops,false,'full');ports=ids(result,[ins,outs,{'Predict'}]);
embed(model,ports.Predict,fullfile(module,'src/ekf_predict.m'));
reference=Simulink.ID.getFullName([model,':',extractAfter(measurement,'blk_')]);
ops={struct('op','add_block','type','KalmanMeasurement','ReferenceBlock',reference,'name','Measurement','ref','Measurement', ...
    'params',struct('MaskValueString','cfg')), ...
    b('UnitDelay','PriorMemory',struct('InitialCondition','zeros(28,1)','SampleTime','cfg.Model.Ts')), ...
    b('Constant','Settings',struct('Value','cfg.Settings')),b('Mux','Voltage',struct('Inputs','2')), ...
    b('Demux','Channels',struct('Outputs','24')),b('Demux','PosteriorParts',struct('Outputs','[4 16 8]')), ...
    b('Terminator','StateInDiagnostics',struct()),b('Terminator','MetadataInDiagnostics',struct()), ...
    c('#u_alpha.y1','#Voltage.u1'),c('#u_beta.y1','#Voltage.u2'), ...
    c('#PriorMemory.y1','#Measurement.u1'),c('#i_alpha.y1','#Measurement.u2'),c('#i_beta.y1','#Measurement.u3'), ...
    c('#direction.y1','#Measurement.u4'),c('#enable.y1','#Measurement.u5'),c('#reset.y1','#Measurement.u6'), ...
    c('#Measurement.y1','#Predict.u1'),c('#Voltage.y1','#Predict.u2'),c('#enable.y1','#Predict.u3'), ...
    c('#reset.y1','#Predict.u4'),c('#Settings.y1','#Predict.u5'),c('#Predict.y1','#PriorMemory.u1'), ...
    c('#Measurement.y2','#Channels.u1'),c('#Measurement.y1','#PosteriorParts.u1'), ...
    c('#PosteriorParts.y1','#StateInDiagnostics.u1'),c('#PosteriorParts.y2','#covariance.u1'),c('#PosteriorParts.y3','#MetadataInDiagnostics.u1')};
for k=1:24,ops{end+1}=c(sprintf('#Channels.y%d',k),['#',outs{k},'.u1']);end
edit(model,core,resolve(ops,ports),true,'incremental');
save_system(model,fullfile(module,'src',[model,'.slx']));
new_system(test);initialize_ekf_test(test);
callback='addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));initialize_ekf_test(bdroot);';
reference=Simulink.ID.getFullName([model,':',extractAfter(core,'blk_')]);
ops={struct('op','configure','target',['config:',test],'params',struct('Solver','FixedStepDiscrete','SolverType','Fixed-step', ...
    'FixedStep','ekfCfg.Model.Ts','StopTime','ekfTestCfg.Duration','PostLoadFcn',callback,'ReturnWorkspaceOutputs','on')), ...
    b('FromWorkspace','Stimulus',struct('VariableName','testStim','Interpolate','off','SampleTime','ekfCfg.Model.Ts','OutputAfterFinalValue','Holding final value')), ...
    b('Demux','Inputs',struct('Outputs','9')),struct('op','add_block','type','EKF','ReferenceBlock',reference, ...
    'name','Observer','ref','Observer','params',struct('MaskValueString','ekfCfg')), ...
    b('Mux','Trace',struct('Inputs','35')),b('ToWorkspace','SaveTrace',struct('VariableName','trace', ...
    'SaveFormat','Structure With Time','MaxDataPoints','inf','SampleTime','ekfCfg.Model.Ts')), ...
    b('Sum','Difference',struct('Inputs','+-')),b('Trigonometry','ErrorSin',struct('Operator','sin')), ...
    b('Trigonometry','ErrorCos',struct('Operator','cos')),b('Trigonometry','AngleError',struct('Operator','atan2')), ...
    c('#Stimulus.y1','#Inputs.u1'),c('#Observer.y1','#Difference.u1'),c('#Inputs.y8','#Difference.u2'), ...
    c('#Difference.y1','#ErrorSin.u1'),c('#Difference.y1','#ErrorCos.u1'), ...
    c('#ErrorSin.y1','#AngleError.u1'),c('#ErrorCos.y1','#AngleError.u2'),c('#AngleError.y1','#Trace.u35'), ...
    c('#Observer.y25','#Trace.u34'),c('#Trace.y1','#SaveTrace.u1')};
for k=1:7,ops{end+1}=c(sprintf('#Inputs.y%d',k),sprintf('#Observer.u%d',k));end
for k=1:9,ops{end+1}=c(sprintf('#Inputs.y%d',k),sprintf('#Trace.u%d',k));end
for k=1:24,ops{end+1}=c(sprintf('#Observer.y%d',k),sprintf('#Trace.u%d',k+9));end
groups={'AngleScope',{'#Inputs.y8','#Observer.y1','#AngleError.y1'}; ...
    'SpeedScope',{'#Inputs.y9','#Observer.y2','#Observer.y11'}; ...
    'CurrentScope',{'#Inputs.y3','#Observer.y4','#Inputs.y4','#Observer.y5'}; ...
    'InnovationScope',{'#Observer.y6','#Observer.y7'};'NisScope',{'#Observer.y8'}; ...
    'AngleSigmaScope',{'#Observer.y9'};'SpeedSigmaScope',{'#Observer.y10'}; ...
    'RateMismatchScope',{'#Observer.y12'};'EmfScope',{'#Observer.y23'}; ...
    'StatusScope',{'#Inputs.y5','#Inputs.y6','#Inputs.y7','#Observer.y3','#Observer.y13','#Observer.y14','#Observer.y24'}};
for g=1:size(groups,1)
    name=groups{g,1};sources=groups{g,2};mux=[name,'Channels'];
    ops=[ops,{b('Mux',mux,struct('Inputs',num2str(numel(sources)))),b('Scope',name,struct('NumInputPorts','1')),c(['#',mux,'.y1'],['#',name,'.u1'])}];
    for k=1:numel(sources),ops{end+1}=c(sources{k},sprintf('#%s.u%d',mux,k));end
end
edit(test,'root',ops,true,'full');save_system(test,fullfile(module,'src',[test,'.slx']));
close_system(test,0);close_system(model,0);
end
function scope=create_core(model,name)
result=edit(model,'root',{struct('op','create_subsystem','name',name,'ref',name, ...
    'interface',struct('inputs',{{}},'outputs',{{}}))},false,'incremental');scope=id(result,name);
end
function mask(model,scope)
edit(model,'root',{struct('op','configure','target',scope,'params',struct('Mask','on','MaskVariables','cfg=@1;', ...
    'MaskStyleString','edit','MaskPromptString','Kalman configuration','MaskValueString','ekf_parameters()'))},false,'incremental');
end
function embed(model,block,file)
actual=Simulink.ID.getFullName([model,':',extractAfter(block,'blk_')]);
configuration=get_param(actual,'MATLABFunctionConfiguration');configuration.FunctionScript=fileread(file);
end
function operation=b(type,name,parameters)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',parameters);
end
function operation=c(source,target)
operation=struct('op','connect','target',[source,' -> ',target]);
end
function result=edit(model,scope,ops,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(ops),layout);disp(result);disp(model_read(model,scope,'0'));
assert(contains(string(result),'status: ok'),'Inspect the current scope before continuing.');
if complete,check=model_check(model,scope,'["all"]');disp(check);assert(~contains(string(check),'severity: error'));end
end
function p=ids(result,names)
p=struct();for k=1:numel(names),p.(names{k})=id(result,names{k});end
end
function value=id(result,name)
matches=regexp(char(result),['(?m)^[ \t]*',regexptranslate('escape',name),':[ \t]*(blk_\d+)'],'tokens');assert(isscalar(matches),name);value=matches{1}{1};
end
function ops=resolve(ops,p)
names=fieldnames(p);
for k=1:numel(ops)
    if ~isfield(ops{k},'target'),continue;end
    for j=1:numel(names),ops{k}.target=strrep(ops{k}.target,['#',names{j},'.'],[p.(names{j}),'.']);end
end
end
