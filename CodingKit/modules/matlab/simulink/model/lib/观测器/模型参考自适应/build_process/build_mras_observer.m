function build_mras_observer()
%BUILD_MRAS_OBSERVER Create a masked SPMSM MRAS library and independent bench.
assert(strcmp(version('-release'),'2026b'));gate=library.settingsLookup();assert(gate.gatePass);
module=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(module,'src'),fullfile(module,'parameter'),fileparts(mfilename('fullpath')));
model='MrasObserver';test='MrasObserverTest';
assert(~bdIsLoaded(model) && ~bdIsLoaded(test));
assert(~isfile(fullfile(module,'src',[model,'.slx'])) && ~isfile(fullfile(module,'src',[test,'.slx'])));
new_system(model,'Library');
result=edit(model,'root',{struct('op','create_subsystem','name','CurrentModelMRAS','ref','core', ...
    'interface',struct('inputs',{{}},'outputs',{{}}))},false,'full');scope=id(result,'core');
edit(model,'root',{struct('op','configure','target',scope,'params',struct('Mask','on', ...
    'MaskVariables','cfg=@1;','MaskStyleString','edit','MaskPromptString','MRAS configuration', ...
    'MaskValueString','mras_parameters()'))},false,'incremental');
ins={'u_alpha','u_beta','i_alpha','i_beta','direction','enable','reset'};
outs={'theta_e_hat','omega_e_hat','valid','predicted_id','predicted_iq','measured_id','measured_iq', ...
    'residual_d','residual_q','normalized_d','normalized_q','emf_magnitude','qualification_count', ...
    'speed_integral','fault','normalization_denominator'};
ops={};
for k=1:numel(ins),ops{end+1}=b('Inport',ins{k},struct('Port',num2str(k),'SampleTime','cfg.Ts'));end
for k=1:numel(outs),ops{end+1}=b('Outport',outs{k},struct('Port',num2str(k)));end
ops=[ops,{b('MATLAB Function','Update',struct()),b('MATLAB Function','Output',struct())}];
result=edit(model,scope,ops,false,'full');ports=struct();names=[ins,outs,{'Update','Output'}];
for k=1:numel(names),ports.(names{k})=id(result,names{k});end
for pair={{'Update','mras_step.m'},{'Output','mras_output.m'}}
    entry=pair{1};block=Simulink.ID.getFullName([model,':',extractAfter(ports.(entry{1}),'blk_')]);
    configuration=get_param(block,'MATLABFunctionConfiguration');configuration.FunctionScript=fileread(fullfile(module,'src',entry{2}));
end
ops={b('Mux','Voltage',struct('Inputs','2')),b('Mux','Current',struct('Inputs','2')), ...
    b('Constant','Settings',struct('Value','cfg.Settings')), ...
    b('UnitDelay','State',struct('InitialCondition','zeros(21,1)','SampleTime','cfg.Ts')), ...
    b('Demux','Channels',struct('Outputs','16')), ...
    c('#u_alpha.y1','#Voltage.u1'),c('#u_beta.y1','#Voltage.u2'),c('#i_alpha.y1','#Current.u1'),c('#i_beta.y1','#Current.u2'), ...
    c('#State.y1','#Update.u1'),c('#Voltage.y1','#Update.u2'),c('#Current.y1','#Update.u3'), ...
    c('#direction.y1','#Update.u4'),c('#enable.y1','#Update.u5'),c('#reset.y1','#Update.u6'),c('#Settings.y1','#Update.u7'), ...
    c('#Update.y1','#State.u1'),c('#State.y1','#Output.u1'),c('#direction.y1','#Output.u2'), ...
    c('#enable.y1','#Output.u3'),c('#reset.y1','#Output.u4'),c('#Settings.y1','#Output.u5'),c('#Output.y1','#Channels.u1')};
for k=1:numel(outs),ops{end+1}=c(sprintf('#Channels.y%d',k),['#',outs{k},'.u1']);end
edit(model,scope,resolve(ops,ports),true,'incremental');
save_system(model,fullfile(module,'src',[model,'.slx']));
new_system(test);initialize_mras_test(test);
callback='addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));initialize_mras_test(bdroot);';
reference=Simulink.ID.getFullName([model,':',extractAfter(scope,'blk_')]);
ops={struct('op','configure','target',['config:',test],'params',struct('Solver','FixedStepDiscrete', ...
    'SolverType','Fixed-step','FixedStep','mrasCfg.Ts','StopTime','mrasTestCfg.Duration','PostLoadFcn',callback,'ReturnWorkspaceOutputs','on')), ...
    b('FromWorkspace','Stimulus',struct('VariableName','testStim','Interpolate','off','SampleTime','mrasCfg.Ts','OutputAfterFinalValue','Holding final value')), ...
    b('Demux','Inputs',struct('Outputs','9')),struct('op','add_block','type','CurrentModelMRAS', ...
    'ReferenceBlock',reference,'name','Observer','ref','Observer','params',struct('MaskValueString','mrasCfg')), ...
    b('Mux','Trace',struct('Inputs','26')),b('ToWorkspace','SaveTrace',struct('VariableName','trace', ...
    'SaveFormat','Structure With Time','MaxDataPoints','inf','SampleTime','mrasCfg.Ts')), ...
    b('Sum','Difference',struct('Inputs','+-')),b('Trigonometry','ErrorSin',struct('Operator','sin')), ...
    b('Trigonometry','ErrorCos',struct('Operator','cos')),b('Trigonometry','AngleError',struct('Operator','atan2')), ...
    c('#Stimulus.y1','#Inputs.u1'),c('#Observer.y1','#Difference.u1'),c('#Inputs.y8','#Difference.u2'), ...
    c('#Difference.y1','#ErrorSin.u1'),c('#Difference.y1','#ErrorCos.u1'), ...
    c('#ErrorSin.y1','#AngleError.u1'),c('#ErrorCos.y1','#AngleError.u2'),c('#AngleError.y1','#Trace.u26'),c('#Trace.y1','#SaveTrace.u1')};
for k=1:7,ops{end+1}=c(sprintf('#Inputs.y%d',k),sprintf('#Observer.u%d',k));end
for k=1:9,ops{end+1}=c(sprintf('#Inputs.y%d',k),sprintf('#Trace.u%d',k));end
for k=1:16,ops{end+1}=c(sprintf('#Observer.y%d',k),sprintf('#Trace.u%d',k+9));end
groups={'AngleScope',{'#Inputs.y8','#Observer.y1','#AngleError.y1'}; ...
    'SpeedScope',{'#Inputs.y9','#Observer.y2','#Observer.y14'}; ...
    'CurrentModelScope',{'#Observer.y6','#Observer.y4','#Observer.y7','#Observer.y5'}; ...
    'ResidualScope',{'#Observer.y8','#Observer.y9'};'NormalizedScope',{'#Observer.y10','#Observer.y11'}; ...
    'EmfScope',{'#Observer.y12'};'NormalizerScope',{'#Observer.y16'}; ...
    'StatusScope',{'#Inputs.y5','#Inputs.y6','#Inputs.y7','#Observer.y3','#Observer.y13','#Observer.y15'}};
for g=1:size(groups,1)
    name=groups{g,1};sources=groups{g,2};mux=[name,'Channels'];
    ops=[ops,{b('Mux',mux,struct('Inputs',num2str(numel(sources)))),b('Scope',name,struct('NumInputPorts','1')), ...
        c(['#',mux,'.y1'],['#',name,'.u1'])}];
    for k=1:numel(sources),ops{end+1}=c(sources{k},sprintf('#%s.u%d',mux,k));end
end
edit(test,'root',ops,true,'full');
save_system(test,fullfile(module,'src',[test,'.slx']));
close_system(test,0);close_system(model,0);
end
function operation=b(type,name,parameters)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',parameters);
end
function operation=c(source,target)
operation=struct('op','connect','target',[source,' -> ',target]);
end
function result=edit(model,scope,ops,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(ops),layout);disp(result);disp(model_read(model,scope,'0'));
assert(contains(string(result),'status: ok'),'Inspect the current scope before continuing.');
if complete,check=model_check(model,scope,'["all"]');disp(check);assert(~contains(string(check),'severity: error'));end
end
function value=id(result,name)
matches=regexp(char(result),['(?m)^[ \t]*',regexptranslate('escape',name),':[ \t]*(blk_\d+)'],'tokens');
assert(isscalar(matches),name);value=matches{1}{1};
end
function ops=resolve(ops,ports)
names=fieldnames(ports);
for k=1:numel(ops)
    if ~isfield(ops{k},'target'),continue;end
    for j=1:numel(names),ops{k}.target=strrep(ops{k}.target,['#',names{j},'.'],[ports.(names{j}),'.']);end
end
end
