function build_hfi_probe()
%BUILD_HFI_PROBE Append measured-tensor qualification to the HFI library.
assert(strcmp(version('-release'),'2026b'));gate=library.settingsLookup();assert(gate.gatePass);
module=fileparts(fileparts(mfilename('fullpath')));lib=fileparts(fileparts(module));
addpath(fullfile(module,'src'),fullfile(module,'parameter'),fileparts(mfilename('fullpath')), ...
    fullfile(lib,'永磁同步电机','src'),fullfile(lib,'永磁同步电机','parameter'),fullfile(lib,'math','src'));
model='HighFrequencyObserver';test='HFISaliencyTest';load_system(model);
assert(~isfile(fullfile(module,'src',[test,'.slx'])) && ~bdIsLoaded(test));
assert(isempty(find_system(model,'SearchDepth',1,'Name','SaliencyProbe')),'Probe already exists; inspect before editing.');
edit(model,'root',{struct('op','configure','target',['config:',model],'params',struct('Lock','off'))},false,'incremental');
result=edit(model,'root',{struct('op','create_subsystem','name','SaliencyProbe','ref','core', ...
    'interface',struct('inputs',{{}},'outputs',{{}}))},false,'incremental');scope=id(result,'core');
% Establish local cfg before validating sample times; never depend on base cfg.
edit(model,'root',{struct('op','configure','target',scope,'params',struct('Mask','on','MaskVariables','cfg=@1;', ...
    'MaskStyleString','edit','MaskPromptString','Orthogonal probe configuration','MaskValueString','hfi_probe_parameters()'))},false,'incremental');
inputs={'u_alpha','u_beta','i_alpha','i_beta','enable','reset'};
outputs={'injection_alpha','injection_beta','theta_axis','saliency_ratio','qualified','done','inverse_average', ...
    'inverse_aa','inverse_ab','inverse_bb','fit_residual','sample_count','fault_code','eigen_min','eigen_max','quality_code'};
operations={};
for k=1:numel(inputs),operations{end+1}=b('Inport',inputs{k},struct('Port',num2str(k),'SampleTime','cfg.Ts'));end
for k=1:numel(outputs),operations{end+1}=b('Outport',outputs{k},struct('Port',num2str(k)));end
operations=[operations,{b('MATLAB Function','Update',struct()),b('MATLAB Function','Output',struct())}];
result=edit(model,scope,operations,false,'full');ports=ids(result,[inputs,outputs,{'Update','Output'}]);
embed(model,ports.Update,fullfile(module,'src','hfi_probe_update.m'));
embed(model,ports.Output,fullfile(module,'src','hfi_probe_output.m'));disp(model_read(model,scope,'0'));
operations={b('Mux','VoltageAB',struct('Inputs','2')),b('Mux','CurrentAB',struct('Inputs','2')), ...
    b('UnitDelay','ProbeStates',struct('InitialCondition','cfg.InitialState','SampleTime','cfg.Ts')), ...
    b('Constant','Settings',struct('Value','cfg.Settings')),b('Demux','OutputSignals',struct('Outputs','16')), ...
    b('Logic','NotReset',struct('Operator','NOT')),b('Logic','Active',struct('Operator','AND','Inputs','2')), ...
    c('#u_alpha.y1','#VoltageAB.u1'),c('#u_beta.y1','#VoltageAB.u2'), ...
    c('#i_alpha.y1','#CurrentAB.u1'),c('#i_beta.y1','#CurrentAB.u2'), ...
    c('#reset.y1','#NotReset.u1'),c('#NotReset.y1','#Active.u2'),c('#enable.y1','#Active.u1'), ...
    c('#ProbeStates.y1','#Update.u1'),c('#CurrentAB.y1','#Update.u2'),c('#VoltageAB.y1','#Update.u3'), ...
    c('#Active.y1','#Update.u4'),c('#Settings.y1','#Update.u5'),c('#Update.y1','#ProbeStates.u1'), ...
    c('#ProbeStates.y1','#Output.u1'),c('#Active.y1','#Output.u2'),c('#Settings.y1','#Output.u3'),c('#Output.y1','#OutputSignals.u1')};
for k=1:numel(outputs),operations{end+1}=c(sprintf('#OutputSignals.y%d',k),['#',outputs{k},'.u1']);end
edit(model,scope,resolve(operations,ports),true,'incremental');
edit(model,'root',{struct('op','configure','target',scope,'params',struct('Mask','off'))},false,'incremental');
disp(model_read(model,scope,'0'));health=model_check(model,scope,'["all"]');disp(health);assert(~contains(string(health),'severity: error'));
edit(model,'root',{struct('op','configure','target',scope,'params',struct('Mask','on','MaskVariables','cfg=@1;', ...
    'MaskStyleString','edit','MaskPromptString','Orthogonal probe configuration','MaskValueString','probeCfg', ...
    'Position','[200 600 540 1060]'))},false,'incremental');
save_system(model,fullfile(module,'src',[model,'.slx']));close_system(model,0);build_bench(module,test,model);
end
