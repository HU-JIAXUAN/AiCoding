function embed(model,block,source)
path=Simulink.ID.getFullName([model,':',extractAfter(block,'blk_')]);
configuration=get_param(path,'MATLABFunctionConfiguration');configuration.FunctionScript=fileread(source);
end
function operation=b(type,name,parameters)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',parameters);
end
function operation=c(source,destination)
operation=struct('op','connect','target',[source,' -> ',destination]);
end
function result=edit(model,scope,operations,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(operations),layout);disp(result);disp(model_read(model,scope,'0'));
if ~contains(string(result),'status: ok'),disp(model_check(model,scope,'["all"]'));error('HFIProbe:ModelEdit','Model edit did not complete: %s',char(result));end
if complete,health=model_check(model,scope,'["all"]');disp(health);assert(~contains(string(health),'severity: error'));end
end
function value=id(result,reference)
pattern=['(?m)^[ \t]*',regexptranslate('escape',reference),':[ \t]*(blk_\d+)'];
matches=regexp(char(result),pattern,'tokens');assert(isscalar(matches));value=matches{1}{1};
end
function values=ids(result,names)
values=struct();for k=1:numel(names),values.(names{k})=id(result,names{k});end
end
function operations=resolve(operations,ports)
names=fieldnames(ports);
for k=1:numel(operations)
    if isfield(operations{k},'target')
        for n=1:numel(names),operations{k}.target=strrep(operations{k}.target,['#',names{n},'.'],[ports.(names{n}),'.']);end
    end
end
end
