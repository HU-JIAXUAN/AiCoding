function build_emf_observer()
%BUILD_EMF_OBSERVER Build visible current/EMF state observers and two benches.
assert(strcmp(version('-release'),'2026b'));gate=library.settingsLookup();assert(gate.gatePass);
module=fileparts(fileparts(mfilename('fullpath')));pll=fullfile(fileparts(fileparts(module)),'相位跟踪');
addpath(fullfile(module,'src'),fullfile(module,'parameter'),fileparts(mfilename('fullpath')), ...
    fullfile(pll,'src'),fullfile(pll,'parameter'));load_system('AngleTracking');
model='EmfObserver';assert(~bdIsLoaded(model) && ~isfile(fullfile(module,'src',[model,'.slx'])));
new_system(model,'Library');open_system(model);
names={'LinearEMF','EEMF'};
for instance=1:2
    result=edit(model,'root',{struct('op','create_subsystem','name',names{instance}, ...
        'ref','core','interface',struct('inputs',{{}},'outputs',{{}}))},false,'incremental');
    scope=id(result,'core');
    ins={'u_alpha','u_beta','i_alpha','i_beta','direction','enable','reset'};
    outs={'theta_e_hat','omega_e_hat','valid','emf_alpha','emf_beta','i_hat_alpha', ...
        'i_hat_beta','residual_alpha','residual_beta','phase_measured','emf_magnitude','phase_error'};
    operations={};
    for k=1:7,operations{end+1}=b('Inport',ins{k},struct('Port',num2str(k),'SampleTime','cfg.Ts'));end
    for k=1:12,operations{end+1}=b('Outport',outs{k},struct('Port',num2str(k)));end
    operations{end+1}=b('MATLAB Function','Predict',struct());
    result=edit(model,scope,operations,false,'full');predict=id(result,'Predict');
    ports=struct();portNames=[ins,outs];
    for k=1:numel(portNames),ports.(portNames{k})=id(result,portNames{k});end
    configuration=get_param(Simulink.ID.getFullName([model,':',extractAfter(predict,'blk_')]),'MATLABFunctionConfiguration');
    configuration.FunctionScript=fileread(fullfile(module,'src','emf_predict.m'));
    disp(model_read(model,scope,'0'));
    operations={b('Mux','VoltageAB',struct('Inputs','2')),b('Mux','CurrentAB',struct('Inputs','2')), ...
        b('Constant','Settings',struct('Value','[cfg.Ts;cfg.Rs;cfg.Ld;cfg.Lq;2*pi*cfg.BandwidthHz]')), ...
        b('UnitDelay','State',struct('InitialCondition','zeros(4,1)','SampleTime','cfg.Ts')), ...
        b('Demux','States',struct('Outputs','2')),b('Constant','ZeroVector',struct('Value','[0;0]')), ...
        b('Constant','One',struct('Value','1')),b('Abs','DirectionMagnitude',struct()), ...
        b('RelationalOperator','DirectionOK',struct('Operator','==')), ...
        b('UnitDelay','PreviousDirection',struct('InitialCondition','0','SampleTime','cfg.Ts')), ...
        b('RelationalOperator','DirectionChanged',struct('Operator','~=')), ...
        b('Logic','ResetAny',struct('Operator','OR','Inputs','2')),b('Logic','NotReset',struct('Operator','NOT')), ...
        b('Logic','Active',struct('Operator','AND','Inputs','3')), ...
        sw('CurrentOutput'),sw('EmfOutput'),sw('ResidualOutput'), ...
        b('Demux','CurrentChannels',struct('Outputs','2')),b('Demux','EmfChannels',struct('Outputs','2')), ...
        b('Demux','ResidualChannels',struct('Outputs','2')),b('Sum','Residual',struct('Inputs','+-')), ...
        b('DotProduct','ResidualSquared',struct()),b('Sqrt','ResidualNorm',struct()), ...
        b('Constant','MaximumResidual',struct('Value','cfg.MaxResidual')), ...
        b('RelationalOperator','ResidualOK',struct('Operator','<=')), ...
        b('DotProduct','EmfSquared',struct()),b('Sqrt','Magnitude',struct()), ...
        b('Product','DirectedAlpha',struct('Inputs','**')),b('Gain','MinusAlpha',struct('Gain','-1')), ...
        b('Product','DirectedBeta',struct('Inputs','**')),b('Trigonometry','Phase',struct('Operator','atan2')), ...
        struct('op','add_block','type','PLL','ReferenceBlock','AngleTracking/PLL','name','PLL','ref','PLL', ...
            'params',struct('MaskValueString','trackerCfg')), ...
        b('Product','DirectedSpeed',struct('Inputs','**')),b('Constant','MinimumSpeed',struct('Value','cfg.MinOmega')), ...
        b('RelationalOperator','SpeedOK',struct('Operator','>=')),b('Logic','Valid',struct('Operator','AND','Inputs','4')), ...
        b('DataTypeConversion','ValidDouble',struct('OutDataTypeStr','double')), ...
        b('Terminator','UnusedIntegral',struct()),b('Terminator','UnusedCount',struct())};
    edges={'u_alpha','VoltageAB',1;'u_beta','VoltageAB',2;'i_alpha','CurrentAB',1;'i_beta','CurrentAB',2; ...
        'direction','DirectionMagnitude',1;'DirectionMagnitude','DirectionOK',1;'One','DirectionOK',2; ...
        'direction','PreviousDirection',1;'direction','DirectionChanged',1;'PreviousDirection','DirectionChanged',2; ...
        'reset','ResetAny',1;'DirectionChanged','ResetAny',2;'ResetAny','NotReset',1; ...
        'enable','Active',1;'DirectionOK','Active',2;'NotReset','Active',3; ...
        'State','States',1;'CurrentOutput','CurrentChannels',1;'EmfOutput','EmfChannels',1; ...
        'ResidualOutput','ResidualChannels',1;'CurrentAB','Residual',2; ...
        'Residual','ResidualOutput',1;'Active','ResidualOutput',2;'ZeroVector','ResidualOutput',3; ...
        'Active','CurrentOutput',2;'ZeroVector','CurrentOutput',3;'Active','EmfOutput',2;'ZeroVector','EmfOutput',3; ...
        'ResidualOutput','ResidualSquared',1;'ResidualOutput','ResidualSquared',2;'ResidualSquared','ResidualNorm',1; ...
        'ResidualNorm','ResidualOK',1;'MaximumResidual','ResidualOK',2; ...
        'EmfOutput','EmfSquared',1;'EmfOutput','EmfSquared',2;'EmfSquared','Magnitude',1; ...
        'direction','DirectedAlpha',2;'direction','DirectedBeta',2;'DirectedAlpha','MinusAlpha',1; ...
        'MinusAlpha','Phase',1;'DirectedBeta','Phase',2;'Phase','PLL',1;'Magnitude','PLL',2; ...
        'Active','PLL',3;'ResetAny','PLL',4;'direction','DirectedSpeed',2; ...
        'DirectedSpeed','SpeedOK',1;'MinimumSpeed','SpeedOK',2;'Active','Valid',2;'SpeedOK','Valid',3;'ResidualOK','Valid',4; ...
        'Valid','ValidDouble',1;'ValidDouble','valid',1;'Phase','phase_measured',1;'Magnitude','emf_magnitude',1};
    for k=1:size(edges,1),operations{end+1}=c(['#',edges{k,1},'.y1'],sprintf('#%s.u%d',edges{k,2},edges{k,3}));end
    operations=[operations,{c('#State.y1',[predict,'.u1']),c('#VoltageAB.y1',[predict,'.u2']), ...
        c('#CurrentAB.y1',[predict,'.u3']),c('#PLL.y2',[predict,'.u4']),c('#Active.y1',[predict,'.u5']), ...
        c('#Settings.y1',[predict,'.u6']),c([predict,'.y1'],'#State.u1'), ...
        c('#States.y1','#CurrentOutput.u1'),c('#States.y2','#EmfOutput.u1'),c('#States.y1','#Residual.u1'), ...
        c('#EmfChannels.y1','#DirectedAlpha.u1'),c('#EmfChannels.y2','#DirectedBeta.u1'), ...
        c('#PLL.y1','#theta_e_hat.u1'),c('#PLL.y2','#omega_e_hat.u1'),c('#PLL.y2','#DirectedSpeed.u1'), ...
        c('#PLL.y3','#phase_error.u1'),c('#PLL.y4','#Valid.u1'),c('#PLL.y5','#UnusedIntegral.u1'),c('#PLL.y6','#UnusedCount.u1')}];
    for k=1:2
        operations=[operations,{c(sprintf('#EmfChannels.y%d',k),sprintf('#%s.u1',outs{k+3})), ...
            c(sprintf('#CurrentChannels.y%d',k),sprintf('#%s.u1',outs{k+5})), ...
            c(sprintf('#ResidualChannels.y%d',k),sprintf('#%s.u1',outs{k+7}))}];
    end
    for k=1:numel(operations)
        if isfield(operations{k},'target')
            for field=portNames
                operations{k}.target=strrep(operations{k}.target,['#',field{1},'.'],[ports.(field{1}),'.']);
            end
        end
    end
    edit(model,scope,operations,true,'incremental');
    edit(model,'root',{struct('op','configure','target',scope,'params',struct('Mask','on', ...
        'MaskVariables','cfg=@1;trackerCfg=@2;','MaskStyleString','edit,edit', ...
        'MaskPromptString','Observer configuration|PLL configuration','MaskValueString','emfCfg|pllCfg'))},false,'incremental');
end
save_system(model,fullfile(module,'src',[model,'.slx']));
for instance=1:2
    if instance==1,test='LinearEmfTest';else,test='EemfObserverTest';end
    assert(~bdIsLoaded(test) && ~isfile(fullfile(module,'src',[test,'.slx'])));
    new_system(test);open_system(test);initialize_emf_test(test);
    callback=['addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));initialize_emf_test(bdroot);'];
    operations={struct('op','configure','target',['config:',test],'params',struct('Solver','FixedStepDiscrete', ...
        'SolverType','Fixed-step','FixedStep','emfCfg.Ts','StopTime','emfTestCfg.Duration','ReturnWorkspaceOutputs','on','PostLoadFcn',callback)), ...
        b('FromWorkspace','Stimulus',struct('VariableName','testStim','Interpolate','off','SampleTime','emfCfg.Ts','OutputAfterFinalValue','Holding final value')), ...
        b('Demux','Inputs',struct('Outputs','9')), ...
        struct('op','add_block','type',names{instance},'ReferenceBlock',[model,'/',names{instance}], ...
            'name','Observer','ref','Observer','params',struct('MaskValueString','emfCfg|pllCfg')), ...
        b('Mux','TraceChannels',struct('Inputs','22')),b('ToWorkspace','SaveTrace',struct('VariableName','trace','SaveFormat','Structure With Time','MaxDataPoints','inf')), ...
        b('Sum','AngleDifference',struct('Inputs','+-')),b('Trigonometry','ErrorSin',struct('Operator','sin')), ...
        b('Trigonometry','ErrorCos',struct('Operator','cos')),b('Trigonometry','AngleError',struct('Operator','atan2')), ...
        c('#Stimulus.y1','#Inputs.u1'),c('#Observer.y1','#AngleDifference.u1'),c('#Inputs.y8','#AngleDifference.u2'), ...
        c('#AngleDifference.y1','#ErrorSin.u1'),c('#AngleDifference.y1','#ErrorCos.u1'), ...
        c('#ErrorSin.y1','#AngleError.u1'),c('#ErrorCos.y1','#AngleError.u2'),c('#AngleError.y1','#TraceChannels.u22'),c('#TraceChannels.y1','#SaveTrace.u1')};
    for k=1:7,operations{end+1}=c(sprintf('#Inputs.y%d',k),sprintf('#Observer.u%d',k));end
    for k=1:9,operations{end+1}=c(sprintf('#Inputs.y%d',k),sprintf('#TraceChannels.u%d',k));end
    for k=1:12,operations{end+1}=c(sprintf('#Observer.y%d',k),sprintf('#TraceChannels.u%d',k+9));end
    groups={'AngleScope',{'#Inputs.y8','#Observer.y1','#AngleError.y1'}; ...
        'SpeedScope',{'#Inputs.y9','#Observer.y2'};'EmfScope',{'#Observer.y4','#Observer.y5','#Observer.y11'}; ...
        'CurrentScope',{'#Inputs.y3','#Observer.y6','#Inputs.y4','#Observer.y7'}; ...
        'ResidualScope',{'#Observer.y8','#Observer.y9'}; ...
        'StatusScope',{'#Inputs.y5','#Inputs.y6','#Inputs.y7','#Observer.y3','#Observer.y12'}};
    for g=1:size(groups,1)
        name=groups{g,1};sources=groups{g,2};mux=[name,'Channels'];
        operations=[operations,{b('Mux',mux,struct('Inputs',num2str(numel(sources)))),b('Scope',name,struct('NumInputPorts','1')),c(['#',mux,'.y1'],['#',name,'.u1'])}];
        for k=1:numel(sources),operations{end+1}=c(sources{k},sprintf('#%s.u%d',mux,k));end
    end
    edit(test,'root',operations,true,'full');save_system(test,fullfile(module,'src',[test,'.slx']));
end
end
function operation=b(type,name,parameters)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',parameters);
end
function operation=sw(name)
operation=b('Switch',name,struct('Criteria','u2 > Threshold','Threshold','0.5'));
end
function operation=c(source,destination)
operation=struct('op','connect','target',[source,' -> ',destination]);
end
function result=edit(model,scope,operations,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(operations),layout);disp(result);
disp(model_read(model,scope,'0'));
if ~contains(string(result),'status: ok')
    disp(model_check(model,scope,'["all"]'));error('Inspect the current model before continuing.');
end
if complete
    check=model_check(model,scope,'["all"]');disp(check);assert(~contains(string(check),'severity: error'));
end
end
function value=id(result,reference)
matches=regexp(char(result),[reference,':\s*(blk_\d+)'],'tokens');assert(isscalar(matches));value=matches{1}{1};
end
