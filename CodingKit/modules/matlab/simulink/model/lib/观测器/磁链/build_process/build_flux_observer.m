function build_flux_observer()
%BUILD_FLUX_OBSERVER Build a causal SPMSM voltage-model flux library and bench.
assert(strcmp(version('-release'),'2026b'));gate=library.settingsLookup();assert(gate.gatePass);
module=fileparts(fileparts(mfilename('fullpath')));lib=fileparts(fileparts(module));
addpath(fullfile(module,'src'),fullfile(module,'parameter'),fileparts(mfilename('fullpath')), ...
    fullfile(lib,'相位跟踪','src'),fullfile(lib,'相位跟踪','parameter'), ...
    fullfile(lib,'观测器','反电势','build_process'));load_system('AngleTracking');
model='FluxObserver';assert(~bdIsLoaded(model) && ~isfile(fullfile(module,'src',[model,'.slx'])));
new_system(model,'Library');open_system(model);
result=edit(model,'root',{struct('op','create_subsystem','name','Flux','ref','core', ...
    'interface',struct('inputs',{{}},'outputs',{{}}))},false,'full');scope=id(result,'core');
ins={'u_alpha','u_beta','i_alpha','i_beta','enable','reset'};
outs={'theta_e_hat','omega_e_hat','valid','rotor_flux_alpha','rotor_flux_beta', ...
    'stator_flux_alpha','stator_flux_beta','flux_magnitude','torque_hat','phase_measured', ...
    'phase_error','equivalent_residual','filtered_speed','compensation_ready'};
operations={};
for k=1:numel(ins),operations{end+1}=b('Inport',ins{k},struct('Port',num2str(k),'SampleTime','cfg.Ts'));end
for k=1:numel(outs),operations{end+1}=b('Outport',outs{k},struct('Port',num2str(k)));end
operations=[operations,{b('MATLAB Function','Compute',struct()),b('MATLAB Function','Predict',struct())}];
result=edit(model,scope,operations,false,'full');ports=struct();portNames=[ins,outs,{'Compute','Predict'}];
for k=1:numel(portNames),ports.(portNames{k})=id(result,portNames{k});end
for name={'Compute','Predict'}
    path=Simulink.ID.getFullName([model,':',extractAfter(ports.(name{1}),'blk_')]);
    config=get_param(path,'MATLABFunctionConfiguration');
    config.FunctionScript=fileread(fullfile(module,'src',['flux_',lower(name{1}),'.m']));
    disp(model_read(model,scope,'0'));
end
operations={b('Mux','VoltageAB',struct('Inputs','2')),b('Mux','CurrentAB',struct('Inputs','2')), ...
    b('Constant','Settings',struct('Value','[cfg.Ts;cfg.Rs;cfg.L;cfg.PolePairs;cfg.LeakA;cfg.LeakB;cfg.DcA;cfg.MinCompOmega;cfg.FullCompOmega;cfg.MaxCompGain;cfg.Flux]')), ...
    b('UnitDelay','FluxStates',struct('InitialCondition','zeros(4,1)','SampleTime','cfg.Ts')), ...
    b('UnitDelay','FrequencyState',struct('InitialCondition','0','SampleTime','cfg.Ts')), ...
    b('Logic','NotReset',struct('Operator','NOT')),b('Logic','Active',struct('Operator','AND','Inputs','2')), ...
    b('Gain','FrequencyMemory',struct('Gain','cfg.FrequencyA')),b('Gain','FrequencyInput',struct('Gain','1-cfg.FrequencyA')), ...
    b('Sum','FrequencyCandidate',struct('Inputs','++')),b('Constant','Zero',struct('Value','0')), ...
    b('Switch','FrequencyReset',struct('Criteria','u2 > Threshold','Threshold','0.5')), ...
    b('Demux','RotorChannels',struct('Outputs','2')),b('Demux','StatorChannels',struct('Outputs','2')), ...
    b('DotProduct','RotorSquared',struct()),b('Sqrt','Magnitude',struct()), ...
    b('Trigonometry','Phase',struct('Operator','atan2')), ...
    struct('op','add_block','type','PLL','ReferenceBlock','AngleTracking/PLL','name','PLL','ref','PLL', ...
        'params',struct('MaskValueString','trackerCfg')), ...
    b('Abs','SpeedMagnitude',struct()),b('Constant','MinimumSpeed',struct('Value','cfg.MinOmega')), ...
    b('RelationalOperator','SpeedOK',struct('Operator','>=')), ...
    b('Constant','MaximumResidual',struct('Value','cfg.MaxResidual')), ...
    b('RelationalOperator','ResidualOK',struct('Operator','<=')), ...
    b('Constant','MaximumFlux',struct('Value','cfg.MaxFlux')), ...
    b('RelationalOperator','FluxOK',struct('Operator','<=')), ...
    b('Logic','Valid',struct('Operator','AND','Inputs','6')),b('DataTypeConversion','ValidDouble',struct('OutDataTypeStr','double')), ...
    b('DataTypeConversion','ReadyDouble',struct('OutDataTypeStr','double')), ...
    b('Terminator','UnusedIntegral',struct()),b('Terminator','UnusedCount',struct())};
edges={'u_alpha','VoltageAB',1;'u_beta','VoltageAB',2;'i_alpha','CurrentAB',1;'i_beta','CurrentAB',2; ...
    'reset','NotReset',1;'NotReset','Active',2;'enable','Active',1; ...
    'FluxStates','Compute',1;'CurrentAB','Compute',2;'FrequencyState','Compute',3;'Active','Compute',4;'Settings','Compute',5; ...
    'FluxStates','Predict',1;'VoltageAB','Predict',2;'CurrentAB','Predict',3;'Active','Predict',4;'Settings','Predict',5; ...
    'Predict','FluxStates',1;'FrequencyState','FrequencyMemory',1;'FrequencyMemory','FrequencyCandidate',1; ...
    'FrequencyInput','FrequencyCandidate',2;'FrequencyCandidate','FrequencyReset',1; ...
    'Active','FrequencyReset',2;'Zero','FrequencyReset',3;'FrequencyReset','FrequencyState',1; ...
    'Magnitude','PLL',2;'Active','PLL',3;'reset','PLL',4; ...
    'Magnitude','FluxOK',1;'MaximumFlux','FluxOK',2;'SpeedMagnitude','SpeedOK',1;'MinimumSpeed','SpeedOK',2; ...
    'MaximumResidual','ResidualOK',2;'Active','Valid',2;'SpeedOK','Valid',3;'ResidualOK','Valid',4;'FluxOK','Valid',5; ...
    'Valid','ValidDouble',1;'ValidDouble','valid',1;'ReadyDouble','compensation_ready',1; ...
    'Phase','PLL',1;'Phase','phase_measured',1;'Magnitude','flux_magnitude',1;'FrequencyState','filtered_speed',1};
for k=1:size(edges,1),operations{end+1}=c(['#',edges{k,1},'.y1'],sprintf('#%s.u%d',edges{k,2},edges{k,3}));end
operations=[operations,{c('#Compute.y1','#RotorChannels.u1'),c('#Compute.y1','#RotorSquared.u1'),c('#Compute.y1','#RotorSquared.u2'), ...
    c('#Compute.y2','#StatorChannels.u1'),c('#Compute.y3','#torque_hat.u1'),c('#Compute.y4','#equivalent_residual.u1'), ...
    c('#Compute.y4','#ResidualOK.u1'),c('#Compute.y5','#Valid.u6'),c('#Compute.y5','#ReadyDouble.u1'), ...
    c('#RotorSquared.y1','#Magnitude.u1'),c('#RotorChannels.y2','#Phase.u1'),c('#RotorChannels.y1','#Phase.u2'), ...
    c('#PLL.y1','#theta_e_hat.u1'),c('#PLL.y2','#omega_e_hat.u1'),c('#PLL.y2','#SpeedMagnitude.u1'), ...
    c('#PLL.y2','#FrequencyInput.u1'),c('#PLL.y3','#phase_error.u1'),c('#PLL.y4','#Valid.u1'), ...
    c('#PLL.y5','#UnusedIntegral.u1'),c('#PLL.y6','#UnusedCount.u1')}];
for k=1:2
    operations=[operations,{c(sprintf('#RotorChannels.y%d',k),sprintf('#%s.u1',outs{k+3})), ...
        c(sprintf('#StatorChannels.y%d',k),sprintf('#%s.u1',outs{k+5}))}];
end
for k=1:numel(operations)
    if isfield(operations{k},'target')
        for name=portNames,operations{k}.target=strrep(operations{k}.target,['#',name{1},'.'],[ports.(name{1}),'.']);end
    end
end
edit(model,scope,operations,true,'incremental');
edit(model,'root',{struct('op','configure','target',scope,'params',struct('Mask','on', ...
    'MaskVariables','cfg=@1;trackerCfg=@2;','MaskStyleString','edit,edit', ...
    'MaskPromptString','Flux configuration|PLL configuration','MaskValueString','fluxCfg|pllCfg'))},false,'incremental');
save_system(model,fullfile(module,'src',[model,'.slx']));
test='FluxObserverTest';assert(~bdIsLoaded(test) && ~isfile(fullfile(module,'src',[test,'.slx'])));
new_system(test);open_system(test);initialize_flux_test(test);
callback=['addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));initialize_flux_test(bdroot);'];
operations={struct('op','configure','target',['config:',test],'params',struct('Solver','FixedStepDiscrete', ...
    'SolverType','Fixed-step','FixedStep','fluxCfg.Ts','StopTime','fluxTestCfg.Duration','ReturnWorkspaceOutputs','on','PostLoadFcn',callback)), ...
    b('FromWorkspace','Stimulus',struct('VariableName','testStim','Interpolate','off','SampleTime','fluxCfg.Ts','OutputAfterFinalValue','Holding final value')), ...
    b('Demux','Inputs',struct('Outputs','9')),struct('op','add_block','type','Flux','ReferenceBlock','FluxObserver/Flux', ...
        'name','Observer','ref','Observer','params',struct('MaskValueString','fluxCfg|pllCfg')), ...
    b('Mux','TraceChannels',struct('Inputs','24')),b('ToWorkspace','SaveTrace',struct('VariableName','trace','SaveFormat','Structure With Time','MaxDataPoints','inf')), ...
    b('Sum','AngleDifference',struct('Inputs','+-')),b('Trigonometry','ErrorSin',struct('Operator','sin')), ...
    b('Trigonometry','ErrorCos',struct('Operator','cos')),b('Trigonometry','AngleError',struct('Operator','atan2')), ...
    c('#Stimulus.y1','#Inputs.u1'),c('#Observer.y1','#AngleDifference.u1'),c('#Inputs.y8','#AngleDifference.u2'), ...
    c('#AngleDifference.y1','#ErrorSin.u1'),c('#AngleDifference.y1','#ErrorCos.u1'),c('#ErrorSin.y1','#AngleError.u1'), ...
    c('#ErrorCos.y1','#AngleError.u2'),c('#AngleError.y1','#TraceChannels.u24'),c('#TraceChannels.y1','#SaveTrace.u1')};
inputColumns=[1,2,3,4,6,7];
for k=1:6,operations{end+1}=c(sprintf('#Inputs.y%d',inputColumns(k)),sprintf('#Observer.u%d',k));end
for k=1:9,operations{end+1}=c(sprintf('#Inputs.y%d',k),sprintf('#TraceChannels.u%d',k));end
for k=1:14,operations{end+1}=c(sprintf('#Observer.y%d',k),sprintf('#TraceChannels.u%d',k+9));end
groups={'AngleScope',{'#Inputs.y8','#Observer.y1','#AngleError.y1'};'SpeedScope',{'#Inputs.y9','#Observer.y2'}; ...
    'RotorFluxScope',{'#Observer.y4','#Observer.y5','#Observer.y8'};'StatorFluxScope',{'#Observer.y6','#Observer.y7'}; ...
    'TorqueScope',{'#Observer.y9'};'QualityScope',{'#Observer.y3','#Observer.y12'}; ...
    'CompensationScope',{'#Observer.y13','#Observer.y14'}};
for g=1:size(groups,1)
    name=groups{g,1};sources=groups{g,2};mux=[name,'Channels'];
    operations=[operations,{b('Mux',mux,struct('Inputs',num2str(numel(sources)))),b('Scope',name,struct('NumInputPorts','1')),c(['#',mux,'.y1'],['#',name,'.u1'])}];
    for k=1:numel(sources),operations{end+1}=c(sources{k},sprintf('#%s.u%d',mux,k));end
end
result=edit(test,'root',operations,true,'full');observerId=id(result,'Observer');
observerPath=Simulink.ID.getFullName([test,':',extractAfter(observerId,'blk_')]);
box=get_param(observerPath,'Position');box(3:4)=box(1:2)+[340,400];
edit(test,'root',{struct('op','configure','target',observerId, ...
    'params',struct('Position',mat2str(box)))},false,'incremental');
edit(test,'root',{},true,'full');
save_system(test,fullfile(module,'src',[test,'.slx']));
end
function operation=b(type,name,parameters)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',parameters);
end
function operation=c(source,destination)
operation=struct('op','connect','target',[source,' -> ',destination]);
end
function result=edit(model,scope,operations,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(operations),layout);disp(result);
disp(model_read(model,scope,'0'));
if ~contains(string(result),'status: ok')
    disp(model_check(model,scope,'["all"]'));error('Inspect the current model before continuing.');
end
if complete
    check=model_check(model,scope,'["all"]');disp(check);assert(~contains(string(check),'severity: error'));
end
end
function value=id(result,reference)
matches=regexp(char(result),[reference,':\s*(blk_\d+)'],'tokens');assert(isscalar(matches));value=matches{1}{1};
end
