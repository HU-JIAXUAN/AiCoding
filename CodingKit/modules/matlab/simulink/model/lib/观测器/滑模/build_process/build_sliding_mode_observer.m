function build_sliding_mode_observer()
%BUILD_SLIDING_MODE_OBSERVER Build an inspectable boundary-layer SPMSM SMO.
assert(strcmp(version('-release'),'2026b'),'Build with MATLAB R2026b.');
gate=library.settingsLookup(); assert(gate.gatePass);
module=fileparts(fileparts(mfilename('fullpath')));
pllModule=fullfile(fileparts(fileparts(module)),'相位跟踪');
addpath(fullfile(module,'src'),fullfile(module,'parameter'),fullfile(module,'build_process'), ...
    fullfile(pllModule,'src'),fullfile(pllModule,'parameter'));
assert(isfile(fullfile(pllModule,'src','AngleTracking.slx')),'Build AngleTracking first.');
assert(~bdIsLoaded('SlidingModeObserver') && ~bdIsLoaded('SlidingModeObserverTest'));
assert(~isfile(fullfile(module,'src','SlidingModeObserver.slx')), ...
    'Source model already exists. Rebuild in a separate copy.');
new_system('SlidingModeObserver','Library'); open_system('SlidingModeObserver');
editScope('SlidingModeObserver','root',{struct('op','create_subsystem','name','SMO', ...
    'ref','smo','interface',struct('inputs',{{}},'outputs',{{}}))});
sid=Simulink.ID.getSID('SlidingModeObserver/SMO'); scope=['blk_',extractAfter(sid,':')];
o={}; ins={'u_alpha','u_beta','i_alpha','i_beta','direction','enable','reset'};
outs={'theta_e_hat','omega_e_hat','valid','emf_alpha','emf_beta','i_hat_alpha', ...
    'i_hat_beta','injection_alpha','injection_beta','phase_measured','emf_magnitude','phase_error'};
for k=1:numel(ins),o{end+1}=b('Inport',ins{k},struct('Port',num2str(k),'SampleTime','smoCfg.Ts'));end
for k=1:numel(outs),o{end+1}=b('Outport',outs{k},struct('Port',num2str(k)));end
o=[o,{b('Mux','voltage_ab',struct('Inputs','2')),b('Mux','current_ab',struct('Inputs','2')), ...
    b('Constant','zero_vector',struct('Value','[0;0]')),b('Constant','one',struct('Value','1')), ...
    b('Abs','abs_direction',struct()),b('RelationalOperator','direction_ok',struct('Operator','==')), ...
    b('UnitDelay','previous_direction',struct('InitialCondition','0','SampleTime','smoCfg.Ts')), ...
    b('RelationalOperator','direction_changed',struct('Operator','~=')), ...
    b('Logic','reset_any',struct('Operator','OR','Inputs','2')), ...
    b('Logic','not_reset',struct('Operator','NOT')), ...
    b('Logic','active',struct('Operator','AND','Inputs','3')), ...
    b('UnitDelay','current_state',struct('InitialCondition','[0;0]','SampleTime','smoCfg.Ts')), ...
    b('Sum','current_error',struct('Inputs','+-')), ...
    b('Gain','boundary_scale',struct('Gain','1/smoCfg.Boundary')), ...
    b('Saturate','boundary_layer',struct('UpperLimit','1','LowerLimit','-1')), ...
    b('Gain','sliding_injection',struct('Gain','smoCfg.SlidingGain')), ...
    b('Sum','voltage_residual',struct('Inputs','+-')), ...
    b('Gain','input_coefficient',struct('Gain','smoCfg.B')), ...
    b('Gain','current_coefficient',struct('Gain','smoCfg.A')), ...
    b('Sum','current_candidate',struct('Inputs','++')),sw('current_reset'), ...
    b('UnitDelay','emf_state',struct('InitialCondition','[0;0]','SampleTime','smoCfg.Ts')), ...
    b('Gain','filter_memory',struct('Gain','smoCfg.FilterA')), ...
    b('Gain','filter_input',struct('Gain','1-smoCfg.FilterA')), ...
    b('Sum','emf_candidate',struct('Inputs','++')),sw('emf_reset'), ...
    sw('emf_output'),sw('current_output'),sw('injection_output'), ...
    b('Demux','emf_components',struct('Outputs','2')), ...
    b('Demux','current_components',struct('Outputs','2')), ...
    b('Demux','injection_components',struct('Outputs','2')), ...
    b('Product','directed_alpha',struct('Inputs','**')),b('Gain','minus_alpha',struct('Gain','-1')), ...
    b('Product','directed_beta',struct('Inputs','**')), ...
    b('Trigonometry','emf_angle',struct('Operator','atan2')), ...
    b('DotProduct','emf_squared',struct()),b('Sqrt','emf_norm',struct()), ...
    b('UnitDelay','previous_speed',struct('InitialCondition','0','SampleTime','smoCfg.Ts')), ...
    b('Gain','discrete_frequency',struct('Gain','smoCfg.Ts')), ...
    b('Trigonometry','frequency_sin',struct('Operator','sin')), ...
    b('Trigonometry','frequency_cos',struct('Operator','cos')), ...
    b('Constant','filter_a',struct('Value','smoCfg.FilterA')), ...
    b('Sum','phase_denominator',struct('Inputs','+-')), ...
    b('Trigonometry','filter_phase',struct('Operator','atan2')), ...
    b('Gain','phase_compensation',struct('Gain','smoCfg.Compensate')), ...
    b('Sum','corrected_phase',struct('Inputs','++')), ...
    struct('op','add_block','type','PLL','ReferenceBlock','AngleTracking/PLL','name','PLL','ref','pll'), ...
    b('Abs','abs_speed',struct()),b('Constant','min_speed',struct('Value','smoCfg.MinOmega')), ...
    b('RelationalOperator','speed_ok',struct('Operator','>=')), ...
    b('Logic','valid_logic',struct('Operator','AND','Inputs','3')), ...
    b('DataTypeConversion','valid_double',struct('OutDataTypeStr','double')), ...
    b('Terminator','unused_integral',struct()),b('Terminator','unused_count',struct())}];
o=[o,wrapBlocks('phase_wrap')];
e={'u_alpha','voltage_ab',1;'u_beta','voltage_ab',2;'i_alpha','current_ab',1;'i_beta','current_ab',2; ...
    'direction','abs_direction',1;'abs_direction','direction_ok',1;'one','direction_ok',2; ...
    'direction','previous_direction',1;'direction','direction_changed',1;'previous_direction','direction_changed',2; ...
    'reset','reset_any',1;'direction_changed','reset_any',2;'reset_any','not_reset',1; ...
    'enable','active',1;'direction_ok','active',2;'not_reset','active',3; ...
    'current_state','current_error',1;'current_ab','current_error',2;'current_error','boundary_scale',1; ...
    'boundary_scale','boundary_layer',1;'boundary_layer','sliding_injection',1; ...
    'voltage_ab','voltage_residual',1;'sliding_injection','voltage_residual',2; ...
    'voltage_residual','input_coefficient',1;'current_state','current_coefficient',1; ...
    'input_coefficient','current_candidate',1;'current_coefficient','current_candidate',2; ...
    'current_candidate','current_reset',1;'active','current_reset',2;'zero_vector','current_reset',3; ...
    'current_reset','current_state',1;'emf_state','filter_memory',1;'sliding_injection','filter_input',1; ...
    'filter_memory','emf_candidate',1;'filter_input','emf_candidate',2; ...
    'emf_candidate','emf_reset',1;'active','emf_reset',2;'zero_vector','emf_reset',3;'emf_reset','emf_state',1; ...
    'emf_state','emf_output',1;'active','emf_output',2;'zero_vector','emf_output',3; ...
    'current_state','current_output',1;'active','current_output',2;'zero_vector','current_output',3; ...
    'sliding_injection','injection_output',1;'active','injection_output',2;'zero_vector','injection_output',3; ...
    'emf_output','emf_components',1;'current_output','current_components',1;'injection_output','injection_components',1; ...
    'direction','directed_alpha',2;'direction','directed_beta',2;'directed_alpha','minus_alpha',1; ...
    'minus_alpha','emf_angle',1;'directed_beta','emf_angle',2; ...
    'emf_output','emf_squared',1;'emf_output','emf_squared',2;'emf_squared','emf_norm',1; ...
    'previous_speed','discrete_frequency',1;'discrete_frequency','frequency_sin',1;'discrete_frequency','frequency_cos',1; ...
    'frequency_cos','phase_denominator',1;'filter_a','phase_denominator',2; ...
    'frequency_sin','filter_phase',1;'phase_denominator','filter_phase',2;'filter_phase','phase_compensation',1; ...
    'emf_angle','corrected_phase',1;'phase_compensation','corrected_phase',2; ...
    'corrected_phase','phase_wrap_sin',1;'corrected_phase','phase_wrap_cos',1; ...
    'phase_wrap','pll',1;'emf_norm','pll',2;'active','pll',3;'reset_any','pll',4; ...
    'abs_speed','speed_ok',1;'min_speed','speed_ok',2;'speed_ok','valid_logic',2;'active','valid_logic',3; ...
    'valid_logic','valid_double',1;'valid_double','valid',1;'emf_norm','emf_magnitude',1;'phase_wrap','phase_measured',1};
o=wire(o,e);
o=[o,{c('#emf_components.y1','#directed_alpha.u1'),c('#emf_components.y2','#directed_beta.u1'), ...
    c('#pll.y1','#theta_e_hat.u1'),c('#pll.y2','#omega_e_hat.u1'),c('#pll.y2','#previous_speed.u1'), ...
    c('#pll.y2','#abs_speed.u1'),c('#pll.y3','#phase_error.u1'),c('#pll.y4','#valid_logic.u1'), ...
    c('#pll.y5','#unused_integral.u1'),c('#pll.y6','#unused_count.u1')}];
for k=1:2
    o{end+1}=c(sprintf('#emf_components.y%d',k),sprintf('#%s.u1',outs{k+3}));
    o{end+1}=c(sprintf('#current_components.y%d',k),sprintf('#%s.u1',outs{k+5}));
    o{end+1}=c(sprintf('#injection_components.y%d',k),sprintf('#%s.u1',outs{k+7}));
end
editScope('SlidingModeObserver',scope,o);
save_system('SlidingModeObserver',fullfile(module,'src','SlidingModeObserver.slx'));
new_system('SlidingModeObserverTest');open_system('SlidingModeObserverTest');
initialize_smo_test('SlidingModeObserverTest');
cb=['addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));initialize_smo_test(bdroot);'];
o={struct('op','configure','target','config:SlidingModeObserverTest','params',struct( ...
    'Solver','FixedStepDiscrete','SolverType','Fixed-step','FixedStep','smoCfg.Ts','StopTime','smoTestCfg.Duration', ...
    'ReturnWorkspaceOutputs','on','PostLoadFcn',cb)), ...
    b('FromWorkspace','stimulus',struct('VariableName','testStim','Interpolate','off','SampleTime','smoCfg.Ts','OutputAfterFinalValue','Holding final value')), ...
    b('Demux','inputs',struct('Outputs','9')), ...
    struct('op','add_block','type','SMO','ReferenceBlock','SlidingModeObserver/SMO','name','SMO','ref','smo'), ...
    b('Mux','trace_mux',struct('Inputs','22')), ...
    b('ToWorkspace','trace',struct('VariableName','trace','SaveFormat','Structure With Time','MaxDataPoints','inf')), ...
    b('Sum','angle_delta',struct('Inputs','+-'))};
o=[o,wrapBlocks('angle_error')];
o{end+1}=c('#stimulus.y1','#inputs.u1');
for k=1:7,o{end+1}=c(sprintf('#inputs.y%d',k),sprintf('#smo.u%d',k));end
for k=1:9,o{end+1}=c(sprintf('#inputs.y%d',k),sprintf('#trace_mux.u%d',k));end
for k=1:12,o{end+1}=c(sprintf('#smo.y%d',k),sprintf('#trace_mux.u%d',k+9));end
o=[o,{c('#smo.y1','#angle_delta.u1'),c('#inputs.y8','#angle_delta.u2'), ...
    c('#angle_delta.y1','#angle_error_sin.u1'),c('#angle_delta.y1','#angle_error_cos.u1'), ...
    c('#angle_error.y1','#trace_mux.u22'),c('#trace_mux.y1','#trace.u1')}];
groups={ 'AngleScope',{'#inputs.y8','#smo.y1','#angle_error.y1'}; ...
    'SpeedScope',{'#inputs.y9','#smo.y2'}; ...
    'EmfScope',{'#smo.y4','#smo.y5','#smo.y11'}; ...
    'CurrentScope',{'#inputs.y3','#smo.y6','#inputs.y4','#smo.y7'}; ...
    'StatusScope',{'#inputs.y5','#inputs.y6','#inputs.y7','#smo.y3','#smo.y12'}};
labels={{'theta_true','theta_e_hat','angle_error'}, {'omega_true','omega_e_hat'}, ...
    {'emf_alpha','emf_beta','emf_magnitude'}, {'i_alpha','i_hat_alpha','i_beta','i_hat_beta'}, ...
    {'direction','enable','reset','valid','phase_error'}};
for g=1:size(groups,1)
    name=groups{g,1}; channels=groups{g,2}; mux=[name,'_channels'];
    o{end+1}=b('Mux',mux,struct('Inputs',num2str(numel(channels))));
    o{end+1}=b('Scope',name,struct('NumInputPorts','1'));
    for k=1:numel(channels),o{end+1}=c(channels{k},sprintf('#%s.u%d',mux,k),labels{g}{k});end
    o{end+1}=c(['#',mux,'.y1'],['#',name,'.u1']);
end
editScope('SlidingModeObserverTest','root',o);
save_system('SlidingModeObserverTest',fullfile(module,'src','SlidingModeObserverTest.slx'));
print('-sSlidingModeObserver/SMO','-dpng',fullfile(module,'build_process','smo_diagram.png'));
print('-sSlidingModeObserverTest','-dpng',fullfile(module,'build_process','test_diagram.png'));
end
function s=b(type,name,params)
s=struct('op','add_block','type',type,'name',name,'ref',name,'params',params);
end
function s=sw(name)
s=b('Switch',name,struct('Criteria','u2 > Threshold','Threshold','0.5'));
end
function s=c(source,destination,name)
s=struct('op','connect','target',[source,' -> ',destination]);
if nargin>2,s.params=struct('Name',name);end
end
function o=wire(o,edges)
for k=1:size(edges,1),o{end+1}=c(['#',edges{k,1},'.y1'],sprintf('#%s.u%d',edges{k,2},edges{k,3}));end
end
function o=wrapBlocks(name)
o={b('Trigonometry',[name,'_sin'],struct('Operator','sin')),b('Trigonometry',[name,'_cos'],struct('Operator','cos')), ...
    b('Trigonometry',name,struct('Operator','atan2')),c(['#',name,'_sin.y1'],['#',name,'.u1']),c(['#',name,'_cos.y1'],['#',name,'.u2'])};
end
function editScope(model,scope,operations)
disp(model_read(model,scope,'0'));r=model_edit(model,scope,jsonencode(operations),'full');disp(r);
disp(model_read(model,scope,'0'));check=model_check(model,scope,'["all"]');disp(check);
assert(contains(string(r),'status: ok') && ~contains(string(check),'severity: error'), ...
    'Inspect the editor or structural-check result before continuing.');
end
