function build_sigmoid_smo()
%BUILD_SIGMOID_SMO Create a separate smooth library and linked Test bench.
assert(strcmp(version('-release'),'2026b'));gate=library.settingsLookup();assert(gate.gatePass);
module=initialize_sigmoid_smo_paths();lib='SigmoidSlidingModeObserver';test='SigmoidSlidingModeObserverTest';
assert(~bdIsLoaded(lib) && ~bdIsLoaded(test));
assert(~isfile(fullfile(module,'src',[lib,'.slx'])) && ~isfile(fullfile(module,'src',[test,'.slx'])));
new_system(lib,'Library');
result=edit(lib,'root',{struct('op','create_subsystem','name','SigmoidSMO','ref','core', ...
    'interface',struct('inputs',{{}},'outputs',{{}}))},false,'full');scope=id(result,'core');
mask=struct('Mask','on','MaskVariables','cfg=@1;trackerCfg=@2;','MaskStyleString','edit,edit', ...
    'MaskPromptString','Sigmoid SMO configuration|PLL configuration', ...
    'MaskValueString','sigmoid_smo_parameters()|sigmoid_smo_pll_parameters()');
edit(lib,'root',{struct('op','configure','target',scope,'params',mask)},false,'incremental');
ins={'u_alpha','u_beta','i_alpha','i_beta','direction','enable','reset'};
outs={'theta_e_hat','omega_e_hat','valid','emf_alpha','emf_beta','i_hat_alpha','i_hat_beta', ...
    'residual_alpha','residual_beta','phase_measured','emf_magnitude','phase_error','fault','residual_norm'};
ops={};
for k=1:numel(ins),ops{end+1}=b('Inport',ins{k},struct('Port',num2str(k),'SampleTime','cfg.Ts'));end
for k=1:numel(outs),ops{end+1}=b('Outport',outs{k},struct('Port',num2str(k)));end
ops=[ops,{b('MATLAB Function','Measure',struct()),b('MATLAB Function','Predict',struct())}];
result=edit(lib,scope,ops,false,'full');ports=struct();names=[ins,outs,{'Measure','Predict'}];
for k=1:numel(names),ports.(names{k})=id(result,names{k});end
for pair={{'Measure','sigmoid_smo_measure.m'},{'Predict','sigmoid_smo_predict.m'}}
    entry=pair{1};block=Simulink.ID.getFullName([lib,':',extractAfter(ports.(entry{1}),'blk_')]);
    configuration=get_param(block,'MATLABFunctionConfiguration');configuration.FunctionScript=fileread(fullfile(module,'src',entry{2}));
end
disp(model_read(lib,scope,'0'));
ops={b('Mux','VoltageAB',struct('Inputs','2')),b('Mux','CurrentAB',struct('Inputs','2')), ...
    b('Constant','Settings',struct('Value','cfg.Settings')),b('UnitDelay','CurrentMemory',struct('InitialCondition','zeros(4,1)','SampleTime','cfg.Ts')), ...
    b('Demux','InjectionChannels',struct('Outputs','2')),b('Demux','CurrentChannels',struct('Outputs','2')),b('Demux','ResidualChannels',struct('Outputs','2')), ...
    struct('op','add_block','type','PLL','ReferenceBlock','AngleTracking/PLL','name','PLL','ref','PLL','params',struct('MaskValueString','trackerCfg')), ...
    b('Product','DirectedSpeed',struct('Inputs','**')),b('Constant','MinimumSpeed',struct('Value','cfg.MinOmega')), ...
    b('Constant','MaximumSpeed',struct('Value','cfg.MaxOmega')),b('Constant','MaximumResidual',struct('Value','cfg.MaxResidual')), ...
    b('RelationalOperator','MinimumSpeedOK',struct('Operator','>=')),b('RelationalOperator','MaximumSpeedOK',struct('Operator','<=')), ...
    b('RelationalOperator','ResidualOK',struct('Operator','<=')),b('Logic','Valid',struct('Operator','AND','Inputs','5')), ...
    b('DataTypeConversion','ValidDouble',struct('OutDataTypeStr','double')),b('Terminator','UnusedIntegral',struct()),b('Terminator','UnusedCount',struct())};
edges={'u_alpha','VoltageAB',1;'u_beta','VoltageAB',2;'i_alpha','CurrentAB',1;'i_beta','CurrentAB',2; ...
    'CurrentMemory','Measure',1;'CurrentAB','Measure',2;'direction','Measure',3;'enable','Measure',4;'reset','Measure',5;'Settings','Measure',6; ...
    'CurrentMemory','Predict',1;'VoltageAB','Predict',2;'direction','Predict',3;'enable','Predict',4;'reset','Predict',5;'Settings','Predict',9; ...
    'direction','DirectedSpeed',2;'DirectedSpeed','MinimumSpeedOK',1;'MinimumSpeed','MinimumSpeedOK',2; ...
    'DirectedSpeed','MaximumSpeedOK',1;'MaximumSpeed','MaximumSpeedOK',2;'MaximumResidual','ResidualOK',2; ...
    'MinimumSpeedOK','Valid',3;'MaximumSpeedOK','Valid',4;'ResidualOK','Valid',5;'Valid','ValidDouble',1;'ValidDouble','valid',1};
for k=1:size(edges,1),ops{end+1}=c(['#',edges{k,1},'.y1'],sprintf('#%s.u%d',edges{k,2},edges{k,3}));end
more={'#Predict.y1','#CurrentMemory.u1';'#Measure.y1','#InjectionChannels.u1';'#Measure.y2','#CurrentChannels.u1'; ...
    '#Measure.y3','#ResidualChannels.u1';'#Measure.y4','#PLL.u1';'#Measure.y4','#phase_measured.u1'; ...
    '#Measure.y5','#PLL.u2';'#Measure.y5','#emf_magnitude.u1';'#Measure.y6','#PLL.u3';'#Measure.y6','#Valid.u2'; ...
    '#Measure.y6','#Predict.u6';'#Measure.y7','#PLL.u4';'#Measure.y8','#fault.u1';'#Measure.y8','#Predict.u8'; ...
    '#Measure.y9','#residual_norm.u1';'#Measure.y9','#ResidualOK.u1';'#Measure.y1','#Predict.u7'; ...
    '#PLL.y1','#theta_e_hat.u1';'#PLL.y2','#omega_e_hat.u1';'#PLL.y2','#DirectedSpeed.u1';'#PLL.y3','#phase_error.u1'; ...
    '#PLL.y4','#Valid.u1';'#PLL.y5','#UnusedIntegral.u1';'#PLL.y6','#UnusedCount.u1'; ...
    '#InjectionChannels.y1','#emf_alpha.u1';'#InjectionChannels.y2','#emf_beta.u1'; ...
    '#CurrentChannels.y1','#i_hat_alpha.u1';'#CurrentChannels.y2','#i_hat_beta.u1'; ...
    '#ResidualChannels.y1','#residual_alpha.u1';'#ResidualChannels.y2','#residual_beta.u1'};
for k=1:size(more,1),ops{end+1}=c(more{k,1},more{k,2});end
edit(lib,scope,resolve(ops,ports),true,'incremental');
callback='addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));initialize_sigmoid_smo_paths();';
% Library root exports intentionally have no callers; connectivity was checked inside the exported subsystem.
edit(lib,'root',{struct('op','configure','target',['config:',lib],'params',struct('PostLoadFcn',callback,'Lock','on'))},false,'incremental');
save_system(lib,fullfile(module,'src',[lib,'.slx']));close_system(lib,0);
new_system(test);initialize_sigmoid_smo_test(test);
callback='addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));initialize_sigmoid_smo_test(bdroot);';
ops={struct('op','configure','target',['config:',test],'params',struct('Solver','FixedStepDiscrete','SolverType','Fixed-step', ...
    'FixedStep','sigmoidCfg.Ts','StopTime','sigmoidTestCfg.Duration','ReturnWorkspaceOutputs','on','PostLoadFcn',callback)), ...
    b('FromWorkspace','Stimulus',struct('VariableName','testStim','Interpolate','off','SampleTime','sigmoidCfg.Ts','OutputAfterFinalValue','Holding final value')), ...
    b('Demux','Inputs',struct('Outputs','9')),struct('op','add_block','type','SigmoidSMO','ReferenceBlock',[lib,'/SigmoidSMO'], ...
        'name','Observer','ref','Observer','params',struct('MaskValueString','sigmoidCfg|pllCfg')), ...
    b('Mux','Trace',struct('Inputs','24')),b('ToWorkspace','SaveTrace',struct('VariableName','trace','SaveFormat','Structure With Time', ...
        'SampleTime','sigmoidCfg.Ts','MaxDataPoints','inf')),b('Sum','AngleDifference',struct('Inputs','+-')), ...
    b('Trigonometry','ErrorSin',struct('Operator','sin')),b('Trigonometry','ErrorCos',struct('Operator','cos')), ...
    b('Trigonometry','AngleError',struct('Operator','atan2')),c('#Stimulus.y1','#Inputs.u1'),c('#Trace.y1','#SaveTrace.u1'), ...
    c('#Observer.y1','#AngleDifference.u1'),c('#Inputs.y8','#AngleDifference.u2'),c('#AngleDifference.y1','#ErrorSin.u1'), ...
    c('#AngleDifference.y1','#ErrorCos.u1'),c('#ErrorSin.y1','#AngleError.u1'),c('#ErrorCos.y1','#AngleError.u2'),c('#AngleError.y1','#Trace.u24')};
for k=1:9,ops{end+1}=c(sprintf('#Inputs.y%d',k),sprintf('#Trace.u%d',k));end
for k=1:7,ops{end+1}=c(sprintf('#Inputs.y%d',k),sprintf('#Observer.u%d',k));end
for k=1:14,ops{end+1}=c(sprintf('#Observer.y%d',k),sprintf('#Trace.u%d',9+k));end
groups={'AngleScope',{'#Inputs.y8','#Observer.y1','#AngleError.y1','#Observer.y12'}; ...
    'SpeedScope',{'#Inputs.y9','#Observer.y2'};'EmfScope',{'#Observer.y4','#Observer.y5','#Observer.y11'}; ...
    'CurrentScope',{'#Inputs.y3','#Observer.y6','#Inputs.y4','#Observer.y7'}; ...
    'ResidualScope',{'#Observer.y8','#Observer.y9','#Observer.y14'}; ...
    'StatusScope',{'#Inputs.y5','#Inputs.y6','#Inputs.y7','#Observer.y3','#Observer.y13'}};
for g=1:size(groups,1)
    name=groups{g,1};sources=groups{g,2};mux=[name,'Channels'];
    ops=[ops,{b('Mux',mux,struct('Inputs',num2str(numel(sources)))),b('Scope',name,struct('NumInputPorts','1')),c(['#',mux,'.y1'],['#',name,'.u1'])}];
    for k=1:numel(sources),ops{end+1}=c(sources{k},sprintf('#%s.u%d',mux,k));end
end
edit(test,'root',ops,true,'full');save_system(test,fullfile(module,'src',[test,'.slx']));
check=get_param(test,'SimulationStatus');assert(strcmp(check,'stopped'));close_system(test,0);if bdIsLoaded(lib),close_system(lib,0);end
fprintf('Created separate sigmoid library and linked Test, closed editors.\n');
end
function result=edit(model,scope,operations,complete,layout)
disp(model_read(model,scope,'0'));result=model_edit(model,scope,jsonencode(operations),layout);disp(result);disp(model_read(model,scope,'0'));
if ~contains(string(result),'status: ok'),disp(model_check(model,scope,'["all"]'));error('SigmoidSMO:Edit','%s',char(result));end
if complete,check=model_check(model,scope,'["all"]');disp(check);assert(~contains(string(check),'severity: error'));end
end
function op=b(type,name,params)
op=struct('op','add_block','type',type,'name',name,'ref',name,'params',params);
end
function op=c(a,b)
op=struct('op','connect','target',[a,' -> ',b]);
end
function value=id(result,reference)
matches=regexp(char(result),['(?m)^[ \t]*',regexptranslate('escape',reference),':[ \t]*(blk_\d+)'],'tokens');assert(isscalar(matches));value=matches{1}{1};
end
function ops=resolve(ops,ports)
names=fieldnames(ports);
for k=1:numel(ops)
    if isfield(ops{k},'target')
        for n=1:numel(names),ops{k}.target=strrep(ops{k}.target,['#',names{n},'.'],[ports.(names{n}),'.']);end
    end
end
end
