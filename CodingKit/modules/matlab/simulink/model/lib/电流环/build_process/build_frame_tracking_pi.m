function build_frame_tracking_pi(outputFolder)
%BUILD_FRAME_TRACKING_PI Extend CurrentControl, saving first to an isolated folder.
% Existing TrackingPI/VoltageLimit are preserved. Refresh the two source
% functions if FrameTrackingPI already exists. Validate before promotion.
assert(strcmp(version('-release'),'2026b'));
gate=library.settingsLookup();assert(gate.gatePass);
module=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(module,'src'),fullfile(module,'parameter'),fileparts(mfilename('fullpath')));
assert(nargin==1 && isfolder(outputFolder),'Choose an existing isolated output directory.');
libraryName='CurrentControl';testName='FrameTrackingPITest';
assert(~bdIsLoaded(testName),'Close the existing test before building an isolated candidate.');
assert(~isfile(fullfile(outputFolder,[libraryName,'.slx'])) && ...
    ~isfile(fullfile(outputFolder,[testName,'.slx'])));
load_system(fullfile(module,'src',[libraryName,'.slx']));
assert(strcmpi(get_param(libraryName,'FileName'),fullfile(module,'src',[libraryName,'.slx'])));
assert(strcmp(get_param(libraryName,'Dirty'),'off'),'Save or discard existing edits before building.');
rootRead=model_read(libraryName,'root','0');disp(rootRead);
existing=regexp(char(rootRead),'- id: (blk_\d+)\s+Name: FrameTrackingPI','tokens');
assert(numel(existing)<=1);
% Switch the in-memory diagram to the candidate path before any mutation.
save_system(libraryName,fullfile(outputFolder,[libraryName,'.slx']));
edit(libraryName,'root',{struct('op','configure','target',['config:',libraryName], ...
    'params',struct('Lock','off'))},false,'incremental');
if isempty(existing)
result=edit(libraryName,'root',{struct('op','create_subsystem','name','FrameTrackingPI', ...
    'ref','framePI','interface',struct('inputs',{{}},'outputs',{{}}))},false,'incremental');
subId=createdId(result,'framePI');
subPath=Simulink.ID.getFullName([libraryName,':',extractAfter(subId,'blk_')]);
result=edit(libraryName,subId,{b('MATLAB Function','Compute',struct()), ...
    b('MATLAB Function','Update',struct())},false,'full');
computeId=createdId(result,'Compute');updateId=createdId(result,'Update');
corePaths={Simulink.ID.getFullName([libraryName,':',extractAfter(computeId,'blk_')]), ...
    Simulink.ID.getFullName([libraryName,':',extractAfter(updateId,'blk_')])};
else
    subId=existing{1}{1};
    subPath=Simulink.ID.getFullName([libraryName,':',extractAfter(subId,'blk_')]);
    corePaths=cell(1,2);names={'Compute','Update'};
    for index=1:2
        observed=find_system(subPath,'SearchDepth',1,'LookUnderMasks','all','Name',names{index});
        assert(numel(observed)==1);corePaths{index}=observed{1};
    end
end
sources={'frame_pi_compute.m','frame_pi_update.m'};
for index=1:2
    configuration=get_param(corePaths{index},'MATLABFunctionConfiguration');
    configuration.FunctionScript=fileread(fullfile(module,'src',sources{index}));
end
disp(model_read(libraryName,subId,'0'));
if isempty(existing)
inputs={'error_dq','voltage_residual','feedforward_dq','delta_extra','track','enable','reset'};
outputs={'voltage_pi','integral_base','integral_state'};operations={};
for index=1:7,operations{end+1}=b('Inport',inputs{index},struct('Port',num2str(index),'SampleTime','currentCfg.Ts'));end
for index=1:3,operations{end+1}=b('Outport',outputs{index},struct('Port',num2str(index)));end
operations=[operations,{b('UnitDelay','state',struct('InitialCondition','zeros(8,1)','SampleTime','currentCfg.Ts')), ...
    b('Mux','compute_input',struct('Inputs','6')),b('Mux','update_input',struct('Inputs','4')), ...
    b('Mux','next_state',struct('Inputs','2')), ...
    b('Constant','Kp',struct('Value','[currentCfg.Kpd;currentCfg.Kpq]')), ...
    b('Constant','UpdateParameters',struct('Value','[currentCfg.Ts;currentCfg.Kid;currentCfg.Kiq;currentCfg.Kaw]')), ...
    c('#state.y1',[computeId,'.u1']),c('#compute_input.y1',[computeId,'.u2']),c('#Kp.y1',[computeId,'.u3']), ...
    c([computeId,'.y2'],[updateId,'.u1']),c('#update_input.y1',[updateId,'.u2']), ...
    c('#UpdateParameters.y1',[updateId,'.u3']),c([updateId,'.y1'],'#next_state.u1'), ...
    c([computeId,'.y3'],'#next_state.u2'),c('#next_state.y1','#state.u1'), ...
    c([computeId,'.y1'],'#voltage_pi.u1'),c([computeId,'.y2'],'#integral_base.u1'), ...
    c([computeId,'.y4'],'#integral_state.u1')}];
computeInputs=[1,3,4,5,6,7];updateInputs=[1,2,6,7];
for index=1:6,operations{end+1}=c(['#',inputs{computeInputs(index)},'.y1'],sprintf('#compute_input.u%d',index));end
for index=1:4,operations{end+1}=c(['#',inputs{updateInputs(index)},'.y1'],sprintf('#update_input.u%d',index));end
edit(libraryName,subId,operations,true,'full');
else
    check=model_check(libraryName,subId,'["all"]');disp(check);
    assert(~contains(string(check),'severity: error'));
end
edit(libraryName,'root',{struct('op','configure','target',subId,'params', ...
    struct('Mask','on','MaskVariables','currentCfg=@1;','MaskStyleString','edit', ...
    'MaskPromptString','Current controller configuration','MaskValueString','currentCfg')), ...
    struct('op','configure','target',['config:',libraryName],'params',struct('Lock','on'))},false,'incremental');
save_system(libraryName,fullfile(outputFolder,[libraryName,'.slx']));

assert(~bdIsLoaded(testName));new_system(testName);open_system(testName);initialize_frame_pi_test(testName);
callback=['addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));', ...
    'initialize_frame_pi_test(bdroot);'];
% The load callback is valid after promotion into module/src. The isolated
% validation uses the already initialized, loaded candidate.
referencePI=Simulink.ID.getFullName('CurrentControl:1');
referenceLimit=Simulink.ID.getFullName('CurrentControl:10');
operations={struct('op','configure','target',['config:',testName],'params', ...
    struct('Solver','FixedStepDiscrete','SolverType','Fixed-step','FixedStep','currentCfg.Ts', ...
    'StopTime','testCfg.StopTime','ReturnWorkspaceOutputs','on','PostLoadFcn',callback)), ...
    b('FromWorkspace','stimulus',struct('VariableName','testStim','Interpolate','off', ...
    'SampleTime','currentCfg.Ts','OutputAfterFinalValue','Holding final value')), ...
    b('Demux','inputs',struct('Outputs','10')),b('Mux','error',struct('Inputs','2')), ...
    b('Mux','external_residual',struct('Inputs','2')),b('Mux','raw_feedforward',struct('Inputs','2')), ...
    struct('op','add_block','type','FrameTrackingPI','ReferenceBlock',subPath,'name','FramePI','ref','pi'), ...
    struct('op','add_block','type','TrackingPI','ReferenceBlock',referencePI,'name','ReferencePI','ref','old'), ...
    struct('op','add_block','type','VoltageLimit','ReferenceBlock',referenceLimit,'name','VoltageLimit','ref','limit'), ...
    b('Logic','NotReset',struct('Operator','NOT','Inputs','1')), ...
    b('Logic','Active',struct('Operator','AND','Inputs','2')), ...
    b('DataTypeConversion','ActiveDouble',struct('OutDataTypeStr','double')), ...
    b('Constant','ZeroVector',struct('Value','[0;0]')), ...
    b('Switch','GateFeedforward',struct('Criteria','u2 ~= 0')), ...
    b('Sum','TotalVoltage',struct('Inputs','++')),b('Sum','InternalResidual',struct('Inputs','+-')), ...
    b('Constant','InternalLimitSelected',struct('Value','testCfg.UseInternalLimit')), ...
    b('Switch','ResidualUsed',struct('Criteria','u2 ~= 0')), ...
    b('Mux','trace_mux',struct('Inputs','21')), ...
    b('ToWorkspace','trace',struct('VariableName','trace','SaveFormat','Structure With Time','MaxDataPoints','inf')), ...
    c('#stimulus.y1','#inputs.u1'),c('#trace_mux.y1','#trace.u1'), ...
    c('#inputs.y1','#error.u1'),c('#inputs.y2','#error.u2'), ...
    c('#inputs.y3','#external_residual.u1'),c('#inputs.y4','#external_residual.u2'), ...
    c('#inputs.y5','#raw_feedforward.u1'),c('#inputs.y6','#raw_feedforward.u2'), ...
    c('#inputs.y10','#NotReset.u1'),c('#inputs.y9','#Active.u1'),c('#NotReset.y1','#Active.u2'), ...
    c('#Active.y1','#ActiveDouble.u1'),c('#Active.y1','#GateFeedforward.u2'), ...
    c('#raw_feedforward.y1','#GateFeedforward.u1'),c('#ZeroVector.y1','#GateFeedforward.u3'), ...
    c('#error.y1','#pi.u1'),c('#ResidualUsed.y1','#pi.u2'),c('#GateFeedforward.y1','#pi.u3'), ...
    c('#inputs.y7','#pi.u4'),c('#inputs.y8','#pi.u5'),c('#inputs.y9','#pi.u6'),c('#inputs.y10','#pi.u7'), ...
    c('#error.y1','#old.u1'),c('#ResidualUsed.y1','#old.u2'),c('#inputs.y9','#old.u3'),c('#inputs.y10','#old.u4'), ...
    c('#pi.y1','#TotalVoltage.u1'),c('#GateFeedforward.y1','#TotalVoltage.u2'), ...
    c('#TotalVoltage.y1','#limit.u1'),c('#limit.y1','#InternalResidual.u1'),c('#TotalVoltage.y1','#InternalResidual.u2'), ...
    c('#InternalResidual.y1','#ResidualUsed.u1'),c('#InternalLimitSelected.y1','#ResidualUsed.u2'), ...
    c('#external_residual.y1','#ResidualUsed.u3')};
for index=1:10,operations{end+1}=c(sprintf('#inputs.y%d',index),sprintf('#trace_mux.u%d',index));end
recordSources={'#pi.y1','#pi.y2','#pi.y3','#GateFeedforward.y1','#TotalVoltage.y1','#limit.y1', ...
    '#ResidualUsed.y1','#old.y1','#old.y2','#limit.y2','#ActiveDouble.y1'};
for index=1:numel(recordSources),operations{end+1}=c(recordSources{index},sprintf('#trace_mux.u%d',index+10));end
groups={'ErrorScope',{'#error.y1'};'VoltageScope',{'#TotalVoltage.y1','#limit.y1'}; ...
    'IntegralScope',{'#pi.y2','#pi.y3'};'ResidualScope',{'#ResidualUsed.y1'}; ...
    'ReferenceScope',{'#pi.y1','#old.y1'};'TransferScope',{'#inputs.y7','#inputs.y8','#ActiveDouble.y1'}};
for group=1:size(groups,1)
    name=groups{group,1};sources=groups{group,2};mux=[name,'_channels'];
    operations=[operations,{b('Mux',mux,struct('Inputs',num2str(numel(sources)))), ...
        b('Scope',name,struct('NumInputPorts','1')),c(['#',mux,'.y1'],['#',name,'.u1'])}];
    for index=1:numel(sources),operations{end+1}=c(sources{index},sprintf('#%s.u%d',mux,index));end
end
edit(testName,'root',operations,true,'full');
save_system(testName,fullfile(outputFolder,[testName,'.slx']));
print(['-s',subPath],'-dpng',fullfile(module,'build_process','frame_pi_diagram.png'));
print(['-s',testName],'-dpng',fullfile(module,'build_process','frame_pi_test_diagram.png'));
end
function operation=b(type,name,parameters)
operation=struct('op','add_block','type',type,'name',name,'ref',name,'params',parameters);
end
function operation=c(source,destination)
operation=struct('op','connect','target',[source,' -> ',destination]);
end
function id=createdId(result,reference)
match=regexp(char(result),[reference,':\s*(blk_\d+)'],'tokens');
assert(isscalar(match),'Inspect the editor-created map.');id=match{1}{1};
end
function result=edit(model,scope,operations,complete,layout)
disp(model_read(model,scope,'0'));
result=model_edit(model,scope,jsonencode(operations),layout);disp(result);
disp(model_read(model,scope,'0'));
if ~contains(string(result),'status: ok')
    disp(model_check(model,scope,'["all"]'));error('Inspect the failed or partial edit before continuing.');
end
if complete
    check=model_check(model,scope,'["all"]');disp(check);
    assert(~contains(string(check),'severity: error'));
end
end
