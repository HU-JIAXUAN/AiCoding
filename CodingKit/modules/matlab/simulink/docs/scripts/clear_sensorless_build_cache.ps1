#requires -Version 7.0
<#
.SYNOPSIS
Removes only this build owned temporary directories, backups and compiled caches.
.EXAMPLE
pwsh -NoProfile -File ./clear_sensorless_build_cache.ps1 -WhatIf
.EXAMPLE
pwsh -NoProfile -File ./clear_sensorless_build_cache.ps1
#>
[CmdletBinding(SupportsShouldProcess = $true, ConfirmImpact = 'Medium')]
param([switch]$BackupsOnly)

$ErrorActionPreference = 'Stop'
$temporaryRoot = [System.IO.Path]::GetFullPath([System.IO.Path]::GetTempPath()).TrimEnd('\', '/')
$temporaryPrefix = $temporaryRoot + [System.IO.Path]::DirectorySeparatorChar
$ownedNames = if ($BackupsOnly) { @() } else { @(
    'sensorless-build-v3614sn0'
    'd720-49a9-6fd9-2ebf'
) }

# These exact files were generated by this run's first R2026b saves. Their
# hashes match the pre-change models; modified or unknown files are refused.
$moduleRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$modulePrefix = $moduleRoot.TrimEnd('\', '/') + [System.IO.Path]::DirectorySeparatorChar
$modelBackups = @(
    @{ Path = 'model/lib/电流环/src/CurrentLoopTest.slx.r2026a'; Hash = '3107c791960f621bfd17aef86c749f212025b6e19d80ede0fbc9a0b6f8f588e0' }
    @{ Path = 'model/lib/死区补偿/src/DeadtimeTest.slx.r2026a'; Hash = 'bf77f75012275959a3645e6d50a726c5802e8e4038331cb28694a1d5261f5185' }
    @{ Path = 'model/lib/死区补偿/src/SwitchingLegTest.slx.r2026a'; Hash = '7a57881351ad73f849f2458b10374b2105dc929bc04aee655de3989aef09efdb' }
    @{ Path = 'model/lib/离散并联PID/src/DiscretePIDTest.slx.r2026a'; Hash = 'f99e8375041bca74a34092092dc67bb4fe0206ea186207cfe0ce9f0d76f46064' }
    @{ Path = 'model/lib/电压前馈/src/FeedforwardTest.slx.r2026a'; Hash = '0ea7b4f4bdd2d1464e26338c954f4a66a2e311b471dd543656c4c76f1d201d41' }
    @{ Path = 'model/lib/逆变器/src/InverterTest.slx.r2026a'; Hash = '8f443476ca24e4dfb86f2f7b7f13605ae57097b975db05c5ee21e4210575188b' }
    @{ Path = 'model/lib/运动环/src/MotionLoopTest.slx.r2026a'; Hash = 'fb361b47416de8b89a1bfe9c67463a2fb309dc766414a6ee04cbaeebcf8a4e18' }
    @{ Path = 'model/lib/永磁同步电机/src/PMSMPlantTest.slx.r2026a'; Hash = '2e47514470555f39c81c350b29f82503da3aa1aa8a56a1c3f9c2abe0b81711e7' }
    @{ Path = 'model/lib/采样执行时序/src/TimingTest.slx.r2026a'; Hash = '4393d726cae2a20c98abf44708d289e41f99fdc3973e1100d1872c67f945182f' }
    @{ Path = 'model/app_models/Sensor/experiment/src/MotorExperiment.slx.r2026a'; Hash = 'ffb17ce844a0e7ba7182687eaea0c61264e2639cc680c16548eafee26200577c' }
)
$backupTargets = foreach ($entry in $modelBackups) {
    $candidate = [System.IO.Path]::GetFullPath((Join-Path $moduleRoot $entry.Path))
    if (-not $candidate.StartsWith($modulePrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw ('Backup target escaped the model project: {0}' -f $candidate)
    }
    if (-not (Test-Path -LiteralPath $candidate)) { continue }
    $resolved = (Resolve-Path -LiteralPath $candidate).ProviderPath
    if (-not $resolved.Equals($candidate, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw ('Resolved backup path differs from the allowlist: {0}' -f $candidate)
    }
    $item = Get-Item -LiteralPath $candidate -Force
    if ($item.PSIsContainer -or ($item.Attributes -band [System.IO.FileAttributes]::ReparsePoint)) {
        throw ('Expected an ordinary generated backup file: {0}' -f $candidate)
    }
    if ((Get-FileHash -LiteralPath $candidate -Algorithm SHA256).Hash -ne $entry.Hash) {
        throw ('Generated backup was modified; preserve it: {0}' -f $candidate)
    }
    $candidate
}

# Exact Simulink-generated caches observed in this project during this build.
$cacheRelativePaths = if ($BackupsOnly) { @() } else { @(
    'SensorlessFieldWeakeningFOC.slxc'
    'slprj/sim/varcache/SensorlessFieldWeakeningFOC/checksumOfCache.mat'
    'slprj/sim/varcache/SensorlessFieldWeakeningFOC/varInfo.mat'
    'slprj/sim/varcache/SensorlessFieldWeakeningFOC/tmwinternal/simulink_cache.xml'
) }
$cacheTargets = foreach ($relativePath in $cacheRelativePaths) {
    $candidate = [System.IO.Path]::GetFullPath((Join-Path $moduleRoot $relativePath))
    if (-not $candidate.StartsWith($modulePrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw ('Compiled cache escaped the model project: {0}' -f $candidate)
    }
    if (-not (Test-Path -LiteralPath $candidate)) { continue }
    $item = Get-Item -LiteralPath $candidate -Force
    if ($item.PSIsContainer -or ($item.Attributes -band [System.IO.FileAttributes]::ReparsePoint)) {
        throw ('Expected an ordinary generated cache file: {0}' -f $candidate)
    }
    $resolved = (Resolve-Path -LiteralPath $candidate).ProviderPath
    if (-not $resolved.Equals($candidate, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw ('Resolved cache path differs from the allowlist: {0}' -f $candidate)
    }
    $ancestor = [System.IO.Path]::GetDirectoryName($candidate)
    while ($ancestor.StartsWith($modulePrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
        if ((Get-Item -LiteralPath $ancestor -Force).Attributes -band [System.IO.FileAttributes]::ReparsePoint) {
            throw ('Cache parent is a reparse point; preserve it: {0}' -f $ancestor)
        }
        $ancestor = [System.IO.Path]::GetDirectoryName($ancestor)
    }
    $candidate
}

# An installer may still be streaming files into these directories.
$installers = @(Get-Process -Name 'mpm' -ErrorAction SilentlyContinue)
if ($installers.Count -gt 0) {
    throw 'An mpm installer is still running. Finish installation before cleanup.'
}

$targets = foreach ($ownedName in $ownedNames) {
    $candidate = [System.IO.Path]::GetFullPath((Join-Path $temporaryRoot $ownedName))
    if (-not $candidate.StartsWith($temporaryPrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw ('Target escaped the temporary directory: {0}' -f $candidate)
    }
    if ([System.IO.Path]::GetDirectoryName($candidate) -ne $temporaryRoot) {
        throw ('Target is not a direct child of the temporary directory: {0}' -f $candidate)
    }
    if (-not (Test-Path -LiteralPath $candidate)) {
        Write-Verbose ('Already absent: {0}' -f $candidate)
        continue
    }
    $item = Get-Item -LiteralPath $candidate -Force
    if (-not $item.PSIsContainer -or ($item.Attributes -band [System.IO.FileAttributes]::ReparsePoint)) {
        throw ('Expected an ordinary owned directory: {0}' -f $candidate)
    }
    $resolved = (Resolve-Path -LiteralPath $candidate).ProviderPath
    if (-not $resolved.Equals($candidate, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw ('Resolved path differs from the allowlisted target: {0}' -f $candidate)
    }
    $candidate
}

# Preserve unpublished work and the user's editable symbol-table buffer.
foreach ($target in $targets) {
    if ([System.IO.Path]::GetFileName($target) -ne 'sensorless-build-v3614sn0') { continue }
    $symbolBuffer = Join-Path $target 'symbol_table/符号定义表.md'
    $publishedSymbols = Join-Path $moduleRoot 'docs/UserDocs/符号定义表.md'
    if (Test-Path -LiteralPath $symbolBuffer -PathType Leaf) {
        if (-not (Test-Path -LiteralPath $publishedSymbols -PathType Leaf)) {
            throw 'Published symbol table is missing; preserve the editable buffer.'
        }
        $bufferHash = (Get-FileHash -LiteralPath $symbolBuffer -Algorithm SHA256).Hash
        $publishedHash = (Get-FileHash -LiteralPath $publishedSymbols -Algorithm SHA256).Hash
        if ($bufferHash -ne $publishedHash) {
            throw 'The editable symbol table differs from the published table. Publish the user revision before cleanup.'
        }
    }
    $stagedFw = Join-Path $target 'sensorless_fw_build/src/SensorlessFieldWeakeningFOC.slx'
    $publishedFw = Join-Path $moduleRoot 'model/app_models/Sensorless/sensorless_fw/src/SensorlessFieldWeakeningFOC.slx'
    if ((Test-Path -LiteralPath $stagedFw -PathType Leaf) -and
        -not (Test-Path -LiteralPath $publishedFw -PathType Leaf)) {
        throw 'Unpublished sensorless FW model is still in the temporary build directory. Preserve it until its canonical src output exists.'
    }
    $observerProof = Join-Path $moduleRoot 'model/app_models/Sensorless/sensorless_foc/waveform_analysis/extension_verification.json'
    foreach ($modelName in @('MrasSensorlessFOC', 'EkfSensorlessFOC', 'UkfSensorlessFOC', 'SigmoidSensorlessFOC')) {
        $stagedObserver = Join-Path $target ('extension_foc_build/src/{0}.slx' -f $modelName)
        if (-not (Test-Path -LiteralPath $stagedObserver -PathType Leaf)) { continue }
        $publishedObserver = Join-Path $moduleRoot ('model/app_models/Sensorless/sensorless_foc/src/{0}.slx' -f $modelName)
        if (-not (Test-Path -LiteralPath $publishedObserver -PathType Leaf) -or
            -not (Test-Path -LiteralPath $observerProof -PathType Leaf)) {
            throw ('Unpublished extension observer App remains: {0}. Preserve its build directory until its canonical model and verification record exist.' -f $modelName)
        }
        $observerRecord = Get-Content -LiteralPath $observerProof -Raw -Encoding utf8 | ConvertFrom-Json
        if ($observerRecord.status -ne 'passed') {
            throw 'Extension observer App verification has not passed. Preserve the temporary build directory.'
        }
    }
}

# A typed-code experiment must have its model/source and verification published.
foreach ($target in $targets) {
    if ([System.IO.Path]::GetFileName($target) -ne 'sensorless-build-v3614sn0') { continue }
    $stagedLibrary = Join-Path $target 'mras_typed_model/src/MrasObserver.slx'
    if (-not (Test-Path -LiteralPath $stagedLibrary -PathType Leaf)) { continue }
    $proof = Join-Path $moduleRoot 'model/lib/观测器/模型参考自适应/waveform_analysis/typed_verification.json'
    if (-not (Test-Path -LiteralPath $proof -PathType Leaf)) {
        throw 'Typed MRAS verification is unpublished. Preserve its working directory.'
    }
    $record = Get-Content -LiteralPath $proof -Raw -Encoding utf8 | ConvertFrom-Json
    if ($record.status -ne 'passed') { throw 'Typed MRAS verification has not passed.' }
    foreach ($fileName in @('MrasObserver.slx', 'mras_step.m')) {
        $staged = Join-Path $target ('mras_typed_model/src/{0}' -f $fileName)
        $published = Join-Path $moduleRoot ('model/lib/观测器/模型参考自适应/src/{0}' -f $fileName)
        if (-not (Test-Path -LiteralPath $published -PathType Leaf) -or
            (Get-FileHash -LiteralPath $staged -Algorithm SHA256).Hash -ne
            (Get-FileHash -LiteralPath $published -Algorithm SHA256).Hash) {
            throw ('Typed MRAS source/model differs from the published file: {0}' -f $fileName)
        }
    }
}

$runningCommands = @(Get-CimInstance Win32_Process |
    Where-Object { $_.Name -in @('MATLAB.exe', 'python.exe', 'pwsh.exe', 'powershell.exe') })
foreach ($target in $targets) {
    foreach ($process in $runningCommands) {
        if ($process.ProcessId -ne $PID -and $process.CommandLine -and
            $process.CommandLine.Replace('/', '\').Contains($target, [System.StringComparison]::OrdinalIgnoreCase)) {
            throw ('Process {0} is still using {1}' -f $process.ProcessId, $target)
        }
    }
}

foreach ($target in $cacheTargets) {
    if ($PSCmdlet.ShouldProcess($target, 'Remove this run-generated Simulink compiled cache')) {
        Remove-Item -LiteralPath $target -Force
        Write-Output ('Removed generated cache: {0}' -f $target)
    }
}

# Prune only these empty parents; never recurse into an unknown cache directory.
if (-not $BackupsOnly) {
    foreach ($relativePath in @(
        'slprj/sim/varcache/SensorlessFieldWeakeningFOC/tmwinternal'
        'slprj/sim/varcache/SensorlessFieldWeakeningFOC'
        'slprj/sim/varcache'
        'slprj/sim'
        'slprj'
    )) {
        $candidate = [System.IO.Path]::GetFullPath((Join-Path $moduleRoot $relativePath))
        if (-not $candidate.StartsWith($modulePrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
            throw ('Cache directory escaped the project: {0}' -f $candidate)
        }
        if (-not (Test-Path -LiteralPath $candidate -PathType Container)) { continue }
        $item = Get-Item -LiteralPath $candidate -Force
        if ($item.Attributes -band [System.IO.FileAttributes]::ReparsePoint) {
            throw ('Expected an ordinary cache directory: {0}' -f $candidate)
        }
        if (@(Get-ChildItem -LiteralPath $candidate -Force).Count -eq 0 -and
            $PSCmdlet.ShouldProcess($candidate, 'Remove empty generated cache directory')) {
            [System.IO.Directory]::Delete($candidate, $false)
        }
    }
}

foreach ($target in $backupTargets) {
    if ($PSCmdlet.ShouldProcess($target, 'Remove this run-generated verified model backup')) {
        Remove-Item -LiteralPath $target -Force
        Write-Output ('Removed generated backup: {0}' -f $target)
    }
}

foreach ($target in $targets) {
    $files = @(Get-ChildItem -LiteralPath $target -Recurse -Force -File)
    $bytes = ($files | Measure-Object -Property Length -Sum).Sum
    Write-Output ('Owned cache: {0}; files: {1}; bytes: {2}' -f $target, $files.Count, $bytes)
    if ($PSCmdlet.ShouldProcess($target, 'Remove this run-owned temporary directory')) {
        Remove-Item -LiteralPath $target -Recurse -Force
        Write-Output ('Removed: {0}' -f $target)
    }
}

# Keep the existing project inventory consistent after removing generated files.
$manifestPath = Join-Path $moduleRoot 'MANIFEST.json'
if (Test-Path -LiteralPath $manifestPath -PathType Leaf) {
    $manifest = Get-Content -LiteralPath $manifestPath -Raw -Encoding utf8 | ConvertFrom-Json
    $fileCount = @(Get-ChildItem -LiteralPath $moduleRoot -Recurse -Force -File).Count
    $directoryCount = 1 + @(Get-ChildItem -LiteralPath $moduleRoot -Recurse -Force -Directory).Count
    $readmeCount = @(Get-ChildItem -LiteralPath $moduleRoot -Recurse -Force -File -Filter 'README.md').Count
    if (($manifest.file_count -ne $fileCount -or $manifest.directory_count -ne $directoryCount -or
        $manifest.readmes -ne $readmeCount) -and
        $PSCmdlet.ShouldProcess($manifestPath, 'Refresh derived project inventory after cleanup')) {
        $manifest.file_count = $fileCount
        $manifest.directory_count = $directoryCount
        $manifest.readmes = $readmeCount
        $content = ($manifest | ConvertTo-Json -Depth 20) + [System.Environment]::NewLine
        [System.IO.File]::WriteAllText($manifestPath, $content, [System.Text.UTF8Encoding]::new($false))
    }
}

