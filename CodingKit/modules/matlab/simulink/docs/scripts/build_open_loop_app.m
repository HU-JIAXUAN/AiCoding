function build_open_loop_app(kind,outputModule)
%BUILD_OPEN_LOOP_APP Linked physical I-f or V/f assembly; no rotor feedback.
assert(strcmp(version('-release'),'2026b'));gate=library.settingsLookup();assert(gate.gatePass);
spec=open_loop_app_spec(kind);module=spec.module;model=spec.model;
if nargin<2,outputModule=module;end
if ~isfolder(fullfile(module,'src')),mkdir(fullfile(module,'src'));end
addpath(fullfile(module,'parameter'),fullfile(module,'build_process'));initialize_motor_paths();
assert(~bdIsLoaded(model)&&~isfile(fullfile(outputModule,'src',[model '.slx'])),'Build in a fresh directory.');
for name={'OpenLoopDrive','CurrentControl','ClarkePark','Inverter','PMSMBridgeBusPlant'}
    load_system(name{1});read=model_read(name{1},'root','0');assert(startsWith(strtrim(string(read)),'status: ok'));
end
new_system(model);feval(['initialize_' kind '_app'],model);
callback=sprintf('addpath(fullfile(fileparts(get_param(bdroot,''FileName'')),''..'',''build_process''));initialize_%s_app(bdroot);',kind);
ops={struct('op','configure','target',['config:' model],'params',struct('Solver','FixedStepDiscrete','SolverType','Fixed-step','FixedStep','experimentCfg.Step', ...
    'StopTime','experimentCfg.Duration','ReturnWorkspaceOutputs','on','PostLoadFcn',callback)), ...
    b('FromWorkspace','Stimulus',struct('VariableName','testStim','Interpolate','off','SampleTime','currentCfg.Ts','OutputAfterFinalValue','Holding final value')), ...
    b('Demux','Inputs',struct('Outputs','5')),lib('OpenLoopDrive','Reference','Command',struct('MaskValueString','openLoopCfg')), ...
    lib('PMSMBridgeBusPlant','BridgeBusMotor','Plant',struct('MaskValueString','bridgeCfg')), ...
    b('Constant','OffMode',struct('Value','0')),b('Constant','Zero',struct('Value','0')), ...
    b('Sum','BridgeMode',struct('Inputs','++')),b('DotProduct','CurrentSquared',struct()),b('Sqrt','CurrentMagnitude',struct()), ...
    b('DotProduct','TerminalSquared',struct()),b('Sqrt','TerminalMagnitude',struct()), ...
    b('ZeroOrderHold','CurrentSample',struct('SampleTime','currentCfg.Ts')), ...
    b('ZeroOrderHold','ProtectionSample',struct('SampleTime','currentCfg.Ts')),b('ZeroOrderHold','TerminalSample',struct('SampleTime','currentCfg.Ts')), ...
    struct('op','create_subsystem','name','VoltageStage','ref','VoltageStage','interface',struct('inputs',{{}},'outputs',{{}}))};
if strcmp(kind,'if')
    ops{end+1}=struct('op','create_subsystem','name','CurrentLoop','ref','CurrentLoop','interface',struct('inputs',{{}},'outputs',{{}}));
    ops=[ops,{b('Gain','VoltageRequest',struct('Gain','1')),b('Gain','CurrentDQ',struct('Gain','1'))}];
else
    ops=[ops,{b('Mux','VoltageReference',struct('Inputs','2')),lib('ClarkePark','Park','MeasuredPark',struct()), ...
        b('Demux','CurrentChannels',struct('Outputs','2')),b('Mux','CurrentDQ',struct('Inputs','2')), ...
        b('Gain','VoltageRequest',struct('Gain','1'))}];
end
edit(model,'root',ops,false);ids=scopeIds(model,model);
scope=ids.VoltageStage;
ops=interfaces({'request_dq','theta','bus'},{'duty','limited_dq','residual','scale'});
ops=[ops,{b('Product','Normalize',struct('Inputs','*/')),lib('CurrentControl','VoltageLimit','VoltageCircle',struct()), ...
    b('Product','RestoreVolts',struct('Inputs','**')),b('Sum','Residual',struct('Inputs','+-')), ...
    b('Demux','DQChannels',struct('Outputs','2')),lib('ClarkePark','InversePark','InversePark',struct()), ...
    lib('Inverter','SVPWM','Modulator',struct()),b('Mux','DutyABC',struct('Inputs','3')),b('Terminator','CommonMode',struct()), ...
    c('#request_dq.y1','#Normalize.u1'),c('#bus.y1','#Normalize.u2'),c('#Normalize.y1','#VoltageCircle.u1'), ...
    c('#VoltageCircle.y1','#RestoreVolts.u1'),c('#bus.y1','#RestoreVolts.u2'),c('#RestoreVolts.y1','#limited_dq.u1'), ...
    c('#RestoreVolts.y1','#Residual.u1'),c('#request_dq.y1','#Residual.u2'),c('#Residual.y1','#residual.u1'), ...
    c('#VoltageCircle.y2','#scale.u1'),c('#VoltageCircle.y1','#DQChannels.u1'), ...
    c('#DQChannels.y1','#InversePark.u1'),c('#DQChannels.y2','#InversePark.u2'),c('#theta.y1','#InversePark.u3'), ...
    c('#InversePark.y1','#Modulator.u1'),c('#InversePark.y2','#Modulator.u2'),c('#Modulator.y4','#CommonMode.u1'),c('#DutyABC.y1','#duty.u1')}];
for k=1:3,ops{end+1}=c(sprintf('#Modulator.y%d',k),sprintf('#DutyABC.u%d',k));end
edit(model,scope,ops,true);
if strcmp(kind,'if')
    scope=ids.CurrentLoop;ops=interfaces({'current_ab','theta','amplitude','enable','reset','residual'},{'request_dq','measured_dq','reference_dq','error_dq','integral'});
    ops=[ops,{b('Demux','CurrentChannels',struct('Outputs','2')),lib('ClarkePark','Park','MeasuredPark',struct()), ...
        b('Mux','MeasuredDQ',struct('Inputs','2')),b('Mux','ReferenceDQ',struct('Inputs','2')),b('Constant','Zero',struct('Value','0')), ...
        b('Sum','Error',struct('Inputs','+-')),lib('CurrentControl','TrackingPI','CurrentPI',struct()), ...
        c('#current_ab.y1','#CurrentChannels.u1'),c('#CurrentChannels.y1','#MeasuredPark.u1'),c('#CurrentChannels.y2','#MeasuredPark.u2'), ...
        c('#theta.y1','#MeasuredPark.u3'),c('#MeasuredPark.y1','#MeasuredDQ.u1'),c('#MeasuredPark.y2','#MeasuredDQ.u2'), ...
        c('#amplitude.y1','#ReferenceDQ.u1'),c('#Zero.y1','#ReferenceDQ.u2'),c('#ReferenceDQ.y1','#Error.u1'),c('#MeasuredDQ.y1','#Error.u2'), ...
        c('#Error.y1','#CurrentPI.u1'),c('#residual.y1','#CurrentPI.u2'),c('#enable.y1','#CurrentPI.u3'),c('#reset.y1','#CurrentPI.u4'), ...
        c('#CurrentPI.y1','#request_dq.u1'),c('#MeasuredDQ.y1','#measured_dq.u1'),c('#ReferenceDQ.y1','#reference_dq.u1'), ...
        c('#Error.y1','#error_dq.u1'),c('#CurrentPI.y2','#integral.u1')}];edit(model,scope,ops,true);
    ops={c([ids.CurrentLoop '.y1'],[ids.VoltageRequest '.u1']),c([ids.CurrentLoop '.y2'],[ids.CurrentDQ '.u1'])};
else,ops={};end
ops=[ops,{c([ids.Inputs '.y1'],[ids.Command '.u1']),c([ids.Inputs '.y2'],[ids.Command '.u2']),c([ids.Inputs '.y3'],[ids.Command '.u3']), ...
    c([ids.Inputs '.y5'],[ids.Command '.u6']),c([ids.CurrentMagnitude '.y1'],[ids.ProtectionSample '.u1']),c([ids.ProtectionSample '.y1'],[ids.Command '.u4']), ...
    c([ids.TerminalMagnitude '.y1'],[ids.TerminalSample '.u1']),c([ids.TerminalSample '.y1'],[ids.Command '.u5']),c([ids.Plant '.y1'],[ids.CurrentSample '.u1']), ...
    c([ids.Plant '.y1'],[ids.CurrentSquared '.u1']),c([ids.Plant '.y1'],[ids.CurrentSquared '.u2']),c([ids.CurrentSquared '.y1'],[ids.CurrentMagnitude '.u1']), ...
    c([ids.Plant '.y4'],[ids.TerminalSquared '.u1']),c([ids.Plant '.y4'],[ids.TerminalSquared '.u2']),c([ids.TerminalSquared '.y1'],[ids.TerminalMagnitude '.u1']), ...
    c([ids.Stimulus '.y1'],[ids.Inputs '.u1']),c([ids.OffMode '.y1'],[ids.BridgeMode '.u1']),c([ids.Command '.y4'],[ids.BridgeMode '.u2']), ...
    c([ids.BridgeMode '.y1'],[ids.Plant '.u2']),c([ids.Inputs '.y4'],[ids.Plant '.u3']),c([ids.Inputs '.y5'],[ids.Plant '.u4']), ...
    c([ids.VoltageStage '.y1'],[ids.Plant '.u1']),c([ids.VoltageRequest '.y1'],[ids.VoltageStage '.u1']), ...
    c([ids.Command '.y1'],[ids.VoltageStage '.u2']),c([ids.Inputs '.y5'],[ids.VoltageStage '.u3'])}];
if strcmp(kind,'if')
    ops=[ops,{c([ids.CurrentSample '.y1'],[ids.CurrentLoop '.u1']),c([ids.Command '.y1'],[ids.CurrentLoop '.u2']),c([ids.Command '.y3'],[ids.CurrentLoop '.u3']), ...
        c([ids.Command '.y4'],[ids.CurrentLoop '.u4']),c([ids.Inputs '.y3'],[ids.CurrentLoop '.u5']),c([ids.VoltageStage '.y3'],[ids.CurrentLoop '.u6'])}];
else
    ops=[ops,{c([ids.Zero '.y1'],[ids.VoltageReference '.u1']),c([ids.Command '.y3'],[ids.VoltageReference '.u2']), ...
        c([ids.VoltageReference '.y1'],[ids.VoltageRequest '.u1']),c([ids.CurrentSample '.y1'],[ids.CurrentChannels '.u1']), ...
        c([ids.CurrentChannels '.y1'],[ids.MeasuredPark '.u1']),c([ids.CurrentChannels '.y2'],[ids.MeasuredPark '.u2']),c([ids.Command '.y1'],[ids.MeasuredPark '.u3']), ...
        c([ids.MeasuredPark '.y1'],[ids.CurrentDQ '.u1']),c([ids.MeasuredPark '.y2'],[ids.CurrentDQ '.u2'])}];
end
% All unused physical outputs are intentionally terminated.
for k=[3,9,14,15,16],name=['UnusedPlant' num2str(k)];ops=[ops,{b('Terminator',name,struct()),c(sprintf('%s.y%d',ids.Plant,k),['#' name '.u1'])}];end
if strcmp(kind,'if'),ops=[ops,{b('Terminator','UnusedZero',struct()),c([ids.Zero '.y1'],'#UnusedZero.u1')}];end
edit(model,'root',ops,false);ids=scopeIds(model,model);
defs=open_loop_app_channels(kind);ops={b('Mux','Trace',struct('Inputs',num2str(size(defs,1)))), ...
    b('ToWorkspace','SaveTrace',struct('VariableName','app_trace','SaveFormat','Structure With Time','SampleTime','currentCfg.Ts','MaxDataPoints','inf')), ...
    b('Mux','PhysicalTrace',struct('Inputs','4')),b('ToWorkspace','SavePhysical',struct('VariableName','physical_trace','SaveFormat','Structure With Time','SampleTime','bridgeCfg.Ts','MaxDataPoints','inf')), ...
    b('Gain','SynchronousSpeed',struct('Gain','2*pi/motorCfg.PolePairs')),b('Sum','AngleDifference',struct('Inputs','+-')), ...
    b('Trigonometry','AngleSin',struct('Operator','sin')),b('Trigonometry','AngleCos',struct('Operator','cos')),b('Trigonometry','PhaseDifference',struct('Operator','atan2')), ...
    c('#Trace.y1','#SaveTrace.u1'),c('#PhysicalTrace.y1','#SavePhysical.u1'),c([ids.Command '.y2'],'#SynchronousSpeed.u1'), ...
    c([ids.Command '.y1'],'#AngleDifference.u1'),c([ids.Plant '.y6'],'#AngleDifference.u2'),c('#AngleDifference.y1','#AngleSin.u1'),c('#AngleDifference.y1','#AngleCos.u1'), ...
    c('#AngleSin.y1','#PhaseDifference.u1'),c('#AngleCos.y1','#PhaseDifference.u2'), ...
    c([ids.CurrentMagnitude '.y1'],'#PhysicalTrace.u1'),c([ids.Plant '.y5'],'#PhysicalTrace.u2'),c([ids.Plant '.y7'],'#PhysicalTrace.u3'),c([ids.Plant '.y13'],'#PhysicalTrace.u4')};
for k=1:size(defs,1),ops{end+1}=c(resolve(defs{k,3},ids),sprintf('#Trace.u%d',k));end
groups={'SpeedScope',{[ids.Command '.y2'],'#SynchronousSpeed.y1',[ids.Plant '.y5']}; ...
    'AngleScope',{[ids.Command '.y1'],[ids.Plant '.y6'],'#PhaseDifference.y1'}; ...
    'CurrentScope',{[ids.Plant '.y1'],[ids.CurrentDQ '.y1'],[ids.CurrentMagnitude '.y1']}; ...
    'VoltageScope',{[ids.VoltageRequest '.y1'],[ids.VoltageStage '.y2'],[ids.Plant '.y4'],[ids.VoltageStage '.y4']}; ...
    'DutyScope',{[ids.VoltageStage '.y1'],[ids.BridgeMode '.y1']}; ...
    'StatusScope',{[ids.Inputs '.y2'],[ids.Inputs '.y3'],[ids.Command '.y4'],[ids.Command '.y5'],[ids.Command '.y6'],[ids.Command '.y8']}; ...
    'ObservationScope',{[ids.CurrentMagnitude '.y1'],[ids.TerminalMagnitude '.y1'],[ids.Command '.y7']}; ...
    'AmplitudeScope',{[ids.Command '.y3'],[ids.Command '.y2']}};
if strcmp(kind,'if'),groups=[groups;{'CurrentTrackingScope',{[ids.CurrentLoop '.y3'],[ids.CurrentLoop '.y2'],[ids.CurrentLoop '.y4'],[ids.CurrentLoop '.y5']}}];end
for k=1:size(groups,1)
    name=groups{k,1};sources=groups{k,2};mux=[name 'Channels'];
    ops=[ops,{b('Mux',mux,struct('Inputs',num2str(numel(sources)))),b('Scope',name,struct('NumInputPorts','1')),c(['#' mux '.y1'],['#' name '.u1'])}];
    for j=1:numel(sources),ops{end+1}=c(sources{j},sprintf('#%s.u%d',mux,j));end
end
edit(model,'root',ops,true);
if ~isfolder(fullfile(outputModule,'src')),mkdir(fullfile(outputModule,'src'));end
save_system(model,fullfile(outputModule,'src',[model '.slx']));
print(['-s' model],'-dpng',fullfile(module,'build_process','model_diagram.png'));close_system(model,0);
fprintf('BUILT %s\n',model);
end
function result=edit(model,scope,ops,complete),result=open_loop_model_edit(model,scope,ops,complete,'full');end
function op=b(type,name,params),op=struct('op','add_block','type',type,'name',name,'ref',name,'params',params);end
function op=lib(model,export,name,params)
blocks=find_system(model,'SearchDepth',1,'Type','Block','Name',export);assert(isscalar(blocks));
op=struct('op','add_block','type',export,'ReferenceBlock',blocks{1},'name',name,'ref',name,'params',params);
end
function op=c(a,b),op=struct('op','connect','target',[a ' -> ' b]);end
function ops=interfaces(ins,outs)
ops={};for k=1:numel(ins),ops{end+1}=b('Inport',ins{k},struct('Port',num2str(k)));end
for k=1:numel(outs),ops{end+1}=b('Outport',outs{k},struct('Port',num2str(k)));end
end
function ids=scopeIds(model,scope)
blocks=find_system(scope,'SearchDepth',1,'Type','Block');ids=struct();
for k=1:numel(blocks),if strcmp(blocks{k},scope),continue;end;ids.(get_param(blocks{k},'Name'))=['blk_' extractAfter(Simulink.ID.getSID(blocks{k}),':')];end
end
function source=resolve(source,ids)
token=regexp(source,'^#(\w+)(\.\w+)$','tokens');assert(isscalar(token));source=[ids.(token{1}{1}) token{1}{2}];
end
